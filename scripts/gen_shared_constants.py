"""Generate frontend constants whose source of truth is the Python package.

Writes ``frontend/src/lib/generated/jinjaContext.gen.ts`` from
:mod:`autoair.validation.jinja` (the context variables that need a logical date), so the
editor warning and the server-side validation report the same names::

    uv run python scripts/gen_shared_constants.py           # write the file
    uv run python scripts/gen_shared_constants.py --check   # exit 1 when the file is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PRINT_WIDTH = 120
SCRIPT = Path(__file__).name
OUT = ROOT / "frontend" / "src" / "lib" / "generated" / "jinjaContext.gen.ts"


def _array(name: str, doc: str, values: tuple[str, ...]) -> list[str]:
    # Prettier's layout (print width 120): one line when it fits.
    one_line = f"export const {name} = [{', '.join(json.dumps(v) for v in values)}] as const;"
    if len(one_line) <= PRINT_WIDTH:
        return [f"/** {doc} */", one_line]
    lines = [f"/** {doc} */", f"export const {name} = ["]
    lines += [f"  {json.dumps(v)}," for v in values]
    lines.append("] as const;")
    return lines


def render() -> str:
    from autoair.validation.jinja import DAG_RUN_LOGICAL_DATE_ATTRS, LOGICAL_DATE_NAMES

    lines = [
        f"// Generated by scripts/{SCRIPT} from autoair.validation.jinja. Do not edit.",
        "",
        *_array(
            "LOGICAL_DATE_NAMES",
            "Airflow 3 context variables that are undefined for runs without a logical date.",
            LOGICAL_DATE_NAMES,
        ),
        "",
        *_array(
            "DAG_RUN_LOGICAL_DATE_ATTRS",
            "`dag_run` attributes that are None for runs without a logical date.",
            DAG_RUN_LOGICAL_DATE_ATTRS,
        ),
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current != text:
            print(
                f"{OUT.relative_to(ROOT)} is stale: run uv run python scripts/{SCRIPT}",
                file=sys.stderr,
            )
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
