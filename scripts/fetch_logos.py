"""Download provider integration logos and bundle them as small canvas icons.

Every Airflow provider declares a logo per integration in its metadata
(``/docs/integration-logos/S3.png``); the files live in the Apache Airflow repository under
``providers/<path>/docs/integration-logos/``. This script reads the metadata of every installed
provider (run it from an environment with all providers, e.g. ``.venv-allproviders``),
downloads the logos, scales raster images to 64 px (crisp at 32 px on HiDPI) and keeps SVGs
as they are, then writes ``src/autoair/resources/logos/`` + ``manifest.json``:

    .venv-allproviders/bin/python scripts/fetch_logos.py

Logos are trademarks of their owners; they are used, as in Airflow's own documentation, to
identify the integration an operator talks to.
"""

from __future__ import annotations

import io
import json
import re
import sys
import urllib.error
import urllib.request
from importlib.metadata import distributions
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "autoair" / "resources" / "logos"
RAW = "https://raw.githubusercontent.com/apache/airflow/main/providers/{path}{logo}"
SIZE = 64
# Integrations without an Airflow provider (TaskFlow nodes, popular community packages).
# Kept in the repository: our own artwork and CC0 Simple Icons logos (brand-coloured).
LOCAL_EXTRA = {"bash": "bash.svg", "gitlab": "gitlab.svg", "vespa": "vespa.svg"}
EXTRA = {"python": "https://upload.wikimedia.org/wikipedia/commons/c/c3/Python-logo-notext.svg"}


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def fetch(url: str) -> bytes | None:
    try:
        if not url.startswith("https://"):
            return None
        req = urllib.request.Request(url, headers={"User-Agent": "autoair-logo-fetch/1.0"})  # noqa: S310
        with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310 - fixed https hosts
            return bytes(resp.read())
    except (urllib.error.URLError, TimeoutError):
        return None


def save(data: bytes, name: str, url: str) -> str | None:
    """Write ``data`` as ``name``.png (scaled, transparent padding) or ``name``.svg."""
    if url.lower().endswith(".svg") or data.lstrip()[:5] in (b"<?xml", b"<svg "):
        text = data.decode("utf-8", "replace")
        if "<script" in text.lower() or "javascript:" in text.lower():
            return None  # never bundle active content
        (OUT / f"{name}.svg").write_text(text)
        return f"{name}.svg"
    try:
        img = Image.open(io.BytesIO(data))
        img.load()
    except Exception:
        return None
    img = img.convert("RGBA")
    bbox = img.getbbox()  # trim transparent borders so small logos fill the icon
    if bbox:
        img = img.crop(bbox)
    img.thumbnail((SIZE, SIZE), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    canvas.paste(img, ((SIZE - img.width) // 2, (SIZE - img.height) // 2), img)
    # 256-colour palette (alpha kept): ~half the size, indistinguishable at icon size.
    small = canvas.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
    small.save(OUT / f"{name}.png", optimize=True)
    return f"{name}.png"


def provider_infos() -> list[dict]:
    infos: list[dict] = []
    for dist in distributions():
        for ep in dist.entry_points:
            if ep.group == "apache_airflow_provider":
                try:
                    infos.append(ep.load()())
                except Exception as exc:  # pragma: no cover - broken provider
                    print(f"skip {dist.name}: {exc}", file=sys.stderr)
    return infos


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    manifest: dict[str, dict[str, str]] = {
        "integrations": {},
        "providers": {},
        "extra": {},
        # Concept glyphs generated by frontend/scripts/make_glyph_logos.mjs.
        "glyphs": {p.stem.removeprefix("glyph-"): p.name for p in sorted(OUT.glob("glyph-*.svg"))},
    }
    downloaded: dict[str, str] = {}  # url -> file
    for info in sorted(provider_infos(), key=lambda i: i.get("package-name", "")):
        package = info.get("package-name", "")
        if not package.startswith("apache-airflow-providers-"):
            continue
        path = package.removeprefix("apache-airflow-providers-").replace("-", "/")
        for integ in info.get("integrations", []) or []:
            logo = integ.get("logo")
            name = integ.get("integration-name")
            if not logo or not name:
                continue
            url = RAW.format(path=path, logo=logo)
            if url not in downloaded:
                data = fetch(url)
                file = save(data, slug(Path(logo).stem), url) if data else None
                if file is None:
                    print(f"missing {url}", file=sys.stderr)
                    continue
                downloaded[url] = file
            manifest["integrations"][name] = downloaded[url]
            manifest["providers"].setdefault(package, downloaded[url])
    # Our own artwork kept in the repository (no upstream logo).
    for key, file in LOCAL_EXTRA.items():
        if (OUT / file).exists():
            manifest["extra"][key] = file
    for key, url in EXTRA.items():
        data = fetch(url)
        file = save(data, key, url) if data else None
        if file:
            manifest["extra"][key] = file
        else:
            print(f"missing extra {key}: {url}", file=sys.stderr)
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    files = list(OUT.glob("*.png")) + list(OUT.glob("*.svg"))
    total = sum(f.stat().st_size for f in files)
    print(
        f"{len(manifest['integrations'])} integrations, {len(manifest['providers'])} providers, "
        f"{len(manifest['extra'])} extra → {len(files)} files, {total // 1024} KB"
    )


if __name__ == "__main__":
    main()
