"""Shared models, errors and helpers for every deploy target.

A *deploy target* is where AutoAir persists ``<dag_id>.autoair.json`` (the spec) next to
the rendered DAG file(s): a local folder, an object store (fsspec) or a git repository.

Ownership rules shared by all targets:

* files that do not carry an AutoAir marker are never overwritten or deleted;
* files whose content differs from what AutoAir last wrote are considered *ejected*
  (hand edited) and are only overwritten with ``force=True``;
* the spec is written first, the DAG file(s) after it (the loader stub reads the spec),
  and a failed write leaves everything as it was;
* a state record (``.autoair/state/<dag_id>.json``) that cannot be read fails closed: no
  file is replaced or deleted until it is fixed; a missing one makes existing files
  *unknown* (replaced only with ``force``).
"""

from __future__ import annotations

import builtins
import datetime
import hashlib
import inspect
import json
import re
from typing import Any, Literal, Protocol, runtime_checkable

from pydantic import BaseModel, Field, ValidationError

from autoair.loader import SPEC_SUFFIX, render_stub
from autoair.spec import DagSpec
from autoair.spec.models import KEY_RE

GENERATED_MARKER = "Generated by AutoAir"
STUB_MARKER = "AutoAir loader stub"
STATE_DIR = ".autoair/state"
HISTORY_DIR = ".autoair/history"
DEFAULT_HISTORY_LIMIT = 100
_VERSION_RE = re.compile(r"^[A-Za-z0-9_.-]{1,200}$")

TargetKind = Literal["local", "object", "git"]


# --------------------------------------------------------------------------- errors


def environment_kwargs(method: Any, environment: str | None) -> dict[str, Any]:
    """``{"environment": environment}`` when the target method ``method`` reads per
    environment (git targets map environments to branches); ``{}`` otherwise."""
    if environment is None:
        return {}
    try:
        params = inspect.signature(method).parameters
    except (TypeError, ValueError):
        return {}
    return {"environment": environment} if "environment" in params else {}


class StorageError(Exception):
    """Generic persistence failure (bad id, foreign file, backend error...)."""


class AuthError(StorageError):
    """The git host or remote rejected the credentials (HTTP 401/403, git auth failure).

    Git targets whose credentials come from an Airflow connection re-read the connection
    and retry once (a rotated token works without a restart)."""

    @property
    def status(self) -> int:
        """403 when the host said the credentials lack access (scopes, permissions), else
        401 (unknown or refused credentials)."""
        return 403 if re.search(r"\b403\b", str(self)) else 401


class NotFoundError(StorageError):
    """The requested spec or version does not exist."""


class ConflictError(StorageError):
    """Optimistic-locking failure: the stored spec changed since ``base_etag`` was read."""

    def __init__(self, current: StoredSpec | None, message: str | None = None) -> None:
        self.current = current
        super().__init__(
            message
            or (
                "the spec was changed by someone else since it was loaded"
                if current is not None
                else "the spec was deleted or moved since it was loaded"
            )
        )


class WriteLeaseLost(ConflictError):
    """This writer's lease on a DAG expired and another writer took it over mid-save. The
    new holder's writes are authoritative: nothing may be restored over them."""


class EjectedError(StorageError):
    """A generated file was edited by hand since AutoAir last wrote it."""

    def __init__(self, path: str) -> None:
        self.path = path
        super().__init__(
            f"{path} was modified outside AutoAir (ejected); "
            "save with force=True to overwrite the manual changes"
        )


# --------------------------------------------------------------------------- models


class SpecSummary(BaseModel):
    dag_id: str
    output_mode: str
    display_name: str | None = None
    description: str | None = None
    tags: list[str] = []
    task_count: int
    updated_at: datetime.datetime
    dag_file: str
    etag: str | None = None
    document_type: Literal["spec", "raw"] = Field(
        default="spec",
        description="spec: built in the visual editor (generated code); raw: a raw code DAG "
        "(hand-written file, DagSpec.raw_code).",
    )


class StoredSpec(BaseModel):
    """A spec as currently persisted, with its optimistic-locking token."""

    spec: DagSpec
    etag: str = Field(description="sha256 of the canonical spec JSON.")
    version: str | None = Field(
        default=None, description="Commit sha / history id of the stored spec."
    )
    pending_branch: str | None = Field(
        default=None, description="Git PR mode: branch holding unmerged changes for this DAG."
    )
    pending_pr_url: str | None = None


class SaveResult(BaseModel):
    path: str = Field(description="Path or URL of the main DAG file.")
    etag: str
    version: str | None = None
    pr_url: str | None = None
    branch: str | None = None
    message: str


class VersionInfo(BaseModel):
    version: str
    timestamp: datetime.datetime | None = None
    author: str | None = None
    message: str | None = None
    etag: str | None = None


class TargetStatus(BaseModel):
    kind: TargetKind
    location: str
    writable: bool
    details: dict[str, Any] = Field(default_factory=dict)


class DagState(BaseModel):
    """Bookkeeping AutoAir keeps per DAG (``.autoair/state/<dag_id>.json``)."""

    dag_id: str
    etag: str
    version: str | None = None
    files: dict[str, str] = Field(
        default_factory=dict, description="Generated file name -> sha256 of its content."
    )
    updated_at: datetime.datetime | None = None
    author: str | None = None
    environment: str | None = None
    source_sha: str | None = Field(
        default=None,
        description="sha256 of the spec's source.code (the hand-written file) when it was "
        "deployed: a later deploy with the same code patches the target's file, a new "
        "code (an import, an edit in the code mode) patches that code instead.",
    )
    hand_written: bool = Field(
        default=False,
        description="The DAG file is a hand-written file AutoAir keeps (written by a "
        "source-preserving deploy or taken over as a raw code DAG), not a generated one: "
        "regenerating or deleting it needs 'deploy:overwrite_ejected'.",
    )


class ExistingFile(BaseModel):
    """The DAG file currently in a deploy target, with what AutoAir recorded about it."""

    name: str
    content: str
    location: str
    recorded_sha: str | None = Field(
        default=None, description="sha256 AutoAir recorded when it last wrote the file."
    )
    source_sha: str | None = Field(default=None, description="DagState.source_sha.")
    hand_written: bool = Field(default=False, description="DagState.hand_written.")


def hand_written_refusal(location: str) -> str:
    return (
        f"{location} is a hand-written DAG file AutoAir keeps for this DAG; deleting it "
        "needs the AutoAir permission 'deploy:overwrite_ejected', replacing it also "
        "preserve.allow_force_overwrite"
    )


class HandWrittenError(StorageError):
    """A write or delete would replace the hand-written DAG file AutoAir keeps for a DAG
    without the caller being allowed to (``allow_hand_written``)."""

    def __init__(self, path: str) -> None:
        self.path = path
        super().__init__(hand_written_refusal(path))


def source_sha(spec: DagSpec) -> str | None:
    code = spec.source.code if spec.source is not None else None
    return sha256_text(code) if code is not None else None


# --------------------------------------------------------------------------- protocols


class DagRepository(Protocol):
    """Spec-level storage (list, get, save, delete) used by the MCP tools."""

    def list(self) -> list[SpecSummary]: ...
    def get(self, dag_id: str) -> DagSpec | None: ...
    def save(self, spec: DagSpec, python_source: str | None) -> Any: ...
    def delete(self, dag_id: str) -> bool: ...


@runtime_checkable
class DeployTarget(Protocol):
    """Where specs and generated DAG files are persisted."""

    kind: TargetKind

    def list(self) -> list[SpecSummary]: ...
    def get(self, dag_id: str) -> StoredSpec | None: ...
    def save(
        self,
        spec: DagSpec,
        files: dict[str, str],
        *,
        base_etag: str | None = None,
        author: str | None = None,
        message: str | None = None,
        environment: str | None = None,
        force: bool = False,
    ) -> SaveResult: ...
    def delete(
        self, dag_id: str, *, base_etag: str | None = None, author: str | None = None
    ) -> bool: ...
    def history(self, dag_id: str, limit: int = 50) -> builtins.list[VersionInfo]: ...
    def get_version(self, dag_id: str, version: str) -> DagSpec: ...
    def status(self) -> TargetStatus: ...


# --------------------------------------------------------------------------- helpers


def utcnow() -> datetime.datetime:
    return datetime.datetime.now(tz=datetime.timezone.utc)


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def canonical_json(spec: DagSpec) -> str:
    data = spec.model_dump(mode="json", by_alias=True, exclude_none=True)
    return json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def spec_etag(spec: DagSpec) -> str:
    return sha256_text(canonical_json(spec))


def serialize_spec(spec: DagSpec) -> str:
    """The on-disk form of ``<dag_id>.autoair.json``."""
    return spec.model_dump_json(indent=2, exclude_none=True, by_alias=True) + "\n"


def check_dag_id(dag_id: str) -> str:
    if not KEY_RE.fullmatch(dag_id) or dag_id.startswith(".") or len(dag_id) > 250:
        raise StorageError(f"invalid dag_id {dag_id!r}")
    return dag_id


def check_version(version: str) -> str:
    if not _VERSION_RE.fullmatch(version) or version.startswith("."):
        raise StorageError(f"invalid version {version!r}")
    return version


def spec_filename(dag_id: str) -> str:
    return f"{check_dag_id(dag_id)}{SPEC_SUFFIX}"


def check_files(dag_id: str, files: dict[str, str]) -> None:
    """Generated file names must be flat ``<dag_id>.<ext>`` names next to the spec."""
    if not files:
        raise StorageError("at least one generated DAG file is required")
    for name in files:
        if (
            not name.startswith(f"{dag_id}.")
            or "/" in name
            or "\\" in name
            or name == spec_filename(dag_id)
            or not KEY_RE.fullmatch(name)
        ):
            raise StorageError(f"invalid generated file name {name!r} for DAG {dag_id!r}")


def is_owned(content: str) -> bool:
    head = content[:500]
    return GENERATED_MARKER in head or STUB_MARKER in head


def parse_state(raw: str | None, location: str, dag_id: str) -> DagState | None:
    """``raw`` state record of ``dag_id`` for a write; ``None`` when there is none. An
    unreadable record raises: it is the only place that says which files are hand-written
    or were edited by hand, so a write must not guess (fail closed)."""
    if raw is None:
        return None
    try:
        state = DagState.model_validate_json(raw)
    except ValueError as exc:
        reason = exc.errors()[0]["msg"] if isinstance(exc, ValidationError) else str(exc)
        raise StorageError(
            f"AutoAir's state record {location} is unreadable ({reason}); no file of DAG "
            f"{dag_id!r} is replaced or deleted until it is fixed. Restore it (version "
            "control, a backup) or delete it: the DAG's files then count as unknown and are "
            "replaced only by a deploy with force"
        ) from exc
    if state.dag_id != dag_id:
        raise StorageError(
            f"AutoAir's state record {location} belongs to DAG {state.dag_id!r}, not "
            f"{dag_id!r}; restore or delete it"
        )
    return state


def check_overwrite(
    location: str,
    existing: str | None,
    recorded: str | None,
    new_sha: str | None,
    force: bool,
    expected: str | None = None,
    *,
    unknown: bool = False,
) -> None:
    """Refuse to clobber foreign files and (unless ``force``) hand-edited generated ones.

    ``recorded`` is the sha256 AutoAir stored when it last wrote the file; ``new_sha`` the
    hash of the content about to be written (``None`` when deleting). ``expected``: the
    hash of the file a source-preserving deploy patched -- the write goes ahead (also over a
    hand-written file) only while the file is still exactly that one. ``unknown``: there is
    no state record, so nobody knows whether the file was edited by hand: it is replaced or
    deleted only with ``force`` (unless the new content is identical).
    """
    if existing is None:
        return
    if expected is not None:
        if sha256_text(existing) == expected:
            return
        raise EjectedError(location)
    current_sha = sha256_text(existing)
    if not is_owned(existing):
        # A hand-written file (also one a source-preserving deploy wrote before) is only
        # ever replaced through ``expected``: a deliberate, permission-checked write.
        raise StorageError(
            f"{location} exists and was not created by AutoAir; refusing to overwrite it"
        )
    if recorded is not None and current_sha not in (recorded, new_sha) and not force:
        raise EjectedError(location)
    if (
        recorded is None
        and unknown
        and current_sha != new_sha
        and not force
        and not _pristine_stub(existing)
    ):
        raise EjectedError(location)


_STUB_DAG_RE = re.compile(r"AutoAir loader stub for the airflow DAG '([^'\n]{1,250})'")


def _pristine_stub(content: str) -> bool:
    """An unmodified loader stub: nothing in it can have been edited by hand."""
    match = _STUB_DAG_RE.search(content[:300])
    return match is not None and content == render_stub(match.group(1))


def main_file(dag_id: str, names: list[str] | dict[str, Any]) -> str:
    keys = list(names)
    for preferred in (f"{dag_id}.py", f"{dag_id}.yaml", f"{dag_id}.yml"):
        if preferred in keys:
            return preferred
    return sorted(keys)[0] if keys else f"{dag_id}.py"


def summary_of(
    spec: DagSpec, *, updated_at: datetime.datetime, dag_file: str, etag: str | None
) -> SpecSummary:
    return SpecSummary(
        dag_id=spec.dag_id,
        output_mode=spec.output_mode,
        display_name=spec.display_name,
        description=spec.description,
        tags=spec.tags,
        task_count=len(spec.task_nodes()),
        updated_at=updated_at,
        dag_file=dag_file,
        etag=etag,
        document_type=spec.document_type,
    )


def history_id(when: datetime.datetime, etag: str) -> str:
    return f"{when.strftime('%Y%m%dT%H%M%S%fZ')}-{etag[:8]}"


class HistoryEntry(BaseModel):
    """One ``.autoair/history/<dag_id>/<version>.json`` snapshot."""

    version: str
    timestamp: datetime.datetime
    etag: str
    author: str | None = None
    message: str | None = None
    environment: str | None = None
    spec: dict[str, Any]

    def info(self) -> VersionInfo:
        return VersionInfo(
            version=self.version,
            timestamp=self.timestamp,
            author=self.author,
            message=self.message,
            etag=self.etag,
        )
