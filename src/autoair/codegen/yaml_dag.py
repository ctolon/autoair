"""Airflow 3.4 native YAML Dags (AIP-85 ``YamlDagImporter``): export and import.

The YAML format (schema ``https://airflow.apache.org/schemas/dag/2026-10-30.json``) covers
a subset of what AutoAir models: operator tasks with dependencies, Jinja (``$t``) and
XCom (``$x``) markers, task-level BaseOperator arguments and a string or constructed
timetable schedule. Everything else is reported as a problem instead of being silently
dropped, so ``output_mode="yaml"`` is only deployable when the export is lossless.
"""

from __future__ import annotations

import datetime
import json
from importlib import resources
from typing import Any

import yaml
from pydantic import BaseModel

from autoair.codegen.builder import effective_edges
from autoair.codegen.timedeltas import coerce_timedelta
from autoair.spec import (
    CronSchedule,
    DagSpec,
    IntervalSchedule,
    MultiCronSchedule,
    NoSchedule,
    OperatorNode,
    PresetSchedule,
)

SCHEMA_ID = "https://airflow.apache.org/schemas/dag/2026-10-30.json"
HEADER = "# Generated by AutoAir from the visual DAG spec '{dag_id}'. Edit it in AutoAir.\n"
_TASK_ARGS = (
    "trigger_rule",
    "retries",
    "pool",
    "pool_slots",
    "queue",
    "owner",
    "doc_md",
    "priority_weight",
    "weight_rule",
    "task_display_name",
    "executor",
    "max_active_tis_per_dagrun",
    "depends_on_past",
)
_DEFAULT_ARGS = (
    "owner",
    "retries",
    "depends_on_past",
    "email",
    "email_on_failure",
    "pool",
    "queue",
)


class YamlIssue(BaseModel):
    severity: str
    message: str
    node_id: str | None = None


class YamlExport(BaseModel):
    yaml: str
    issues: list[YamlIssue]

    @property
    def lossless(self) -> bool:
        return not any(i.severity == "error" for i in self.issues)


def yaml_schema() -> dict[str, Any]:
    text = resources.files("autoair.resources") / "airflow-dag-yaml-2026-10-30.schema.json"
    data: dict[str, Any] = json.loads(text.read_text(encoding="utf-8"))
    return data


# --------------------------------------------------------------------------- export


def _value(value: Any, ids: dict[str, str], issues: list[YamlIssue], node_id: str) -> Any:
    if isinstance(value, str):
        return {"$t": value} if ("{{" in value or "{%" in value) else value
    if isinstance(value, list):
        return [_value(v, ids, issues, node_id) for v in value]
    if isinstance(value, dict):
        tag = value.get("$type")
        if tag == "xcom":
            target = ids.get(str(value["node"]))
            if target is None:
                issues.append(
                    YamlIssue(
                        severity="error",
                        node_id=node_id,
                        message="XCom reference to a task not in the YAML Dag",
                    )
                )
                return None
            key = value.get("key")
            return {"$x": {"task": target, "key": key}} if key else {"$x": target}
        if tag in ("function", "file"):
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=node_id,
                    message="functions and scripts written in the builder cannot be expressed "
                    "in YAML Dags; use the Python output",
                )
            )
            return None
        if tag in ("output_model", "toolset"):
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=node_id,
                    message="structured LLM outputs and agent toolsets are Python objects "
                    "that YAML Dags cannot express; use the Python output",
                )
            )
            return None
        if tag == "import":
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=node_id,
                    message=f"Python reference {value.get('path')} cannot be expressed in YAML "
                    "Dags (they contain no code by design); use the Python output",
                )
            )
            return None
        if tag in ("timedelta", "datetime"):
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=node_id,
                    message=f"{tag} values cannot be expressed in YAML Dags",
                )
            )
            return None
        if any(k.startswith("$") for k in value):
            return {"$const": value}
        return {k: _value(v, ids, issues, node_id) for k, v in value.items()}
    return value


def _schedule(spec: DagSpec, issues: list[YamlIssue]) -> Any:
    sched = spec.schedule
    if isinstance(sched, NoSchedule):
        return None
    tz = getattr(sched, "timezone", None) or spec.timezone or "UTC"
    if isinstance(sched, PresetSchedule):
        if spec.timezone and sched.preset not in ("@once", "@continuous"):
            return {
                "uses": "airflow.sdk.CronTriggerTimetable",
                "with": {"expression": sched.preset, "timezone": tz},
            }
        return sched.preset
    if isinstance(sched, CronSchedule):
        if sched.data_interval:
            return {
                "uses": "airflow.sdk.CronDataIntervalTimetable",
                "with": {"expression": sched.expression, "timezone": tz},
            }
        if sched.timezone or spec.timezone or sched.run_immediately or sched.interval_seconds:
            if sched.interval_seconds:
                issues.append(
                    YamlIssue(
                        severity="error", message="cron interval cannot be expressed in YAML Dags"
                    )
                )
            return {
                "uses": "airflow.sdk.CronTriggerTimetable",
                "with": {
                    "expression": sched.expression,
                    "timezone": tz,
                    **({"run_immediately": True} if sched.run_immediately else {}),
                },
            }
        return sched.expression
    if isinstance(sched, MultiCronSchedule):
        issues.append(
            YamlIssue(
                severity="error",
                message="multi-cron schedules need positional "
                "arguments, which YAML timetables cannot express",
            )
        )
        return None
    if isinstance(sched, IntervalSchedule):
        issues.append(
            YamlIssue(
                severity="error",
                message="interval schedules cannot be "
                "expressed in YAML Dags; use a cron expression",
            )
        )
        return None
    issues.append(
        YamlIssue(
            severity="error", message=f"{sched.type} schedules are not supported by YAML Dags"
        )
    )
    return None


def export_yaml_dag(spec: DagSpec) -> YamlExport:
    issues: list[YamlIssue] = []
    nodes = spec.node_map()
    tasks = spec.task_nodes(include_disabled=False)
    if spec.group_nodes():
        issues.append(
            YamlIssue(
                severity="warning",
                message="task groups are flattened: YAML Dags "
                "have no task groups (task ids keep the group prefix)",
            )
        )
    from autoair.validation import effective_task_id

    ids = {t.id: effective_task_id(t, nodes) for t in tasks}  # type: ignore[arg-type]
    upstream: dict[str, list[str]] = {t.id: [] for t in tasks}
    group_members: dict[str, list[str]] = {}
    for t in tasks:
        cur = t.parent_group
        while cur:
            group_members.setdefault(cur, []).append(t.id)
            cur = getattr(nodes.get(cur), "parent_group", None)

    def expand(node_id: str) -> list[str]:
        return group_members.get(node_id, []) if node_id not in ids else [node_id]

    for e in effective_edges(spec):
        if e.label:
            issues.append(
                YamlIssue(
                    severity="warning",
                    node_id=e.target,
                    message=f"edge label {e.label!r} is dropped",
                )
            )
        for src in expand(e.source):
            for dst in expand(e.target):
                if src != dst and ids[src] not in upstream[dst]:
                    upstream[dst].append(ids[src])

    out_tasks: list[dict[str, Any]] = []
    for t in tasks:
        if not isinstance(t, OperatorNode):
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=t.id,
                    message=f"{t.kind} nodes are not supported by YAML Dags (only operators)",
                )
            )
            continue
        for flag, what in (
            (t.mapping, "dynamic task mapping"),
            (t.is_setup or t.is_teardown, "setup/teardown"),
            (t.retry_policy, "retry policies"),
            (not t.callbacks.is_empty(), "callbacks"),
            (t.outlets or t.inlets, "asset inlets/outlets"),
            (
                t.retry_delay_seconds is not None or t.execution_timeout_seconds is not None,
                "timedelta task arguments",
            ),
        ):
            if flag:
                issues.append(
                    YamlIssue(
                        severity="error",
                        node_id=t.id,
                        message=f"{what} cannot be expressed in YAML Dags",
                    )
                )
        task: dict[str, Any] = {"id": ids[t.id]}
        if upstream[t.id]:
            task["needs"] = upstream[t.id]
        if t.operator != "airflow.providers.standard.operators.empty.EmptyOperator" or t.params:
            task["uses"] = t.operator
        else:
            task["uses"] = None
        if t.params:
            task["with"] = {
                k: _value(coerce_timedelta(t.operator, k, v), ids, issues, t.id)
                for k, v in t.params.items()
            }
        for arg in _TASK_ARGS:
            val = getattr(t, arg)
            if val is not None:
                task[arg] = val
        out_tasks.append(task)

    doc: dict[str, Any] = {
        "$schema": SCHEMA_ID,
        "dag_id": spec.dag_id,
        "schedule": _schedule(spec, issues),
    }
    for attr in ("start_date", "end_date"):
        value = getattr(spec, attr)
        if value is None:
            continue
        if spec.timezone and value.tzinfo is None:  # wall clock in the DAG timezone
            import zoneinfo

            value = value.replace(tzinfo=zoneinfo.ZoneInfo(spec.timezone))
        doc[attr] = value.isoformat()
    doc["catchup"] = spec.catchup
    for attr in (
        "description",
        "doc_md",
        "max_active_runs",
        "max_active_tasks",
        "is_paused_upon_creation",
        "fail_fast",
        "max_consecutive_failed_dag_runs",
    ):
        val = getattr(spec, attr)
        if val is not None:
            doc[attr] = val
    if spec.display_name:
        doc["dag_display_name"] = spec.display_name
    if spec.tags:
        doc["tags"] = spec.tags
    da = {k: v for k in _DEFAULT_ARGS if (v := getattr(spec.default_args, k)) is not None}
    if da:
        doc["default_args"] = da
    if (
        spec.default_args.retry_delay_seconds is not None
        or spec.default_args.execution_timeout_seconds is not None
    ):
        issues.append(
            YamlIssue(
                severity="error",
                message="default_args retry_delay / "
                "execution_timeout cannot be expressed in YAML Dags",
            )
        )
    if spec.params:
        doc["params"] = {k: p.default for k, p in spec.params.items()}
        if any(p.schema_kwargs() for p in spec.params.values()):
            issues.append(
                YamlIssue(
                    severity="warning",
                    message="param schemas (type, enum, ...) are dropped; only defaults are kept",
                )
            )
    if spec.deadlines or not spec.callbacks.is_empty() or spec.owner_links:
        issues.append(
            YamlIssue(
                severity="error",
                message="DAG callbacks, deadlines and owner_links cannot be expressed in YAML Dags",
            )
        )
    doc["tasks"] = out_tasks
    text = HEADER.format(dag_id=spec.dag_id) + yaml.safe_dump(
        doc, sort_keys=False, allow_unicode=True, default_flow_style=False
    )
    return YamlExport(yaml=text, issues=issues)


# --------------------------------------------------------------------------- import


def _import_value(value: Any, by_task_id: dict[str, str]) -> Any:
    if isinstance(value, dict):
        if "$t" in value or "$template" in value:
            inner = value.get("$t", value.get("$template"))
            return inner if isinstance(inner, str) else json.dumps(inner)
        if "$x" in value or "$xcom" in value:
            ref: Any = value.get("$x", value.get("$xcom"))
            if isinstance(ref, str):
                task_id, key = ref, None
            else:
                task_id, key = ref["task"], ref.get("key")
            out: dict[str, Any] = {"$type": "xcom", "node": by_task_id.get(task_id, task_id)}
            if key:
                out["key"] = key
            return out
        if "$const" in value:
            return value["$const"]
        return {k: _import_value(v, by_task_id) for k, v in value.items()}
    if isinstance(value, list):
        return [_import_value(v, by_task_id) for v in value]
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    return value


def load_yaml(text: str, max_nodes: int | None = None) -> Any:
    """``yaml.safe_load`` that refuses documents expanding to more than ``max_nodes``
    values. Aliases are shared, not copied, by the loader, so a few hundred bytes of
    nested anchors ("billion laughs") or a self-referencing alias would otherwise make
    every later walk of the document exponential or endless."""
    if max_nodes is None:
        from autoair.sections import InterchangeSettings, active

        max_nodes = active(InterchangeSettings).yaml_max_nodes
    doc = yaml.safe_load(text)
    budget = max_nodes
    stack: list[Any] = [doc]
    while stack:
        value = stack.pop()
        budget -= 1
        if budget < 0:
            raise ValueError(
                f"YAML document expands to more than {max_nodes} values (recursive aliases?)"
            )
        if isinstance(value, dict):
            stack.extend(value.values())
        elif isinstance(value, list):
            stack.extend(value)
    return doc


def import_yaml_dag(text: str) -> tuple[DagSpec, list[YamlIssue]]:
    """Parse an Airflow YAML Dag into a :class:`DagSpec` (for round-trip editing)."""
    doc = load_yaml(text)
    if not isinstance(doc, dict) or "dag_id" not in doc:
        raise ValueError("not an Airflow YAML Dag document (missing dag_id)")
    issues: list[YamlIssue] = []
    templates: dict[str, dict[str, Any]] = doc.get("templates") or {}
    raw_tasks: list[dict[str, Any]] = doc.get("tasks") or []
    by_task_id = {t["id"]: f"n{i + 1}" for i, t in enumerate(raw_tasks)}
    nodes: list[dict[str, Any]] = []
    edges: list[dict[str, Any]] = []
    for i, raw in enumerate(raw_tasks):
        task = dict(raw)
        extends = task.pop("extends", None)
        for name in [extends] if isinstance(extends, str) else (extends or []):
            task = {**templates.get(name, {}), **task}
        node_id = by_task_id[task["id"]]
        if task.get("run") is not None:
            issues.append(
                YamlIssue(
                    severity="warning",
                    node_id=node_id,
                    message="`run:` stub tasks are imported as EmptyOperator",
                )
            )
        node: dict[str, Any] = {
            "kind": "operator",
            "id": node_id,
            "task_id": task["id"],
            "operator": task.get("uses")
            or "airflow.providers.standard.operators.empty.EmptyOperator",
            "params": {
                k: _import_value(v, by_task_id) for k, v in (task.get("with") or {}).items()
            },
            "position": {"x": 0, "y": i * 90},
        }
        for arg in _TASK_ARGS:
            if arg in task:
                node[arg] = task[arg]
        nodes.append(node)
        for up in task.get("needs") or []:
            if up in by_task_id:
                edges.append({"source": by_task_id[up], "target": node_id})
    schedule = doc.get("schedule")
    sched: dict[str, Any]
    if schedule is None:
        sched = {"type": "none"}
    elif isinstance(schedule, str) and schedule.startswith("@"):
        sched = {"type": "preset", "preset": schedule}
    elif isinstance(schedule, str):
        sched = {"type": "cron", "expression": schedule}
    else:
        uses, kw = schedule.get("uses", ""), schedule.get("with") or {}
        expr = kw.get("expression") or kw.get("cron")
        sched = {
            "type": "cron",
            "expression": expr,
            "timezone": kw.get("timezone"),
            "data_interval": uses.endswith("CronDataIntervalTimetable"),
        }
        if not expr:
            issues.append(
                YamlIssue(severity="warning", message=f"timetable {uses} imported as no schedule")
            )
            sched = {"type": "none"}
    spec_doc: dict[str, Any] = {
        "dag_id": doc["dag_id"],
        "output_mode": "yaml",
        "schedule": sched,
        "nodes": nodes,
        "edges": edges,
    }
    for key in (
        "description",
        "doc_md",
        "catchup",
        "tags",
        "max_active_runs",
        "max_active_tasks",
        "is_paused_upon_creation",
        "fail_fast",
        "max_consecutive_failed_dag_runs",
    ):
        if key in doc:
            spec_doc[key] = doc[key]
    for key in ("start_date", "end_date"):
        if key in doc:
            spec_doc[key] = _import_value(doc[key], {})
    if "dag_display_name" in doc:
        spec_doc["display_name"] = doc["dag_display_name"]
    if isinstance(doc.get("default_args"), dict):
        spec_doc["default_args"] = {
            k: v for k, v in doc["default_args"].items() if k in _DEFAULT_ARGS
        }
    if isinstance(doc.get("params"), dict):
        spec_doc["params"] = {k: {"default": v} for k, v in doc["params"].items()}
    return DagSpec.model_validate(spec_doc), issues


def validate_yaml_text(text: str) -> list[str]:
    """Validate a YAML Dag against the vendored JSON Schema (structure only)."""
    import jsonschema

    doc = load_yaml(text)
    validator = jsonschema.Draft202012Validator(yaml_schema())
    return [
        f"{'/'.join(map(str, e.absolute_path)) or '<root>'}: {e.message}"
        for e in validator.iter_errors(doc)
    ]
