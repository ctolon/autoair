def _value(value: Any, ids: dict[str, str], issues: list[YamlIssue], node_id: str) -> Any:
    if isinstance(value, str):
        return {"$t": value} if ("{{" in value or "{%" in value) else value
    if isinstance(value, list):
        return [_value(v, ids, issues, node_id) for v in value]
    if isinstance(value, dict):
        tag = value.get("$type")
        if tag == "xcom":
            target = ids.get(str(value["node"]))
            if target is None:
                issues.append(
                    YamlIssue(
                        severity="error",
                        node_id=node_id,
                        message="XCom reference to a task not in the YAML Dag",
                    )
                )
                return None
            key = value.get("key")
            return {"$x": {"task": target, "key": key}} if key else {"$x": target}
        if tag in ("function", "file"):
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=node_id,
                    message="functions and scripts written in the builder cannot be expressed "
                    "in YAML Dags; use the Python output",
                )
            )
            return None
        if tag in ("output_model", "toolset"):
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=node_id,
                    message="structured LLM outputs and agent toolsets are Python objects "
                    "that YAML Dags cannot express; use the Python output",
                )
            )
            return None
        if tag == "import":
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=node_id,
                    message=f"Python reference {value.get('path')} cannot be expressed in YAML "
                    "Dags (they contain no code by design); use the Python output",
                )
            )
            return None
        if tag in ("timedelta", "datetime"):
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=node_id,
                    message=f"{tag} values cannot be expressed in YAML Dags"
                    + (
                        " (only for arguments Airflow types as timedelta, as a whole number of "
                        "seconds)"
                        if tag == "timedelta"
                        else ""
                    ),
                )
            )
            return None
        if any(k.startswith("$") for k in value):
            return {"$const": value}
        return {k: _value(v, ids, issues, node_id) for k, v in value.items()}
    return value


def _param(
    operator: str, name: str, value: Any, ids: dict[str, str], issues: list[YamlIssue], node_id: str
) -> Any:
    """An operator argument for ``with:``. A duration of an argument Airflow types as
    ``timedelta`` is written as a duration string, which the YAML importer parses."""
    value = coerce_timedelta(operator, name, value)
    if (
        isinstance(value, dict)
        and value.get("$type") == "timedelta"
        and requires_timedelta(operator, name)
    ):
        text = _duration(float(value.get("seconds", 0)))
        if text is not None:
            return text
    return _value(value, ids, issues, node_id)


def _schedule(spec: DagSpec, issues: list[YamlIssue]) -> Any:
    sched = spec.schedule
    if isinstance(sched, NoSchedule):
        return None
    tz = getattr(sched, "timezone", None) or spec.timezone or "UTC"
    if isinstance(sched, PresetSchedule):
        if spec.timezone and sched.preset not in ("@once", "@continuous"):
            return {
                "uses": "airflow.sdk.CronTriggerTimetable",
                "with": {"expression": sched.preset, "timezone": tz},
            }
        return sched.preset
    if isinstance(sched, CronSchedule):
        if sched.data_interval:
            return {
                "uses": "airflow.sdk.CronDataIntervalTimetable",
                "with": {"expression": sched.expression, "timezone": tz},
            }
        if sched.timezone or spec.timezone or sched.run_immediately or sched.interval_seconds:
            if sched.interval_seconds:
                issues.append(
                    YamlIssue(
                        severity="error", message="cron interval cannot be expressed in YAML Dags"
                    )
                )
            return {
                "uses": "airflow.sdk.CronTriggerTimetable",
                "with": {
                    "expression": sched.expression,
                    "timezone": tz,
                    **({"run_immediately": True} if sched.run_immediately else {}),
                },
            }
        return sched.expression
    if isinstance(sched, MultiCronSchedule):
        issues.append(
            YamlIssue(
                severity="error",
                message="multi-cron schedules need positional "
                "arguments, which YAML timetables cannot express",
            )
        )
        return None
    if isinstance(sched, IntervalSchedule):
        issues.append(
            YamlIssue(
                severity="error",
                message="interval schedules cannot be "
                "expressed in YAML Dags; use a cron expression",
            )
        )
        return None
    issues.append(
        YamlIssue(
            severity="error", message=f"{sched.type} schedules are not supported by YAML Dags"
        )
    )
    return None


def export_yaml_dag(spec: DagSpec) -> YamlExport:
    issues: list[YamlIssue] = []
    nodes = spec.node_map()
    tasks = spec.task_nodes(include_disabled=False)
    if spec.group_nodes():
        issues.append(
            YamlIssue(
                severity="warning",
                message="task groups are flattened: YAML Dags "
                "have no task groups (task ids keep the group prefix)",
            )
        )
    from autoair.validation import effective_task_id

    ids = {t.id: effective_task_id(t, nodes) for t in tasks}  # type: ignore[arg-type]
    upstream: dict[str, list[str]] = {t.id: [] for t in tasks}
    group_members: dict[str, list[str]] = {}
    for t in tasks:
        cur = t.parent_group
        while cur:
            group_members.setdefault(cur, []).append(t.id)
            cur = getattr(nodes.get(cur), "parent_group", None)

    def expand(node_id: str) -> list[str]:
        return group_members.get(node_id, []) if node_id not in ids else [node_id]

    for e in effective_edges(spec):
        if e.label:
            issues.append(
                YamlIssue(
                    severity="warning",
                    node_id=e.target,
                    message=f"edge label {e.label!r} is dropped",
                )
            )
        for src in expand(e.source):
            for dst in expand(e.target):
                if src != dst and ids[src] not in upstream[dst]:
                    upstream[dst].append(ids[src])

    for bp in spec.blueprint_nodes(include_disabled=False):
        issues.append(
            YamlIssue(
                severity="error",
                node_id=bp.id,
                message=f"blueprint step {bp.step_id!r} cannot be expressed in YAML Dags "
                "(use the python or loader output mode)",
            )
        )
    out_tasks: list[dict[str, Any]] = []
    for t in tasks:
        if not isinstance(t, OperatorNode):
            issues.append(
                YamlIssue(
                    severity="error",
                    node_id=t.id,
                    message=f"{t.kind} nodes are not supported by YAML Dags (only operators)",
                )
            )
            continue
        for flag, what in (
            (t.mapping, "dynamic task mapping"),
            (t.is_setup or t.is_teardown, "setup/teardown"),
            (t.retry_policy, "retry policies"),
            (not t.callbacks.is_empty(), "callbacks"),
            (t.outlets or t.inlets, "asset inlets/outlets"),
            (t.lineage != "inherit", "OpenLineage enable/disable"),
        ):
            if flag:
                issues.append(
                    YamlIssue(
                        severity="error",
                        node_id=t.id,
                        message=f"{what} cannot be expressed in YAML Dags",
                    )
                )
        task: dict[str, Any] = {"id": ids[t.id]}
        if upstream[t.id]:
            task["needs"] = upstream[t.id]
        if t.operator != "airflow.providers.standard.operators.empty.EmptyOperator" or t.params:
            task["uses"] = t.operator
        else:
            task["uses"] = None
        if t.params:
            task["with"] = {
                k: _param(t.operator, k, v, ids, issues, t.id) for k, v in t.params.items()
            }
        for arg in _TASK_ARGS:
            val = getattr(t, arg)
            if val is not None:
                task[arg] = val
        for arg, field in _TASK_DURATIONS:
            seconds = getattr(t, field)
            if seconds is None:
                continue
            text = _duration(seconds)
            if text is None:
                issues.append(
                    YamlIssue(
                        severity="error",
                        node_id=t.id,
                        message=f"{arg} of {seconds:g}s cannot be expressed in YAML Dags "
                        "(durations are whole seconds)",
                    )
                )
            else:
                task[arg] = text
        out_tasks.append(task)

    doc: dict[str, Any] = {
        "$schema": SCHEMA_ID,
        "dag_id": spec.dag_id,
        "schedule": _schedule(spec, issues),
    }
    for attr in ("start_date", "end_date"):
        value = getattr(spec, attr)
        if value is None:
            continue
        if spec.timezone and value.tzinfo is None:  # wall clock in the DAG timezone
            import zoneinfo

            value = value.replace(tzinfo=zoneinfo.ZoneInfo(spec.timezone))
        doc[attr] = value.isoformat()
    if spec.timezone and not (spec.start_date or spec.end_date):
        sched_tz = getattr(spec.schedule, "timezone", None)
        if not isinstance(spec.schedule, (CronSchedule, PresetSchedule)) or sched_tz:
            issues.append(
                YamlIssue(
                    severity="warning",
                    message=f"the DAG timezone {spec.timezone!r} is dropped: YAML Dags take it "
                    "from start_date (set a start date)",
                )
            )
    doc["catchup"] = spec.catchup
    for attr in _DAG_ARGS:
        val = getattr(spec, attr)
        if val is not None:
            doc[attr] = val
    if spec.dagrun_timeout_seconds is not None:
        text = _duration(spec.dagrun_timeout_seconds)
        if text is None:
            issues.append(
                YamlIssue(
                    severity="error",
                    message=f"dagrun_timeout of {spec.dagrun_timeout_seconds:g}s cannot be "
                    "expressed in YAML Dags (durations are whole seconds)",
                )
            )
        else:
            doc["dagrun_timeout"] = text
    if spec.lineage != "inherit":
        issues.append(
            YamlIssue(
                severity="error",
                message="OpenLineage enable/disable cannot be expressed in YAML Dags",
            )
        )
    if spec.display_name:
        doc["dag_display_name"] = spec.display_name
    if spec.tags:
        doc["tags"] = spec.tags
    # Airflow's YAML Dags have no default_args: they are a task template every task extends
    # (task-level values still win).
    da = {k: v for k in _DEFAULT_ARGS if (v := getattr(spec.default_args, k)) is not None}
    for arg, field in _TASK_DURATIONS:
        seconds = getattr(spec.default_args, field)
        if seconds is None:
            continue
        text = _duration(seconds)
        if text is None:
            issues.append(
                YamlIssue(
                    severity="error",
                    message=f"default_args {arg} of {seconds:g}s cannot be expressed in YAML "
                    "Dags (durations are whole seconds)",
                )
            )
        else:
            da[arg] = text
    if da:
        doc["templates"] = {DEFAULT_ARGS_TEMPLATE: da}
        out_tasks = [{"id": t["id"], "extends": DEFAULT_ARGS_TEMPLATE, **t} for t in out_tasks]
    if spec.params:
        doc["params"] = {k: p.default for k, p in spec.params.items()}
        if any(p.schema_kwargs() for p in spec.params.values()):
            issues.append(
                YamlIssue(
                    severity="warning",
                    message="param schemas (type, enum, ...) are dropped; only defaults are kept",
                )
            )
    if spec.deadlines or not spec.callbacks.is_empty() or spec.owner_links:
        issues.append(
            YamlIssue(
                severity="error",
                message="DAG callbacks, deadlines and owner_links cannot be expressed in YAML Dags",
            )
        )
    doc["tasks"] = out_tasks
    text = HEADER.format(dag_id=spec.dag_id) + yaml.safe_dump(
        doc, sort_keys=False, allow_unicode=True, default_flow_style=False
    )
    return YamlExport(yaml=text, issues=issues)


def _num(value: float) -> int | float:
    return int(value) if float(value).is_integer() else value


