"""Airflow 3.4 native YAML Dags (AIP-85 ``YamlDagImporter``): export and import.

The YAML format (schema ``https://airflow.apache.org/schemas/dag/2026-10-30.json``) covers
a subset of what AutoAir models: operator tasks with dependencies, Jinja (``$t``) and
XCom (``$x``) markers, task-level BaseOperator arguments and a string or constructed
timetable schedule. Everything else is reported as a problem instead of being silently
dropped, so ``output_mode="yaml"`` is only deployable when the export is lossless.
"""

from __future__ import annotations

import datetime
import json
import re
from importlib import resources
from typing import Any

import yaml
from pydantic import BaseModel

from autoair.codegen.builder import effective_edges
from autoair.codegen.timedeltas import coerce_timedelta, requires_timedelta
from autoair.spec import (
    CronSchedule,
    DagSpec,
    IntervalSchedule,
    MultiCronSchedule,
    NoSchedule,
    OperatorNode,
    PresetSchedule,
)

SCHEMA_ID = "https://airflow.apache.org/schemas/dag/2026-10-30.json"
# The task template the DAG's default_args are exported as.
DEFAULT_ARGS_TEMPLATE = "default_args"
HEADER = "# Generated by AutoAir from the visual DAG spec '{dag_id}'. Edit it in AutoAir.\n"
_TASK_ARGS = (
    "trigger_rule",
    "retries",
    "pool",
    "pool_slots",
    "queue",
    "owner",
    "doc_md",
    "priority_weight",
    "weight_rule",
    "task_display_name",
    "executor",
    "max_active_tis_per_dagrun",
    "depends_on_past",
    "retry_exponential_backoff",
    "executor_config",
)
# Task-level duration arguments: Airflow's YAML importer parses duration strings ("5m",
# "PT1H") for arguments typed ``timedelta``.
_TASK_DURATIONS = (
    ("retry_delay", "retry_delay_seconds"),
    ("execution_timeout", "execution_timeout_seconds"),
)
_DAG_ARGS = (
    "description",
    "doc_md",
    "max_active_runs",
    "max_active_tasks",
    "is_paused_upon_creation",
    "fail_fast",
    "max_consecutive_failed_dag_runs",
    "render_template_as_native_obj",
    "rerun_with_latest_version",
)
_DEFAULT_ARGS = (
    "owner",
    "retries",
    "depends_on_past",
    "email",
    "email_on_failure",
    "pool",
    "queue",
)


def _duration(seconds: float) -> str | None:
    """``seconds`` as a duration string Airflow's YAML importer parses ("1h30m"), or None
    when it is not a whole number of seconds (the format has no fractions)."""
    if not float(seconds).is_integer() or seconds < 0:
        return None
    rest = int(seconds)
    if rest == 0:
        return "0s"
    out = ""
    for unit, size in (("w", 604_800), ("d", 86_400), ("h", 3_600), ("m", 60), ("s", 1)):
        if rest >= size:
            out += f"{rest // size}{unit}"
            rest %= size
    return out


_SHORT_DURATION = re.compile(r"^(?=\d)(?:(\d+)w)?(?:(\d+)d)?(?:(\d+)h)?(?:(\d+)m)?(?:(\d+)s)?$")
_ISO_DURATION = re.compile(
    r"^P(?=[\dWDT])(?:(\d+)W)?(?:(\d+)D)?(?:T(?=[\dHMS])(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?)?$"
)


def _duration_seconds(value: Any) -> float | None:
    """Seconds of a YAML duration (``5m``, ``PT1H``, a number of seconds), or None."""
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    if not isinstance(value, str):
        return None
    m = _SHORT_DURATION.match(value) or _ISO_DURATION.match(value)
    if m is None:
        return None
    weeks, days, hours, minutes, secs = (int(g) if g else 0 for g in m.groups())
    return float((((weeks * 7 + days) * 24 + hours) * 60 + minutes) * 60 + secs)


class YamlIssue(BaseModel):
    severity: str
    message: str
    node_id: str | None = None


class YamlExport(BaseModel):
    yaml: str
    issues: list[YamlIssue]

    @property
    def lossless(self) -> bool:
        return not any(i.severity == "error" for i in self.issues)


def yaml_schema() -> dict[str, Any]:
    text = resources.files("autoair.resources") / "airflow-dag-yaml-2026-10-30.schema.json"
    data: dict[str, Any] = json.loads(text.read_text(encoding="utf-8"))
    return data


