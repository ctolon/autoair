def _import_value(value: Any, by_task_id: dict[str, str]) -> Any:
    if isinstance(value, dict):
        if "$t" in value or "$template" in value:
            inner = value.get("$t", value.get("$template"))
            return inner if isinstance(inner, str) else json.dumps(inner)
        if "$x" in value or "$xcom" in value:
            ref: Any = value.get("$x", value.get("$xcom"))
            if isinstance(ref, str):
                task_id, key = ref, None
            else:
                task_id, key = ref["task"], ref.get("key")
            out: dict[str, Any] = {"$type": "xcom", "node": by_task_id.get(task_id, task_id)}
            if key:
                out["key"] = key
            return out
        if "$const" in value:
            return value["$const"]
        return {k: _import_value(v, by_task_id) for k, v in value.items()}
    if isinstance(value, list):
        return [_import_value(v, by_task_id) for v in value]
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    return value


def load_yaml(text: str, max_nodes: int | None = None) -> Any:
    """``yaml.safe_load`` that refuses documents expanding to more than ``max_nodes``
    values. Aliases are shared, not copied, by the loader, so a few hundred bytes of
    nested anchors ("billion laughs") or a self-referencing alias would otherwise make
    every later walk of the document exponential or endless."""
    if max_nodes is None:
        from autoair.sections import InterchangeSettings, active

        max_nodes = active(InterchangeSettings).yaml_max_nodes
    doc = yaml.safe_load(text)
    budget = max_nodes
    stack: list[Any] = [doc]
    while stack:
        value = stack.pop()
        budget -= 1
        if budget < 0:
            raise ValueError(
                f"YAML document expands to more than {max_nodes} values (recursive aliases?)"
            )
        if isinstance(value, dict):
            stack.extend(value.values())
        elif isinstance(value, list):
            stack.extend(value)
    return doc


def import_yaml_dag(text: str) -> tuple[DagSpec, list[YamlIssue]]:
    """Parse an Airflow YAML Dag into a :class:`DagSpec` (for round-trip editing)."""
    doc = load_yaml(text)
    if not isinstance(doc, dict) or "dag_id" not in doc:
        raise ValueError("not an Airflow YAML Dag document (missing dag_id)")
    issues: list[YamlIssue] = []
    templates: dict[str, dict[str, Any]] = doc.get("templates") or {}
    raw_tasks: list[dict[str, Any]] = doc.get("tasks") or []
    # The export's default_args template, extended by every task: the DAG's default_args.
    shared: dict[str, Any] | None = None
    candidate = templates.get(DEFAULT_ARGS_TEMPLATE)
    if (
        isinstance(candidate, dict)
        and raw_tasks
        and "extends" not in candidate
        and set(candidate) <= {*_DEFAULT_ARGS, *(arg for arg, _ in _TASK_DURATIONS)}
        and all(_extends(t) and _extends(t)[0] == DEFAULT_ARGS_TEMPLATE for t in raw_tasks)
    ):
        shared = candidate
    by_task_id = {t["id"]: f"n{i + 1}" for i, t in enumerate(raw_tasks)}
    nodes: list[dict[str, Any]] = []
    edges: list[dict[str, Any]] = []
    for i, raw in enumerate(raw_tasks):
        task = dict(raw)
        extends = _extends(task)
        task.pop("extends", None)
        if shared is not None:
            extends = extends[1:]
        merged: dict[str, Any] = {}
        for name in extends:
            merged = {**merged, **templates.get(name, {})}
        task = {**merged, **task}
        node_id = by_task_id[task["id"]]
        if task.get("run") is not None:
            issues.append(
                YamlIssue(
                    severity="warning",
                    node_id=node_id,
                    message="`run:` stub tasks are imported as EmptyOperator",
                )
            )
        node: dict[str, Any] = {
            "kind": "operator",
            "id": node_id,
            "task_id": task["id"],
            "operator": task.get("uses")
            or "airflow.providers.standard.operators.empty.EmptyOperator",
            "params": {},
            "position": {"x": 0, "y": i * 90},
        }
        for k, v in (task.get("with") or {}).items():
            seconds = _duration_seconds(v) if isinstance(v, str) else None
            if seconds is not None and requires_timedelta(node["operator"], k):
                node["params"][k] = {"$type": "timedelta", "seconds": seconds}
            else:
                node["params"][k] = _import_value(v, by_task_id)
        for arg in _TASK_ARGS:
            if arg in task:
                node[arg] = task[arg]
        for arg, field in _TASK_DURATIONS:
            if task.get(arg) is None:
                continue
            seconds = _duration_seconds(task[arg])
            if seconds is None:
                issues.append(
                    YamlIssue(
                        severity="warning",
                        node_id=node_id,
                        message=f"{arg} {task[arg]!r} is not a duration AutoAir reads; dropped",
                    )
                )
            else:
                node[field] = seconds
        nodes.append(node)
        for up in task.get("needs") or []:
            if up in by_task_id:
                edges.append({"source": by_task_id[up], "target": node_id})
    schedule = doc.get("schedule")
    sched: dict[str, Any]
    if schedule is None:
        sched = {"type": "none"}
    elif isinstance(schedule, str) and schedule.startswith("@"):
        sched = {"type": "preset", "preset": schedule}
    elif isinstance(schedule, str):
        sched = {"type": "cron", "expression": schedule}
    else:
        uses, kw = schedule.get("uses", ""), schedule.get("with") or {}
        expr = kw.get("expression") or kw.get("cron")
        sched = {
            "type": "cron",
            "expression": expr,
            "timezone": kw.get("timezone"),
            "data_interval": uses.endswith("CronDataIntervalTimetable"),
        }
        if kw.get("run_immediately") is True:
            sched["run_immediately"] = True
        extra = sorted(set(kw) - {"expression", "cron", "timezone", "run_immediately"})
        if expr and extra:
            issues.append(
                YamlIssue(
                    severity="warning",
                    message=f"timetable arguments {', '.join(extra)} are not imported",
                )
            )
        if not expr:
            issues.append(
                YamlIssue(severity="warning", message=f"timetable {uses} imported as no schedule")
            )
            sched = {"type": "none"}
    spec_doc: dict[str, Any] = {
        "dag_id": doc["dag_id"],
        "output_mode": "yaml",
        "schedule": sched,
        "nodes": nodes,
        "edges": edges,
    }
    for key in ("catchup", "tags", *_DAG_ARGS):
        if key in doc:
            spec_doc[key] = doc[key]
    if doc.get("dagrun_timeout") is not None:
        seconds = _duration_seconds(doc["dagrun_timeout"])
        if seconds is None:
            issues.append(
                YamlIssue(
                    severity="warning",
                    message=f"dagrun_timeout {doc['dagrun_timeout']!r} is not a duration "
                    "AutoAir reads; dropped",
                )
            )
        else:
            spec_doc["dagrun_timeout_seconds"] = seconds
    for key in ("start_date", "end_date"):
        if key in doc:
            spec_doc[key] = _import_value(doc[key], {})
    _restore_timezone(spec_doc)
    if "dag_display_name" in doc:
        spec_doc["display_name"] = doc["dag_display_name"]
    raw_da = shared if shared is not None else doc.get("default_args")
    if isinstance(raw_da, dict):
        spec_doc["default_args"] = {k: v for k, v in raw_da.items() if k in _DEFAULT_ARGS}
        for arg, field in _TASK_DURATIONS:
            if raw_da.get(arg) is not None:
                seconds = _duration_seconds(raw_da[arg])
                if seconds is not None:
                    spec_doc["default_args"][field] = seconds
        durations = {arg for arg, _ in _TASK_DURATIONS}
        dropped = sorted(k for k in raw_da if k not in _DEFAULT_ARGS and k not in durations)
        if dropped:
            issues.append(
                YamlIssue(
                    severity="warning",
                    message=f"default_args {', '.join(dropped)} are not imported",
                )
            )
    if isinstance(doc.get("params"), dict):
        spec_doc["params"] = {k: {"default": v} for k, v in doc["params"].items()}
    return DagSpec.model_validate(spec_doc), issues


def _extends(task: Any) -> list[str]:
    value = task.get("extends") if isinstance(task, dict) else None
    if isinstance(value, str):
        return [value]
    return [v for v in value if isinstance(v, str)] if isinstance(value, list) else []


def _restore_timezone(spec_doc: dict[str, Any]) -> None:
    """The export writes a DAG timezone as the schedule's timetable timezone and as the UTC
    offset of the dates: when both agree, import it back as the DAG timezone (dates in its
    wall clock, a preset timetable as the preset)."""
    import zoneinfo

    sched = spec_doc["schedule"]
    tz = sched.get("timezone") if sched.get("type") == "cron" else None
    if not tz or tz in ("UTC", "Etc/UTC"):
        return
    try:
        zone = zoneinfo.ZoneInfo(tz)
    except (zoneinfo.ZoneInfoNotFoundError, ValueError):
        return
    dates: dict[str, datetime.datetime] = {}
    for key in ("start_date", "end_date"):
        raw = spec_doc.get(key)
        if raw is None:
            continue
        try:
            value = datetime.datetime.fromisoformat(str(raw).replace("Z", "+00:00"))
        except ValueError:
            return
        if value.tzinfo is None or value.utcoffset() != value.astimezone(zone).utcoffset():
            return
        dates[key] = value
    if not dates:
        return
    spec_doc["timezone"] = tz
    for key, value in dates.items():
        spec_doc[key] = value.astimezone(zone).replace(tzinfo=None).isoformat()
    expr = sched.get("expression") or ""
    if expr.startswith("@") and not sched.get("data_interval"):
        spec_doc["schedule"] = {"type": "preset", "preset": expr}
    else:
        sched.pop("timezone", None)  # the DAG timezone applies


def validate_yaml_text(text: str) -> list[str]:
    """Validate a YAML Dag against the vendored JSON Schema (structure only)."""
    import jsonschema

    doc = load_yaml(text)
    validator = jsonschema.Draft202012Validator(yaml_schema())
    return [
        f"{'/'.join(map(str, e.absolute_path)) or '<root>'}: {e.message}"
        for e in validator.iter_errors(doc)
    ]
