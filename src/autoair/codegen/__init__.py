"""Spec -> Airflow DAG Python source."""

from __future__ import annotations

from autoair.codegen.builder import build_module, generate_source
from autoair.codegen.context import CodegenContext, CodegenError
from autoair.codegen.format import format_source
from autoair.registry import HandlerRegistry
from autoair.spec import DagSpec


def render(
    spec: DagSpec,
    registry: HandlerRegistry | None = None,
    *,
    fmt: bool = True,
    airflow_version: tuple[int, int, int] | None = None,
) -> str:
    """Generate (and by default ruff-format) the DAG file for ``spec``. A raw code DAG
    renders as its own code (never reformatted), see :func:`render_raw`."""
    if spec.raw_code is not None:
        return render_raw(spec)
    source = generate_source(spec, registry, airflow_version=airflow_version)
    return format_source(source) if fmt else source


# Deploy targets only overwrite files carrying this marker near the top
# (autoair.storage.base.is_owned looks at the first 500 characters).
_MARKER = "Generated by AutoAir"
RAW_HEADER = "# Generated by AutoAir from the raw code DAG '{dag_id}'. Edit it in AutoAir.\n"


def render_raw(spec: DagSpec) -> str:
    """The deployed file of a raw code DAG: the code as written, with AutoAir's ownership
    marker prepended when the code does not carry it already."""
    code = spec.raw_code or ""
    if not code.endswith("\n"):
        code += "\n"
    if _MARKER in code[:400]:
        return code
    return RAW_HEADER.format(dag_id=spec.dag_id) + code


