def _dag_kwargs(ctx: CodegenContext) -> list[ast.keyword]:
    spec = ctx.spec
    kws: list[ast.keyword] = [ast.keyword(arg="dag_id", value=ast.Constant(spec.dag_id))]

    def add(arg: str, value: ast.expr) -> None:
        kws.append(ast.keyword(arg=arg, value=value))

    if spec.display_name:
        add("dag_display_name", ast.Constant(spec.display_name))
    if spec.description:
        add("description", ast.Constant(spec.description))
    add("schedule", _schedule(ctx))
    if spec.start_date:
        add("start_date", ctx.datetime_in(spec.start_date, spec.timezone))
    if spec.end_date:
        add("end_date", ctx.datetime_in(spec.end_date, spec.timezone))
    add("catchup", ast.Constant(spec.catchup))
    if spec.tags:
        add("tags", ast.List(elts=[ast.Constant(t) for t in spec.tags], ctx=ast.Load()))
    for attr in (
        "max_active_runs",
        "max_active_tasks",
        "is_paused_upon_creation",
        "fail_fast",
        "max_consecutive_failed_dag_runs",
        "render_template_as_native_obj",
        "rerun_with_latest_version",
    ):
        val = getattr(spec, attr)
        if val is not None:
            add(attr, ast.Constant(val))
    if spec.dagrun_timeout_seconds is not None:
        add("dagrun_timeout", ctx.timedelta(spec.dagrun_timeout_seconds))
    if spec.owner_links:
        add("owner_links", ctx.value(spec.owner_links))
    default_args = _default_args(ctx)
    if default_args is not None:
        add("default_args", default_args)
    if spec.params:
        add("params", _params(ctx))
    for cb in ctx.callback_kwargs(spec.callbacks):
        if cb.arg in ("on_success_callback", "on_failure_callback"):
            kws.append(cb)
    if spec.deadlines:
        add("deadline", ast.List(elts=[_deadline(ctx, d) for d in spec.deadlines], ctx=ast.Load()))
    doc = _doc_md(spec)
    if doc:
        add("doc_md", ast.Constant(doc))
    return kws


def _doc_md(spec: DagSpec) -> str | None:
    parts = [spec.doc_md] if spec.doc_md else []
    parts += [n.text for n in spec.note_nodes() if n.include_in_docs and n.text.strip()]
    return "\n\n".join(parts) or None


def _tz(ctx: CodegenContext, tz: str | None) -> ast.expr:
    """A schedule's own timezone, else the DAG's, else UTC."""
    return ast.Constant(tz or ctx.spec.timezone or "UTC")


def _time_timetable(ctx: CodegenContext, sched: TimeSchedule, *, as_object: bool) -> ast.expr:
    """Expression for a time-based schedule; ``as_object`` forces a timetable instance
    (required inside ``AssetOrTimeSchedule`` & friends)."""
    if isinstance(sched, PresetSchedule):
        # With a DAG timezone, presets become explicit cron timetables in that timezone.
        if not as_object and (not ctx.spec.timezone or sched.preset in ("@once", "@continuous")):
            return ast.Constant(sched.preset)
        if sched.preset in ("@once", "@continuous"):
            raise CodegenError(f"{sched.preset} cannot be combined with asset conditions")
        return ctx.call(
            ctx.sdk("CronTriggerTimetable"),
            ast.Constant(sched.preset),
            timezone=_tz(ctx, None),
        )
    if isinstance(sched, CronSchedule):
        if sched.data_interval:
            return ctx.call(
                ctx.sdk("CronDataIntervalTimetable"),
                ast.Constant(sched.expression),
                timezone=_tz(ctx, sched.timezone),
            )
        simple = not (
            sched.timezone or ctx.spec.timezone or sched.interval_seconds or sched.run_immediately
        )
        if simple and not as_object:
            return ast.Constant(sched.expression)
        kws: dict[str, ast.expr] = {"timezone": _tz(ctx, sched.timezone)}
        if sched.interval_seconds:
            kws["interval"] = ctx.timedelta(sched.interval_seconds)
        if sched.run_immediately:
            kws["run_immediately"] = ast.Constant(True)
        return ctx.call(ctx.sdk("CronTriggerTimetable"), ast.Constant(sched.expression), **kws)
    if isinstance(sched, IntervalSchedule):
        delta = ctx.timedelta(sched.seconds)
        if sched.data_interval:
            return ctx.call(ctx.sdk("DeltaDataIntervalTimetable"), delta)
        return ctx.call(ctx.sdk("DeltaTriggerTimetable"), delta) if as_object else delta
    if isinstance(sched, MultiCronSchedule):
        return ctx.call(
            ctx.sdk("MultipleCronTriggerTimetable"),
            *(ast.Constant(e) for e in sched.expressions),
            timezone=_tz(ctx, sched.timezone),
        )
    assert isinstance(sched, EventsSchedule)
    kws = {"event_dates": ast.List(elts=[ctx.datetime(d) for d in sched.dates], ctx=ast.Load())}
    if sched.restrict_to_events:
        kws["restrict_to_events"] = ast.Constant(True)
    if sched.description:
        kws["description"] = ast.Constant(sched.description)
    return ctx.call(ctx.sdk("EventsTimetable"), **kws)


def _schedule(ctx: CodegenContext) -> ast.expr:
    sched = ctx.spec.schedule
    if isinstance(sched, NoSchedule):
        return ast.Constant(None)
    if isinstance(sched, AssetSchedule):
        assets = ctx.asset_expr(sched.expression)
        if sched.batch_asset_events is None:
            return assets
        return ctx.call(
            ctx.sdk("AssetTriggeredTimetable"),
            assets=assets,
            batch_asset_events=ast.Constant(sched.batch_asset_events),
        )
    if isinstance(sched, AssetOrTimeScheduleSpec):
        return ctx.call(
            ctx.sdk("AssetOrTimeSchedule"),
            timetable=_time_timetable(ctx, sched.time, as_object=True),
            assets=ctx.asset_expr(sched.expression),
        )
    if isinstance(sched, AssetAndTimeScheduleSpec):
        return ctx.call(
            ctx.sdk("AssetAndTimeSchedule"),
            timetable=_time_timetable(ctx, sched.time, as_object=True),
            assets=ctx.asset_expr(sched.expression),
        )
    if isinstance(sched, PartitionedCronSchedule):
        kws: dict[str, ast.expr] = {"timezone": ast.Constant(sched.timezone)}
        if sched.key_format:
            kws["key_format"] = ast.Constant(sched.key_format)
        return ctx.call(ctx.sdk("CronPartitionTimetable"), ast.Constant(sched.expression), **kws)
    if isinstance(sched, PartitionedAssetSchedule):
        mapper_kws: dict[str, ast.expr] = {}
        if sched.timezone and sched.mapper != "identity":
            mapper_kws["timezone"] = ast.Constant(sched.timezone)
        mapper = ctx.call(ctx.sdk(_MAPPERS[sched.mapper]), **mapper_kws)
        return ctx.call(
            ctx.sdk("PartitionedAssetTimetable"),
            assets=ctx.asset_expr(sched.expression),
            default_partition_mapper=mapper,
        )
    return _time_timetable(ctx, sched, as_object=False)


def _deadline(ctx: CodegenContext, d: DeadlineSpec) -> ast.expr:
    ref_cls = ctx.sdk("DeadlineReference")
    ref: ast.expr = ast.Attribute(value=ref_cls, attr=_DEADLINE_REFS[d.reference], ctx=ast.Load())
    if d.reference == "fixed_datetime":
        assert d.fixed_datetime is not None
        ref = ctx.call(ref, ctx.datetime(d.fixed_datetime))
    elif d.reference == "average_runtime":
        ref = ctx.call(
            ref, **({"max_runs": ast.Constant(d.average_max_runs)} if d.average_max_runs else {})
        )
    callback_kws: dict[str, ast.expr] = {}
    if d.callback.params:
        callback_kws["kwargs"] = ctx.value(d.callback.params)
    callback = ctx.call(
        ctx.sdk("SyncCallback" if d.synchronous else "AsyncCallback"),
        ctx.import_path(d.callback.notifier),
        **callback_kws,
    )
    interval = (
        ctx.timedelta(d.interval_seconds)
        if d.interval_seconds >= 0
        else ast.UnaryOp(op=ast.USub(), operand=ctx.timedelta(-d.interval_seconds))
    )
    kws: dict[str, ast.expr] = {"reference": ref, "interval": interval, "callback": callback}
    if d.name:
        kws["name"] = ast.Constant(d.name)
    return ctx.call(ctx.sdk("DeadlineAlert"), **kws)


def _default_args(ctx: CodegenContext) -> ast.expr | None:
    da = ctx.spec.default_args
    keys: list[ast.expr | None] = []
    values: list[ast.expr] = []
    for name in (
        "owner",
        "retries",
        "depends_on_past",
        "email",
        "email_on_failure",
        "pool",
        "queue",
    ):
        val = getattr(da, name)
        if val is not None:
            keys.append(ast.Constant(name))
            values.append(ctx.value(val))
    if da.retry_delay_seconds is not None:
        keys.append(ast.Constant("retry_delay"))
        values.append(ctx.timedelta(da.retry_delay_seconds))
    if da.execution_timeout_seconds is not None:
        keys.append(ast.Constant("execution_timeout"))
        values.append(ctx.timedelta(da.execution_timeout_seconds))
    return ast.Dict(keys=keys, values=values) if keys else None


def _params(ctx: CodegenContext) -> ast.expr:
    keys: list[ast.expr | None] = []
    values: list[ast.expr] = []
    for name, param in ctx.spec.params.items():
        kws = [ast.keyword(arg=k, value=ctx.value(v)) for k, v in param.schema_kwargs().items()]
        keys.append(ast.Constant(name))
        values.append(
            ast.Call(func=ctx.sdk("Param"), args=[ctx.value(param.default)], keywords=kws)
        )
    return ast.Dict(keys=keys, values=values)


# --------------------------------------------------------------------------- nodes


def _function(
    name: str,
    body: list[ast.stmt],
    decorators: list[ast.expr],
    args: list[str] | None = None,
    *,
    kwonly: list[str] | None = None,
    kwarg: str | None = None,
) -> ast.FunctionDef:
    func = ast.FunctionDef(
        name=name,
        args=ast.arguments(
            posonlyargs=[],
            args=[ast.arg(arg=a) for a in args or []],
            vararg=None,
            kwonlyargs=[ast.arg(arg=a) for a in kwonly or []],
            kw_defaults=[ast.Constant(None) for _ in kwonly or []],
            kwarg=ast.arg(arg=kwarg) if kwarg else None,
            defaults=[],
        ),
        body=body or [ast.Pass()],
        decorator_list=decorators,
        returns=None,
    )
    if sys.version_info >= (3, 12):
        func.type_params = []
    return func


def _loop_group(ctx: CodegenContext, group: TaskGroupNode, body: list[ast.stmt]) -> list[ast.stmt]:
    """``@task_group`` function holding the body, then ``group = body.loop(...)`` (3.4+)."""
    assert group.loop is not None
    var = ctx.node_var(group.id)
    fn_name = ctx.reserve_function_name(f"{var}_body")
    kws = [ast.keyword(arg="group_id", value=ast.Constant(group.group_id))]
    if group.tooltip:
        kws.append(ast.keyword(arg="tooltip", value=ast.Constant(group.tooltip)))
    if not group.prefix_group_id:
        kws.append(ast.keyword(arg="prefix_group_id", value=ast.Constant(False)))
    if group.parent_group:
        kws.append(
            ast.keyword(
                arg="parent_group",
                value=ast.Name(id=ctx.node_var(group.parent_group), ctx=ast.Load()),
            )
        )
    stmts: list[ast.stmt] = [
        _function(fn_name, body, [ast.Call(func=ctx.sdk("task_group"), args=[], keywords=kws)])
    ]
    loop_kws: dict[str, ast.expr] = {"max_iterations": ast.Constant(group.loop.max_iterations)}
    if group.loop.until_code:
        try:
            until_body = ast.parse(group.loop.until_code, filename=f"<until {group.group_id}>").body
        except SyntaxError as exc:
            raise CodegenError(
                f"until condition syntax error: {exc.msg} (line {exc.lineno})", group.id
            ) from exc
        until_name = ctx.reserve_function_name(group.loop.until_name)
        prelude = ast.parse('loop = context["loop"]').body
        stmts.append(_function(until_name, prelude + until_body, [], kwarg="context"))
        loop_kws["until"] = ast.Name(id=until_name, ctx=ast.Load())
    loop_call = ast.Call(
        func=ast.Attribute(value=ast.Name(id=fn_name, ctx=ast.Load()), attr="loop", ctx=ast.Load()),
        args=[],
        keywords=[ast.keyword(arg=k, value=v) for k, v in loop_kws.items()],
    )
    stmts.append(_assign(var, loop_call))
    return stmts


_LINEAGE_MODULE = "airflow.providers.openlineage.utils.selective_enable"


def _lineage(ctx: CodegenContext, spec: DagSpec) -> list[ast.stmt]:
    """OpenLineage selective enable/disable (``[openlineage] selective_enable``)."""
    stmts: list[ast.stmt] = []

    def call(fn: str, target: str) -> None:
        stmts.append(
            ast.Expr(
                value=ctx.call(
                    ctx.import_name(_LINEAGE_MODULE, fn), ast.Name(id=target, ctx=ast.Load())
                )
            )
        )

    if spec.lineage != "inherit":
        call("enable_lineage" if spec.lineage == "enabled" else "disable_lineage", "dag")
    for node in spec.task_nodes(include_disabled=False):
        if node.lineage != "inherit" and node.parent_group not in {
            g.id for g in spec.group_nodes() if g.loop is not None
        }:
            call(
                "enable_lineage" if node.lineage == "enabled" else "disable_lineage",
                ctx.node_var(node.id),
            )
    return stmts


def _task_group(ctx: CodegenContext, group: TaskGroupNode) -> ast.expr:
    kws = [ast.keyword(arg="group_id", value=ast.Constant(group.group_id))]
    if group.tooltip:
        kws.append(ast.keyword(arg="tooltip", value=ast.Constant(group.tooltip)))
    if not group.prefix_group_id:
        kws.append(ast.keyword(arg="prefix_group_id", value=ast.Constant(False)))
    if group.parent_group:
        kws.append(
            ast.keyword(
                arg="parent_group",
                value=ast.Name(id=ctx.node_var(group.parent_group), ctx=ast.Load()),
            )
        )
    return ast.Call(func=ctx.sdk("TaskGroup"), args=[], keywords=kws)


def _operator(ctx: CodegenContext, node: OperatorNode) -> ast.expr:
    cls = ctx.import_path(node.operator)
    mapping = node.mapping
    expand = mapping.expand if mapping else {}
    params = [
        ast.keyword(arg=k, value=_operator_value(ctx, node, k, v))
        for k, v in node.params.items()
        if k not in expand
    ]
    kwargs = ctx.task_kwargs(node) + params
    if mapping is None:
        return ast.Call(func=cls, args=[], keywords=kwargs)
    partial = ast.Call(
        func=ast.Attribute(value=cls, attr="partial", ctx=ast.Load()), args=[], keywords=kwargs
    )
    return _map(ctx, partial, mapping)


def _is_hitl(fqn: str) -> bool:
    return ".operators.hitl." in fqn


def _operator_value(ctx: CodegenContext, node: OperatorNode, name: str, value: object) -> ast.expr:
    """HITL operators take a form definition in ``params``: the builder stores it as
    ``{name: DagParam}`` and it becomes ``{name: Param(default, **schema)}``."""
    if _is_hitl(node.operator) and name == "params" and isinstance(value, dict):
        keys: list[ast.expr | None] = []
        values: list[ast.expr] = []
        for pname, pdef in value.items():
            keys.append(ast.Constant(pname))
            if isinstance(pdef, dict) and "$type" not in pdef:
                param = DagParam.model_validate(pdef)
                values.append(
                    ast.Call(
                        func=ctx.sdk("Param"),
                        args=[ctx.value(param.default)],
                        keywords=[
                            ast.keyword(arg=k, value=ctx.value(v))
                            for k, v in param.schema_kwargs().items()
                        ],
                    )
                )
            else:
                values.append(ctx.value(pdef))
        return ast.Dict(keys=keys, values=values)
    return ctx.value(coerce_timedelta(node.operator, name, value))


def _map(ctx: CodegenContext, target: ast.expr, mapping: MappingSpec) -> ast.expr:
    if mapping.expand_kwargs is not None:
        return ast.Call(
            func=ast.Attribute(value=target, attr="expand_kwargs", ctx=ast.Load()),
            args=[ctx.value(mapping.expand_kwargs)],
            keywords=[],
        )
    return ast.Call(
        func=ast.Attribute(value=target, attr="expand", ctx=ast.Load()),
        args=[],
        keywords=[ast.keyword(arg=k, value=ctx.value(v)) for k, v in mapping.expand.items()],
    )


def _decorator(ctx: CodegenContext, node: PythonTaskNode) -> ast.expr:
    task_ref: ast.expr = ctx.sdk("task")
    if node.decorator != "task":
        task_ref = ast.Attribute(value=task_ref, attr=node.decorator, ctx=ast.Load())
    kws = ctx.task_kwargs(node)
    if node.multiple_outputs:
        kws.append(ast.keyword(arg="multiple_outputs", value=ast.Constant(True)))
    kws += [ast.keyword(arg=k, value=ctx.value(v)) for k, v in node.decorator_kwargs.items()]
    return ast.Call(func=task_ref, args=[], keywords=kws)


def _python_task(ctx: CodegenContext, node: PythonTaskNode) -> list[ast.stmt]:
    try:
        user_body = ast.parse(
            normalize_task_body(node.code) or "pass", filename=f"<task {node.task_id}>"
        ).body
    except SyntaxError as exc:
        raise CodegenError(f"python syntax error: {exc.msg} (line {exc.lineno})", node.id) from exc
    expand = node.mapping.expand if node.mapping else {}
    arg_names = list(dict.fromkeys([*node.arguments, *expand, *node.extra_parameters]))
    fn_name = ctx.reserve_function_name(node.function_name)
    decorators = [_decorator(ctx, node)]
    if node.is_result:
        decorators.insert(0, ctx.sdk("result"))
    func = _function(
        fn_name,
        user_body,
        decorators,
        arg_names,
        kwonly=["loop"] if node.uses_loop_context else None,
    )
    fn_ref = ast.Name(id=fn_name, ctx=ast.Load())
    call_kws = [
        ast.keyword(arg=k, value=ctx.value(v)) for k, v in node.arguments.items() if k not in expand
    ]
    call: ast.expr
    if node.mapping is not None:
        partial = ast.Call(
            func=ast.Attribute(value=fn_ref, attr="partial", ctx=ast.Load()),
            args=[],
            keywords=call_kws,
        )
        call = _map(ctx, partial, node.mapping)
    else:
        call = ast.Call(func=fn_ref, args=[], keywords=call_kws)
    return [func, _assign(ctx.node_var(node.id), call)]


def _custom(ctx: CodegenContext, node: CustomNode, registry: HandlerRegistry) -> ast.expr:
    try:
        handler = registry.get(node.handler)
    except KeyError as exc:
        raise CodegenError(str(exc), node.id) from exc
    config = handler.config_model.model_validate(node.config)
    return handler.build(node, config, ctx)


def _plain_value(ctx: CodegenContext, value: object, node_id: str) -> ast.expr:
    """A blueprint config value: JSON only, since it is validated by a Pydantic model at
    parse time (an XCom reference or tagged object would not survive that)."""
    if isinstance(value, dict):
        if "$type" in value:
            raise CodegenError("blueprint config values must be plain JSON", node_id)
        for v in value.values():
            _plain_value(ctx, v, node_id)
    elif isinstance(value, list):
        for v in value:
            _plain_value(ctx, v, node_id)
    return ctx.value(value)


def _blueprint(ctx: CodegenContext, node: BlueprintNode) -> list[ast.stmt]:
    """``bp = Template(); bp.step_id = "..."; g = bp.render(Config(...))``: how the blueprint
    project documents using a template in a Python DAG. Inside a task group the render runs
    under ``with <group>:`` so the rendered TaskGroup/task is created in it."""
    module, _, class_name = node.class_path.rpartition(".")
    cls = ctx.import_name(module, class_name)
    instance = ctx.reserve_function_name(f"{node.step_id}_blueprint")
    config_type: ast.expr
    if node.config_class:
        config_type = ctx.import_name(module, node.config_class)
    else:
        config_type = ast.Call(
            func=ast.Attribute(value=cls, attr="get_config_type", ctx=ast.Load()),
            args=[],
            keywords=[],
        )
    if all(k.isidentifier() and not keyword.iskeyword(k) for k in node.config):
        config: ast.expr = ast.Call(
            func=config_type,
            args=[],
            keywords=[
                ast.keyword(arg=k, value=_plain_value(ctx, v, node.id))
                for k, v in node.config.items()
            ],
        )
    else:
        config = ast.Call(
            func=ast.Attribute(value=config_type, attr="model_validate", ctx=ast.Load()),
            args=[_plain_value(ctx, node.config, node.id)],
            keywords=[],
        )
    render = _assign(
        ctx.node_var(node.id),
        ast.Call(
            func=ast.Attribute(
                value=ast.Name(id=instance, ctx=ast.Load()), attr="render", ctx=ast.Load()
            ),
            args=[config],
            keywords=[],
        ),
    )
    stmts: list[ast.stmt] = [
        _assign(instance, ast.Call(func=cls, args=[], keywords=[])),
        ast.Assign(
            targets=[
                ast.Attribute(
                    value=ast.Name(id=instance, ctx=ast.Load()), attr="step_id", ctx=ast.Store()
                )
            ],
            value=ast.Constant(node.step_id),
        ),
    ]
    if node.parent_group:
        parent = ast.Name(id=ctx.node_var(node.parent_group), ctx=ast.Load())
        stmts.append(ast.With(items=[ast.withitem(context_expr=parent)], body=[render]))
    else:
        stmts.append(render)
    return stmts


def _setup_teardown(
    ctx: CodegenContext, node: TaskNode, edges: list[EffectiveEdge]
) -> list[ast.stmt]:
    ref = ast.Name(id=ctx.node_var(node.id), ctx=ast.Load())
    if node.is_setup:
        return [ast.Expr(value=ctx.call(ast.Attribute(value=ref, attr="as_setup", ctx=ast.Load())))]
    if node.is_teardown:
        nodes = ctx.nodes
        setups = [
            e.source
            for e in edges
            if e.target == node.id and getattr(nodes.get(e.source), "is_setup", False)
        ]
        kws: dict[str, ast.expr] = {}
        if setups:
            kws["setups"] = ast.List(
                elts=[ast.Name(id=ctx.node_var(s), ctx=ast.Load()) for s in setups],
                ctx=ast.Load(),
            )
        return [
            ast.Expr(
                value=ctx.call(ast.Attribute(value=ref, attr="as_teardown", ctx=ast.Load()), **kws)
            )
        ]
    return []


# --------------------------------------------------------------------------- edges


def _edges(ctx: CodegenContext, edges: list[EffectiveEdge]) -> list[ast.stmt]:
    stmts: list[ast.stmt] = []
    unlabeled: dict[str, list[str]] = defaultdict(list)

    def ref(node_id: str) -> ast.expr:
        return ast.Name(id=ctx.node_var(node_id), ctx=ast.Load())

    for edge in edges:
        if edge.label:
            label = ast.Call(func=ctx.sdk("Label"), args=[ast.Constant(edge.label)], keywords=[])
            chain = ast.BinOp(
                left=ast.BinOp(left=ref(edge.source), op=ast.RShift(), right=label),
                op=ast.RShift(),
                right=ref(edge.target),
            )
            stmts.append(ast.Expr(value=chain))
        else:
            unlabeled[edge.source].append(edge.target)
    plain: list[ast.stmt] = []
    for source, targets in unlabeled.items():
        right: ast.expr = (
            ref(targets[0])
            if len(targets) == 1
            else ast.List(elts=[ref(t) for t in targets], ctx=ast.Load())
        )
        plain.append(ast.Expr(value=ast.BinOp(left=ref(source), op=ast.RShift(), right=right)))
    return plain + stmts


# --------------------------------------------------------------------------- ordering


def _assign(name: str, value: ast.expr) -> ast.Assign:
    return ast.Assign(targets=[ast.Name(id=name, ctx=ast.Store())], value=value)


def _ordered_groups(spec: DagSpec) -> list[TaskGroupNode]:
    groups = {g.id: g for g in spec.group_nodes()}
    ordered: list[TaskGroupNode] = []
    state: dict[str, int] = {}

    def visit(g: TaskGroupNode) -> None:
        if state.get(g.id) == 2:
            return
        if state.get(g.id) == 1:
            raise CodegenError(f"task group nesting cycle at {g.id!r}", g.id)
        state[g.id] = 1
        if g.parent_group:
            parent = groups.get(g.parent_group)
            if parent is None:
                raise CodegenError(f"unknown parent group {g.parent_group!r}", g.id)
            visit(parent)
        state[g.id] = 2
        ordered.append(g)

    for g in groups.values():
        visit(g)
    return ordered


def node_values(node: TaskNode) -> list[object]:
    """Every user value of a task node that may contain XCom references."""
    values: list[object] = []
    if isinstance(node, OperatorNode):
        values = list(node.params.values())
    elif isinstance(node, PythonTaskNode):
        values = list(node.arguments.values())
    elif isinstance(node, CustomNode):
        values = list(node.config.values())
    if node.mapping:
        values.extend(node.mapping.expand.values())
        if node.mapping.expand_kwargs is not None:
            values.append(node.mapping.expand_kwargs)
    return values


def _xcom_deps(node: TaskNode) -> list[str]:
    return [r.node for v in node_values(node) for r in iter_xcom_refs(v)]


def _ordered_tasks(spec: DagSpec) -> list[TaskNode]:
    """Spec order, except that XCom producers are defined before their consumers."""
    tasks = {t.id: t for t in spec.task_nodes(include_disabled=False)}
    ordered: list[TaskNode] = []
    state: dict[str, int] = {}

    def visit(t: TaskNode) -> None:
        if state.get(t.id) == 2:
            return
        if state.get(t.id) == 1:
            raise CodegenError(f"circular XCom references at {t.id!r}", t.id)
        state[t.id] = 1
        for dep in _xcom_deps(t):
            if dep not in tasks:
                raise CodegenError(f"XCom reference to unknown or disabled task {dep!r}", t.id)
            visit(tasks[dep])
        state[t.id] = 2
        ordered.append(t)

    for t in tasks.values():
        visit(t)
    return ordered
