@dataclass(frozen=True)
class EffectiveEdge:
    source: str
    target: str
    label: str | None


def build_module(
    spec: DagSpec,
    registry: HandlerRegistry | None = None,
    *,
    airflow_version: tuple[int, int, int] | None = None,
) -> ast.Module:
    """Build the DAG module AST; imports target ``airflow_version`` (default: installed)."""
    registry = registry or default_registry()
    ctx = CodegenContext(spec, airflow_version=airflow_version)
    body: list[ast.stmt] = []
    edges = effective_edges(spec)
    loops = {g.id: g for g in spec.group_nodes() if g.loop is not None}
    loop_members: dict[str, list[str]] = {gid: [] for gid in loops}
    for t in spec.task_nodes(include_disabled=False):
        if t.parent_group in loops:
            loop_members[t.parent_group].append(t.id)
            ctx.in_loop_body.add(t.id)

    for group in _ordered_groups(spec):
        if group.id not in loops:
            body.append(_assign(ctx.node_var(group.id), _task_group(ctx, group)))

    post: list[ast.stmt] = []
    loop_bodies: dict[str, list[ast.stmt]] = {gid: [] for gid in loops}
    loop_post: dict[str, list[ast.stmt]] = {gid: [] for gid in loops}
    for node in _ordered_tasks(spec):
        target = loop_bodies[node.parent_group] if node.parent_group in loops else body
        if isinstance(node, OperatorNode):
            target.append(_assign(ctx.node_var(node.id), _operator(ctx, node)))
        elif isinstance(node, PythonTaskNode):
            target.extend(_python_task(ctx, node))
        else:
            target.append(_assign(ctx.node_var(node.id), _custom(ctx, node, registry)))
        stmts = _setup_teardown(ctx, node, edges)
        (loop_post[node.parent_group] if node.parent_group in loops else post).extend(stmts)

    for bp in spec.blueprint_nodes(include_disabled=False):
        if bp.parent_group in loops:
            raise CodegenError("blueprint steps cannot be placed in a loop group", bp.id)
        body.extend(_blueprint(ctx, bp))

    outer_edges = edges
    for gid, group in loops.items():
        members = set(loop_members[gid])
        inner = [e for e in edges if e.source in members and e.target in members]
        outer_edges = [e for e in outer_edges if e not in inner]
        body.extend(_loop_group(ctx, group, loop_bodies[gid] + loop_post[gid] + _edges(ctx, inner)))

    body.extend(post)
    body.extend(_edges(ctx, outer_edges))
    body.extend(_lineage(ctx, spec))
    if not body:
        body.append(ast.Pass())

    with_dag = ast.With(
        items=[
            ast.withitem(
                context_expr=ast.Call(func=ctx.sdk("DAG"), args=[], keywords=_dag_kwargs(ctx)),
                optional_vars=ast.Name(id="dag", ctx=ast.Store()),
            )
        ],
        body=body,
    )
    docstring = ast.Expr(value=ast.Constant(HEADER.format(dag_id=spec.dag_id)))
    module = ast.Module(
        body=[docstring, *ctx.import_statements(), *ctx.module_defs, with_dag], type_ignores=[]
    )
    return ast.fix_missing_locations(module)


def generate_source(
    spec: DagSpec,
    registry: HandlerRegistry | None = None,
    *,
    airflow_version: tuple[int, int, int] | None = None,
) -> str:
    """Unformatted (but valid) Python source for ``spec``."""
    return ast.unparse(build_module(spec, registry, airflow_version=airflow_version)) + "\n"


# --------------------------------------------------------------------------- graph


def effective_edges(spec: DagSpec) -> list[EffectiveEdge]:
    """Edges between generated tasks/groups.

    Disabled tasks are removed and bridged (``a >> disabled >> b`` becomes ``a >> b``);
    notes never take part in the graph.
    """
    nodes = spec.node_map()

    def active(node_id: str) -> bool:
        n = nodes.get(node_id)
        if n is None or n.kind == "note":
            return False
        return not getattr(n, "disabled", False)

    edges = [EffectiveEdge(e.source, e.target, e.label) for e in spec.edges]
    disabled = [n.id for n in spec.nodes if n.kind != "note" and getattr(n, "disabled", False)]
    for d in disabled:
        preds = [e for e in edges if e.target == d]
        succs = [e for e in edges if e.source == d]
        edges = [e for e in edges if d not in (e.source, e.target)]
        for p in preds:
            for s in succs:
                if p.source != s.target:
                    edges.append(EffectiveEdge(p.source, s.target, s.label or p.label))
    seen: set[tuple[str, str]] = set()
    out: list[EffectiveEdge] = []
    for e in edges:
        if active(e.source) and active(e.target) and (e.source, e.target) not in seen:
            seen.add((e.source, e.target))
            out.append(e)
    return out


