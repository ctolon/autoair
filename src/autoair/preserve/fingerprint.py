"""Generator fingerprint of deployed DAG files.

Every Python file AutoAir generates starts with one comment line carrying a hash of the
rest of the file::

    # autoair:fingerprint sha256=<64 hex digits>

The fingerprint makes a file self-verifying: a file whose fingerprint still matches its
content is exactly what AutoAir wrote, even where the target keeps no AutoAir state (a
copied file, a repository restored from elsewhere). A mismatch means the file was edited by
hand (*ejected*). Files without the line are hand-written or come from AutoAir before 0.2.0;
for those the deploy targets' recorded hashes (``.autoair/state``) decide.

The line is a comment, so Airflow, the generated docstring and the ownership marker
(``Generated by AutoAir`` within the first 500 characters) are unaffected.
"""

from __future__ import annotations

import hashlib
import re
from typing import Literal

FINGERPRINT_PREFIX = "# autoair:fingerprint sha256="
_LINE = re.compile(r"\A# autoair:fingerprint sha256=([0-9a-f]{64})[ \t]*\r?\n")

FingerprintState = Literal["valid", "mismatch", "absent"]


def _digest(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def split(content: str) -> tuple[str | None, str]:
    """``(fingerprint, body)``: the recorded hash (None without the line) and the rest."""
    m = _LINE.match(content)
    if m is None:
        return None, content
    return m.group(1), content[m.end() :]


def add(content: str) -> str:
    """``content`` with a (fresh) fingerprint line in front."""
    _, body = split(content)
    return f"{FINGERPRINT_PREFIX}{_digest(body)}\n{body}"


def refresh(content: str) -> str:
    """Recompute the fingerprint of a file that has one; files without it stay as they are."""
    recorded, _ = split(content)
    return add(content) if recorded is not None else content


def strip(content: str) -> str:
    """``content`` without its fingerprint line (a file that is no longer generated)."""
    return split(content)[1]


def state(content: str) -> FingerprintState:
    recorded, body = split(content)
    if recorded is None:
        return "absent"
    return "valid" if recorded == _digest(body) else "mismatch"


__all__ = ["FINGERPRINT_PREFIX", "FingerprintState", "add", "refresh", "split", "state", "strip"]
