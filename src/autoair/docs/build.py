"""Build the packaged copy of AutoAir's own documentation from the website sources.

The documentation site (``website/docs/**``, published at https://ctolon.github.io/autoair/)
is written in Markdown/MDX. This module turns it into one data file shipped in the wheel,
``autoair/docs/pages.json``, which the documentation MCP tools and the knowledge base's
``autoair`` source read offline (:mod:`autoair.docs.index`):

* front matter ``title`` / ``description`` become fields, the page route its ``path``;
* MDX is reduced to Markdown the way ``website/scripts/llms-txt.mjs`` does it for
  ``llms-full.txt``: ``<Screenshot>`` / ``<Video>`` become their text, admonitions become
  bold labels, imports/exports and comments are dropped, code blocks are kept verbatim;
* site links become absolute URLs of the published site;
* the configuration reference comes from ``docs/configuration-reference.md`` (the site's
  copy is generated by ``npm run sync`` and gitignored), with the front matter that
  ``website/scripts/sync-reference.mjs`` gives it.

Standard library only: the wheel build hook (``hatch_build.py``) loads this file by path
in hatchling's isolated build environment, where AutoAir's dependencies are not installed::

    uv run python -m autoair.docs.build            # write src/autoair/docs/pages.json
    uv run python -m autoair.docs.build --out F    # write F instead
"""

from __future__ import annotations

import argparse
import json
import os
import posixpath
import re
import sys
from pathlib import Path
from typing import Any

FORMAT = 1
KIND = "autoair-docs"
DATA_FILE = "pages.json"
#: Pages the site generates from repository files (never read from website/docs).
_GENERATED_PAGES = frozenset({"reference/configuration.md"})
_CONFIG_SOURCE = "docs/configuration-reference.md"
_CONFIG_ROUTE = "reference/configuration"

_FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
_FENCE = re.compile(r"^\s*(`{3,}|~{3,})")
_FENCE_TITLE = re.compile(r"^(\s*`{3,}\w*)\s+title=.*$")
_COMPONENT = re.compile(r"^\s*<(Screenshot|Video)\b")
_IMPORT = re.compile(r"^\s*import\s.+from\s|^\s*export\s")
_ADMONITION = re.compile(r"^:::(\w+)(?:\s+(.*))?$")
_ADMONITION_END = re.compile(r"^:::\s*$")
_JSX_COMMENT = re.compile(r"\{/\*.*?\*/\}")
_HTML_COMMENT = re.compile(r"<!--.*?-->")
_ESCAPE = re.compile(r"\\([{}<>])")
_LINK = re.compile(r"\]\(([^)\s]+)\)")
_H1 = re.compile(r"^# .*\n+", re.MULTILINE)
_BLANKS = re.compile(r"\n{3,}")


class BuildError(ValueError):
    """The sources are missing or not in the expected shape."""


# --------------------------------------------------------------------------- site


def site_urls(root: Path) -> tuple[str, str]:
    """(origin, base path) of the published site, as ``website/site.config.ts`` computes
    them (the same ``DOCS_*`` environment variables override them)."""
    config = (root / "website" / "site.config.ts").read_text(encoding="utf-8")

    def default(name: str) -> str:
        m = re.search(rf"{name}\s*=\s*process\.env\.DOCS_{name}\s*\?\?\s*'([^']+)'", config)
        if not m:
            raise BuildError(f"website/site.config.ts: cannot read the default of {name}")
        return m.group(1)

    owner = os.environ.get("DOCS_GITHUB_OWNER") or default("GITHUB_OWNER")
    repo = os.environ.get("DOCS_GITHUB_REPO") or default("GITHUB_REPO")
    # The defaults are computed from the owner and repository; a different expression
    # would make the URLs below wrong, so it fails the build instead.
    for name, expected in (
        ("SITE_URL", "?? `https://${GITHUB_OWNER}.github.io`"),
        ("BASE_URL", "?? `/${GITHUB_REPO}/`"),
    ):
        if expected not in config:
            raise BuildError(f"website/site.config.ts: unexpected default of {name}")
    origin = os.environ.get("DOCS_URL") or f"https://{owner}.github.io"
    base = os.environ.get("DOCS_BASE_URL") or f"/{repo}/"
    if not base.endswith("/"):
        base += "/"
    return origin.rstrip("/"), base


def _absolute(origin: str, base: str, path: str) -> str:
    if path.startswith(base):
        return origin + path
    return origin + base + path.lstrip("/")


def _sync_links(root: Path) -> dict[str, str]:
    """Repository doc -> site route (``LINKS`` of ``website/scripts/sync-reference.mjs``)."""
    text = (root / "website" / "scripts" / "sync-reference.mjs").read_text(encoding="utf-8")
    block = re.search(r"const LINKS = \{(.*?)\};", text, re.DOTALL)
    links = dict(re.findall(r"'([^']+\.md)':\s*'([^']+)'", block.group(1) if block else ""))
    if not links:
        raise BuildError("website/scripts/sync-reference.mjs: LINKS not found")
    return links


def _sync_front_matter(root: Path) -> tuple[str, str]:
    """Title and description the site gives the configuration reference."""
    text = (root / "website" / "scripts" / "sync-reference.mjs").read_text(encoding="utf-8")
    title = re.search(r"\btitle:\s*'([^']+)'", text)
    description = re.search(r"\bdescription:\s*'([^']+)'", text)
    if not title or not description:
        raise BuildError("website/scripts/sync-reference.mjs: front matter not found")
    return title.group(1), description.group(1)


# --------------------------------------------------------------------------- pages


def _scalar(value: str) -> Any:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] == '"':
        try:
            return json.loads(value)
        except ValueError:
            return value[1:-1]
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    if value in ("true", "false"):
        return value == "true"
    if value in ("null", "~", ""):
        return None
    return value


def front_matter(text: str) -> tuple[dict[str, Any], str]:
    """(front matter, body) of a page. Only the flat ``key: value`` YAML the site uses;
    folded (``>``) and literal (``|``) blocks are joined into one line."""
    m = _FRONT.match(text)
    if not m:
        return {}, text
    data: dict[str, Any] = {}
    key: str | None = None
    for line in m.group(1).splitlines():
        if key and line.startswith((" ", "\t")):
            data[key] = f"{data[key]} {line.strip()}".strip()
            continue
        name, sep, value = line.partition(":")
        if not sep or not name.strip() or name.startswith((" ", "#")):
            key = None
            continue
        key = name.strip()
        data[key] = "" if value.strip() in (">", "|", ">-", "|-") else _scalar(value)
        if data[key] != "":
            key = None
    return data, text[m.end() :]


def _attr(tag: str, name: str) -> str | None:
    m = re.search(rf"""\b{name}=(?:"([^"]*)"|'([^']*)'|\{{["'`]([^"'`]*)["'`]\}})""", tag)
    if not m:
        return None
    return next(g for g in m.groups() if g is not None)


def to_markdown(body: str, link: Any) -> str:
    """Markdown of an MDX page body (``llms-txt.mjs``'s rules); ``link(target)`` rewrites
    one link target and returns it unchanged when it is not a site link."""
    out: list[str] = []
    fence: str | None = None
    lines = body.replace("\r\n", "\n").split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        opener = _FENCE.match(line)
        if fence:
            if opener and opener.group(1)[0] == fence[0] and len(opener.group(1)) >= len(fence):
                fence = None
            out.append(line)
            continue
        if opener:
            fence = opener.group(1)
            out.append(_FENCE_TITLE.sub(r"\1", line))
            continue
        if _COMPONENT.match(line):
            # A component may span several lines: collect up to its closing "/>".
            while not re.search(r"/>\s*$", line) and i < len(lines):
                line += " " + lines[i].strip()
                i += 1
            kind = re.search(r"<(\w+)", line).group(1)  # type: ignore[union-attr]
            text = _attr(line, "alt") if kind == "Screenshot" else _attr(line, "title")
            caption = _attr(line, "caption")
            label = text or _attr(line, "name") or ""
            out.append(f"[{kind}: {label}{f' ({caption})' if caption else ''}]")
            continue
        if _IMPORT.match(line):
            continue
        admonition = _ADMONITION.match(line)
        if admonition:
            kind = admonition.group(1).capitalize()
            title = admonition.group(2)
            out.append(f"**{kind}: {title}**" if title else f"**{kind}:**")
            continue
        if _ADMONITION_END.match(line):
            continue
        line = _JSX_COMMENT.sub("", line)
        line = _HTML_COMMENT.sub("", line)
        line = _ESCAPE.sub(r"\1", line)
        line = _LINK.sub(lambda m: f"]({link(m.group(1))})", line)
        out.append(line)
    text = _H1.sub("", "\n".join(out), count=1)
    return _BLANKS.sub("\n\n", text).strip() + "\n"


def _route(rel: str, meta: dict[str, Any]) -> str:
    """Docs route of ``website/docs/<rel>`` (``ai/mcp``), as Docusaurus derives it."""
    stem = re.sub(r"\.mdx?$", "", rel)
    folder, _, name = stem.rpartition("/")
    slug = meta.get("slug")
    if isinstance(slug, str) and slug:
        return slug.strip("/") if slug.startswith("/") else posixpath.join(folder, slug).strip("/")
    if isinstance(meta.get("id"), str) and meta["id"]:
        name = str(meta["id"])
    if name.lower() in ("index", "readme") and folder:
        return folder
    return posixpath.join(folder, name) if folder else name


def _linker(origin: str, base: str, routes: dict[str, str], here: str) -> Any:
    def link(target: str) -> str:
        if target.startswith("pathname://"):
            return _absolute(origin, base, target[len("pathname://") :])
        if target.startswith("/"):
            return _absolute(origin, base, target)
        path, _, anchor = target.partition("#")
        if re.search(r"\.mdx?$", path) and "://" not in path:
            rel = posixpath.normpath(posixpath.join(posixpath.dirname(here), path))
            if rel in routes:
                url = _absolute(origin, base, f"/docs/{routes[rel]}")
                return f"{url}#{anchor}" if anchor else url
        return target

    return link


def build(root: Path) -> dict[str, Any]:
    """The documentation data of the repository at ``root``."""
    docs = root / "website" / "docs"
    if not docs.is_dir():
        raise BuildError(f"{docs} does not exist (not a source checkout)")
    origin, base = site_urls(root)
    files: dict[str, tuple[dict[str, Any], str]] = {}
    routes: dict[str, str] = {}
    for path in sorted(docs.rglob("*")):
        if path.suffix not in (".md", ".mdx") or not path.is_file():
            continue
        rel = path.relative_to(docs).as_posix()
        if rel in _GENERATED_PAGES or any(p.startswith(("_", ".")) for p in rel.split("/")):
            continue
        meta, body = front_matter(path.read_text(encoding="utf-8"))
        if meta.get("draft") is True or meta.get("unlisted") is True:
            continue
        files[rel] = (meta, body)
        routes[rel] = _route(rel, meta)
    pages: list[dict[str, Any]] = []
    for rel, (meta, body) in files.items():
        route = routes[rel]
        title = meta.get("title")
        if not isinstance(title, str) or not title:
            h1 = re.search(r"^# (.+)$", body, re.MULTILINE)
            title = h1.group(1).strip() if h1 else route
        description = meta.get("description")
        pages.append(
            {
                "path": route,
                "url": _absolute(origin, base, f"/docs/{route}"),
                "title": title,
                "description": description if isinstance(description, str) else "",
                "section": route.split("/", 1)[0] if "/" in route else "",
                "source": f"website/docs/{rel}",
                "markdown": to_markdown(body, _linker(origin, base, routes, rel)),
            }
        )
    config = root / _CONFIG_SOURCE
    if config.is_file():
        links = _sync_links(root)
        title, description = _sync_front_matter(root)

        def config_link(target: str) -> str:
            path, _, anchor = target.partition("#")
            if path in links:
                url = _absolute(origin, base, links[path])
                return f"{url}#{anchor}" if anchor else url
            return target

        pages.append(
            {
                "path": _CONFIG_ROUTE,
                "url": _absolute(origin, base, f"/docs/{_CONFIG_ROUTE}"),
                "title": title,
                "description": description,
                "section": _CONFIG_ROUTE.split("/", 1)[0],
                "source": _CONFIG_SOURCE,
                "markdown": to_markdown(config.read_text(encoding="utf-8"), config_link),
            }
        )
    pages.sort(key=lambda p: str(p["path"]))
    seen: set[str] = set()
    for page in pages:
        if page["path"] in seen:
            raise BuildError(f"two pages share the route /docs/{page['path']}")
        seen.add(page["path"])
    if not pages:
        raise BuildError(f"no documentation pages under {docs}")
    return {
        "kind": KIND,
        "format": FORMAT,
        "base_url": _absolute(origin, base, "/"),
        "docs_url": _absolute(origin, base, "/docs/"),
        "llms_txt": _absolute(origin, base, "/llms.txt"),
        "pages": pages,
    }


def render(data: dict[str, Any]) -> str:
    # One page per line: a documentation change shows up as a change of that page only.
    head = {k: v for k, v in data.items() if k != "pages"}
    lines = [json.dumps(p, ensure_ascii=False, sort_keys=True) for p in data["pages"]]
    body = ",\n".join(lines)
    return json.dumps(head, sort_keys=True)[:-1] + ', "pages": [\n' + body + "\n]}\n"


def write(root: Path, out: Path | None = None) -> Path:
    target = out or root / "src" / "autoair" / "docs" / DATA_FILE
    text = render(build(root))
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        target.write_text(text, encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[3])
    parser.add_argument("--out", type=Path, default=None, help="output file")
    args = parser.parse_args(argv)
    try:
        path = write(args.root, args.out)
    except (BuildError, OSError) as exc:
        print(f"autoair docs build: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
