"""Reads follow the environment's git branch (0.2.3 review, B03)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from autoair.spec import DagSpec
from autoair.storage.config import GitStorageSettings, StorageSettings
from autoair.storage.git import GitTarget
from tests.integration.test_iam_api import as_role, git_repo, make_client, make_services

__all__ = ["git_repo"]  # pytest fixture used below

SRC = '"""Generated by AutoAir"""\nprint("dev")\n'


def _client(tmp_path: Path, repo: Path) -> Any:
    storage = StorageSettings(
        mode="git",
        git=GitStorageSettings(  # type: ignore[call-arg]
            provider="local",
            repo=f"file://{repo}",
            mode="push",
            cache_dir=tmp_path / "cache",
            base_branch="main",
            environments={"dev": "dev", "prod": "main"},
        ),
    )
    services = make_services(tmp_path, storage=storage, default_environment="dev")
    return services, make_client(services)


def test_a_dag_saved_to_the_dev_branch_is_listed_and_opened(
    tmp_path: Path, git_repo: Path, simple_spec_data: dict[str, Any]
) -> None:
    """B03: with default_environment=dev the DAG lives only on the dev branch; GET and the
    list used to read the base branch (404 and [])."""
    services, client = _client(tmp_path, git_repo)
    target = services.ensure_target()
    assert isinstance(target, GitTarget)
    target.provider.create_branch("dev", target.provider.head("main"))
    spec = DagSpec.model_validate({**simple_spec_data, "dag_id": "dev_only"})
    target.save(spec, {"dev_only.py": SRC}, environment="dev")
    headers = as_role("Viewer")

    assert client.get("/api/specs/dev_only", headers=headers).status_code == 200
    listed = client.get("/api/specs", headers=headers).json()
    assert [s["dag_id"] for s in listed] == ["dev_only"]
    history = client.get("/api/vcs/dev_only/history", headers=headers)
    assert history.status_code == 200, history.text
    assert history.json()

    # The prod branch (main) does not have it.
    assert client.get("/api/specs/dev_only?environment=prod", headers=headers).status_code == 404
    assert client.get("/api/specs?environment=prod", headers=headers).json() == []
