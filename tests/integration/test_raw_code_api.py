"""Raw code DAGs through the API: gating, storage, versions, listing, env preview."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pytest
from fastapi.testclient import TestClient

from tests.integration.test_iam_api import as_role, make_client, make_services

pytestmark = pytest.mark.airflow

CODE = """from airflow.sdk import DAG

with DAG(dag_id="raw_api", schedule=None):
    pass
"""
RAW: dict[str, Any] = {"dag_id": "raw_api", "raw_code": CODE, "tags": ["handmade"]}
VISUAL: dict[str, Any] = {
    "dag_id": "visual_env",
    "environments": {"prod": {"tags": ["prod_only"], "connections": {"db": "db_prod"}}},
    "nodes": [
        {
            "kind": "operator",
            "id": "a",
            "task_id": "a",
            "operator": "airflow.providers.standard.operators.empty.EmptyOperator",
        }
    ],
}


def client(tmp_path: Path, **settings: Any) -> TestClient:
    return make_client(make_services(tmp_path, import_check_on_deploy=False, **settings))


def deploy(c: TestClient, role: str, spec: dict[str, Any] = RAW) -> Any:
    return c.put(f"/api/specs/{spec['dag_id']}", json={"spec": spec}, headers=as_role(role))


def test_raw_deploy_needs_code_raw(tmp_path: Path) -> None:
    c = client(tmp_path, iam={"roles": {"Writer": ["builder:use", "spec:*", "deploy"]}})
    denied = deploy(c, "Writer")
    assert denied.status_code == 403
    assert "code:raw" in denied.text
    # A visual DAG needs no code:raw.
    visual = {**RAW, "raw_code": None, "dag_id": "plain"}
    assert deploy(c, "Writer", visual).status_code == 200
    preview = c.post(
        "/api/specs/raw_api/deploy-preview", json={"spec": RAW}, headers=as_role("Writer")
    )
    assert preview.status_code == 403


def test_raw_deploy_writes_the_code_as_written(tmp_path: Path) -> None:
    c = client(tmp_path)
    res = deploy(c, "Admin")
    assert res.status_code == 200, res.text
    body = res.json()
    assert body["deployed"], body
    written = (tmp_path / "dags" / "raw_api.py").read_text()
    assert written.startswith("# Generated by AutoAir from the raw code DAG 'raw_api'.")
    assert written.endswith(CODE)
    listed = c.get("/api/specs", headers=as_role("Viewer")).json()
    assert [(s["dag_id"], s["document_type"]) for s in listed] == [("raw_api", "raw")]
    stored = c.get("/api/specs/raw_api", headers=as_role("Viewer")).json()
    assert stored["spec"]["raw_code"] == CODE
    # A second version: history and a diff of the code field.
    changed = {**RAW, "raw_code": CODE.replace("pass", "print('hi')")}
    assert deploy(c, "Admin", changed).json()["deployed"]
    history = c.get("/api/vcs/raw_api/history", headers=as_role("Viewer")).json()
    assert len(history) == 2
    diff = c.get(
        "/api/vcs/raw_api/diff",
        params={"from": history[-1]["version"]},
        headers=as_role("Viewer"),
    ).json()
    assert [f["path"] for f in diff["changed_fields"]] == ["raw_code"]


def test_invalid_raw_code_is_not_written(tmp_path: Path) -> None:
    c = client(tmp_path)
    res = deploy(c, "Admin", {**RAW, "raw_code": "def broken(:\n"})
    body = res.json()
    assert body["status"] == "invalid"
    (problem,) = body["report"]["problems"]
    assert problem["code"] == "syntax"
    assert problem["line"] == 1
    assert not (tmp_path / "dags" / "raw_api.py").exists()


@pytest.mark.parametrize(
    "features", [{"python_code": False}, {"code_editor": False}], ids=["python", "code_editor"]
)
def test_raw_writes_follow_the_features(tmp_path: Path, features: dict[str, bool]) -> None:
    c = client(tmp_path, features=features)
    assert deploy(c, "Admin").status_code == 404


def test_code_only_and_visual_only_meta(tmp_path: Path) -> None:
    code_only = client(tmp_path, features={"visual_editor": False})
    flags = code_only.get("/api/meta", headers=as_role("Viewer")).json()["features"]
    assert flags["visual_editor"] is False
    assert flags["code_editor"] is True
    visual_only = client(tmp_path / "v", features={"code_editor": False})
    sync = visual_only.post(
        "/api/interchange/python/sync", json={"source": CODE}, headers=as_role("Admin")
    )
    assert sync.status_code == 404


def test_both_editors_off_is_a_configuration_error(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match=r"at least one of features\.visual_editor"):
        make_services(tmp_path, features={"visual_editor": False, "code_editor": False})


def test_codegen_environment_preview(tmp_path: Path) -> None:
    c = client(tmp_path)
    base = c.post("/api/codegen", json=VISUAL, headers=as_role("Viewer")).json()
    prod = c.post(
        "/api/codegen", params={"environment": "prod"}, json=VISUAL, headers=as_role("Viewer")
    ).json()
    assert "prod_only" in prod["code"]
    assert "prod_only" not in base["code"]
    unknown = c.post(
        "/api/codegen", params={"environment": "nope"}, json=VISUAL, headers=as_role("Viewer")
    )
    assert unknown.status_code == 400
    raw_env = {**RAW, "environments": {"prod": {}}}
    same = c.post(
        "/api/codegen", params={"environment": "prod"}, json=raw_env, headers=as_role("Viewer")
    ).json()
    assert same["code"].endswith(CODE)


def test_test_runs_of_raw_code_follow_the_python_policy(tmp_path: Path) -> None:
    c = client(tmp_path, allow_python_code=False)
    res = c.post("/api/runner/test-dag", json={"spec": RAW}, headers=as_role("Admin"))
    assert res.status_code == 403
    assert "allow_python_code" in res.text
