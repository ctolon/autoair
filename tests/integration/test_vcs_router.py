from __future__ import annotations

from types import SimpleNamespace

import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

from autoair.api.routers import vcs
from autoair.spec import DagSpec
from autoair.storage import LocalFolderTarget

SRC = '"""Generated by AutoAir"""\nprint("v1")\n'


def make_client(services) -> TestClient:
    app = FastAPI()
    app.state.services = services
    app.include_router(vcs.router)
    return TestClient(app)


@pytest.fixture
def target(tmp_path):
    return LocalFolderTarget(tmp_path)


@pytest.fixture
def client(target):
    return make_client(SimpleNamespace(target=target, registry=None))


def test_status_and_missing_target(client):
    resp = client.get("/vcs/status")
    assert resp.status_code == 200
    assert resp.json()["kind"] == "local"
    resp = make_client(SimpleNamespace()).get("/vcs/status")
    assert resp.status_code == 501


def test_history_versions_and_diff(client, target, simple_spec_data):
    spec = DagSpec.model_validate(simple_spec_data)
    first = target.save(spec, {"simple.py": SRC}, author="alice")
    target.save(spec.model_copy(update={"description": "v2"}), {"simple.py": SRC})

    history = client.get("/vcs/simple/history", params={"limit": 10}).json()
    assert [h["version"] for h in history][-1] == first.version
    assert history[-1]["author"] == "alice"

    resp = client.get(f"/vcs/simple/versions/{first.version}")
    assert resp.status_code == 200
    assert DagSpec.model_validate(resp.json()) == spec
    assert client.get("/vcs/simple/versions/20000101T000000000000Z-00000000").status_code == 404
    assert client.get("/vcs/simple/versions/current").json()["description"] == "v2"

    diff = client.get("/vcs/simple/diff", params={"from": first.version}).json()
    assert [c["path"] for c in diff["changed_fields"]] == ["description"]
    assert not diff["identical"]
    assert client.get("/vcs/nope/diff", params={"from": "current"}).status_code == 404
    assert client.get("/vcs/simple/diff").status_code == 422


def test_diff_and_merge_endpoints(client, simple_spec_data):
    a = simple_spec_data
    b = {**simple_spec_data, "description": "changed"}
    resp = client.post("/vcs/diff", json={"a": a, "b": b})
    assert resp.status_code == 200
    assert resp.json()["changed_fields"][0]["after"] == "changed"

    theirs = {**simple_spec_data, "tags": ["x"]}
    merged = client.post("/vcs/merge", json={"base": a, "ours": b, "theirs": theirs}).json()
    assert merged["conflicts"] == []
    assert merged["merged"]["description"] == "changed"
    assert merged["merged"]["tags"] == ["x"]

    clash = {**simple_spec_data, "description": "other"}
    result = client.post("/vcs/merge", json={"base": a, "ours": b, "theirs": clash}).json()
    assert result["merged"] is None
    assert result["conflicts"][0]["path"] == "description"


