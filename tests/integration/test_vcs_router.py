def test_promote_on_git_target(tmp_path, simple_spec_data):
    import shutil
    import subprocess

    if shutil.which("git") is None:
        pytest.skip("git not installed")
    from autoair.storage.git import GitTarget, LocalGitProvider

    bare = tmp_path / "remote.git"
    subprocess.run(["git", "init", "--bare", "-q", "-b", "main", str(bare)], check=True)
    target = GitTarget(
        LocalGitProvider(str(bare), tmp_path / "cache"),
        mode="push",
        environments={"dev": "main", "prod": "prod"},
    )
    spec = DagSpec.model_validate({**simple_spec_data, "output_mode": "loader"})
    target.save(spec, {"simple.py": SRC}, environment="dev")
    # "prod" branch must exist to open a promotion against it
    target.provider.create_branch("prod", target.provider.head("main"))
    client = make_client(SimpleNamespace(target=target, registry=None))
    resp = client.post("/vcs/simple/promote", json={"from_env": "dev", "to_env": "prod"})
    assert resp.status_code == 200, resp.text
    body = resp.json()
    assert body["branch"] == "autoair/promote/dev-to-prod/simple"
    content, _ = target.provider.get_file(body["branch"], "simple.py")
    assert "load_dag(__file__)" in content  # re-rendered as a loader stub
    resp = client.post("/vcs/simple/promote", json={"from_env": "dev", "to_env": "qa"})
    assert resp.status_code == 400
