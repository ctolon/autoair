"""POST /api/vcs/{dag_id}/promote validates like a deploy to the target environment."""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from autoair.api.app import build_services, create_app
from autoair.auth import AuthBackend
from autoair.settings import Settings
from autoair.spec import DagSpec

pytestmark = pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")

SRC = '"""Generated by AutoAir"""\nprint("v1")\n'

RULES = [
    {
        "id": "no-bash-prod",
        "match": {"environments": ["prod"], "operators": ["BashOperator"]},
        "check": "forbid",
    }
]


def _client(tmp_path: Path, spec: DagSpec) -> tuple[TestClient, object]:
    from autoair.storage.git import GitTarget, LocalGitProvider

    bare = tmp_path / "remote.git"
    subprocess.run(["git", "init", "--bare", "-q", "-b", "main", str(bare)], check=True)
    target = GitTarget(
        LocalGitProvider(str(bare), tmp_path / "cache"),
        mode="push",
        environments={"dev": "main", "prod": "prod", "qa": "qa"},
    )
    target.save(spec, {f"{spec.dag_id}.py": SRC}, environment="dev")
    for branch in ("prod", "qa"):
        target.provider.create_branch(branch, target.provider.head("main"))
    settings = Settings(
        dags_folder=tmp_path / "dags",
        subfolder="",
        policy={"rules": RULES},
        import_check_on_deploy=False,
    )
    services = build_services(settings, AuthBackend())
    services.catalog.refresh = lambda: services.catalog.stats()  # type: ignore[method-assign]
    services.target = target
    return TestClient(create_app(services)), target


def test_promotion_is_refused_when_the_target_environment_fails_validation(
    tmp_path, simple_spec_data
):
    spec = DagSpec.model_validate(
        {**simple_spec_data, "environments": {"dev": {}, "prod": {}, "qa": {}}}
    )
    client, target = _client(tmp_path, spec)

    resp = client.post("/api/vcs/simple/promote", json={"from_env": "dev", "to_env": "prod"})
    assert resp.status_code == 422, resp.text
    detail = resp.json()["detail"]
    assert detail["status"] == "invalid"
    assert detail["message"].startswith("validation failed for environment 'prod'")
    codes = {p["code"] for p in detail["report"]["problems"] if p["severity"] == "error"}
    assert codes == {"policy_rule"}
    assert not detail["report"]["ok"]
    # nothing was written: no promotion branch
    assert target.provider.head("autoair/promote/dev-to-prod/simple") is None  # type: ignore[attr-defined]

    # the same spec is fine for an environment the rule does not match
    ok = client.post("/api/vcs/simple/promote", json={"from_env": "dev", "to_env": "qa"})
    assert ok.status_code == 200, ok.text
    assert ok.json()["branch"] == "autoair/promote/dev-to-qa/simple"
    message = subprocess.run(
        [
            "git",
            "--git-dir",
            str(tmp_path / "remote.git"),
            "log",
            "-1",
            "--format=%B",
            ok.json()["branch"],
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    assert "Action: promote" in message
    assert "Validation: passed" in message


def test_promotion_to_an_environment_the_spec_does_not_define_is_rejected(
    tmp_path, simple_spec_data
):
    spec = DagSpec.model_validate({**simple_spec_data, "environments": {"dev": {}, "prod": {}}})
    client, _ = _client(tmp_path, spec)
    resp = client.post("/api/vcs/simple/promote", json={"from_env": "dev", "to_env": "qa"})
    assert resp.status_code == 400
    assert resp.json()["detail"] == "unknown environment 'qa'"


def test_invalid_spec_is_not_promoted_without_policy_rules(tmp_path, simple_spec_data):
    data = {
        **simple_spec_data,
        "edges": [{"source": "a", "target": "b"}, {"source": "b", "target": "a"}],
    }
    spec = DagSpec.model_validate(data)
    client, _ = _client(tmp_path, spec)
    resp = client.post("/api/vcs/simple/promote", json={"from_env": "dev", "to_env": "qa"})
    assert resp.status_code == 422, resp.text
    assert resp.json()["detail"]["status"] == "invalid"
