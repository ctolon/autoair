def test_etag_conflict_and_audit(client):
    first = client.put("/api/specs/api_v2", json={"spec": SPEC}).json()
    assert first["deployed"], first
    etag = first["etag"]
    got = client.get("/api/specs/api_v2")
    assert got.headers["etag"] == f'"{etag}"'
    changed = {**SPEC, "description": "v2"}
    ok = client.put("/api/specs/api_v2", json={"spec": changed, "base_etag": etag}).json()
    assert ok["deployed"]
    stale = client.put(
        "/api/specs/api_v2", json={"spec": {**SPEC, "description": "v3"}, "base_etag": etag}
    ).json()
    assert stale["deployed"] is False
    assert stale["conflict"]["current_spec"]["description"] == "v2"
    history = client.get("/api/vcs/api_v2/history").json()
    assert len(history) >= 2
    audit = client.get("/api/specs/api_v2/audit").json()
    assert [r["action"] for r in audit][:2] == ["deploy", "deploy"]


