def test_marketplace_endpoints(tmp_path: Path):
    from autoair.marketplace import MarketplaceSource, build_index, generate_keypair

    pem, public = generate_keypair()
    root = tmp_path / "market"
    (root / "templates").mkdir(parents=True)
    tpl = {
        "id": "one-task",
        "title": "One task",
        "kind": "fragment",
        "fragment": {"nodes": SPEC["nodes"]},
    }
    (root / "templates" / "one-task.json").write_text(json.dumps(tpl))
    (root / "index.json").write_text(json.dumps(build_index(root, "acme", pem)))
    settings = Settings(
        dags_folder=tmp_path / "dags",
        subfolder="",
        ai={"enabled": False},
        marketplace_sources=[
            MarketplaceSource(name="acme", url=(root / "index.json").as_uri(), public_key=public)
        ],
    )
    client = TestClient(create_app(build_services(settings, AuthBackend())))
    listing = client.get("/api/marketplace").json()
    assert listing["sources"][0]["verified"] is True
    assert [e["id"] for e in listing["entries"]] == ["one-task"]
    installed = client.post(
        "/api/marketplace/install", json={"source": "acme", "entry_id": "one-task"}
    )
    assert installed.status_code == 200, installed.text
    assert client.get("/api/templates/one-task").json()["kind"] == "fragment"
    bad = client.post("/api/marketplace/install", json={"source": "nope", "entry_id": "x"})
    assert bad.status_code == 400


def test_import_spec_json_migrates_and_reports(client):
    ok = client.post("/api/interchange/spec/import", json={"source": json.dumps(SPEC)})
    assert ok.status_code == 200, ok.text
    assert ok.json()["spec_version"] == 2
    assert ok.json()["dag_id"] == "api_v2"
    bad = client.post("/api/interchange/spec/import", json={"source": '{"dag_id": "x y"}'})
    assert bad.status_code == 422
    assert "dag_id" in bad.json()["detail"]
    garbage = client.post("/api/interchange/spec/import", json={"source": "not json"})
    assert garbage.status_code == 422


def test_static_cache_headers(client):
    """Hashed chunks are immutable; the fixed-name entry and the page must revalidate."""
    from autoair.api.app import STATIC_DIR

    plugin = STATIC_DIR / "plugin"
    if not (plugin / "main.js").exists():
        pytest.skip("frontend not built")
    chunk = next(p.name for p in plugin.glob("*.js") if p.name != "main.js")
    assert "immutable" in client.get(f"/static/{chunk}").headers["cache-control"]
    assert client.get("/static/main.js").headers["cache-control"] == "no-cache"
    page = client.get("/ui/")
    if page.status_code == 200:
        assert page.headers["cache-control"] == "no-cache"
    gz = client.get("/api/catalog/operators", headers={"Accept-Encoding": "gzip"})
    assert gz.headers.get("content-encoding") == "gzip"
