def test_targets_write_over_a_hand_written_file_only_while_it_is_unchanged(tmp_path: Any) -> None:
    from autoair.storage import EjectedError, StorageError
    from autoair.storage.local import LocalFolderTarget

    target = LocalFolderTarget(tmp_path)
    (tmp_path / "classic.py").write_text(CLASSIC)
    spec = mark_hand_written(SPEC, CLASSIC)
    patched = CLASSIC.replace("echo load", "echo load2")
    with pytest.raises(StorageError, match="not created by AutoAir"):
        target.save(spec, {"classic.py": patched})  # never without the expected hash
    with pytest.raises(EjectedError):
        target.save(spec, {"classic.py": patched}, expected={"classic.py": "0" * 64})
    target.save(
        spec,
        {"classic.py": patched},
        expected={"classic.py": sha256_text(CLASSIC)},
        hand_written=True,
    )
    current = target.current_file("classic")
    assert current is not None
    assert current.content == patched
    assert current.recorded_sha == sha256_text(patched)
    assert current.source_sha == sha256_text(CLASSIC)
    assert current.hand_written is True
    # a generate write over it needs `expected` (a permitted overwrite), even unchanged:
    # the target refuses the kept file itself, whatever path the write took
    with pytest.raises(StorageError, match="deploy:overwrite_ejected"):
        target.save(SPEC, {"classic.py": "x = 1\n"})
    with pytest.raises(StorageError, match="not created by AutoAir"):
        target.save(SPEC, {"classic.py": "x = 1\n"}, allow_hand_written=True)
    # deleting the hand-written file AutoAir keeps needs deploy:overwrite_ejected
    with pytest.raises(StorageError, match="deploy:overwrite_ejected"):
        target.delete("classic")
    assert target.delete("classic", allow_hand_written=True) is True
    assert not (tmp_path / "classic.py").exists()


def test_validation_scans_the_preserved_file() -> None:
    from autoair.validation import Policy, validate_spec

    forbidden = Policy(forbidden_operators=("*.BashOperator",))
    report = validate_spec(SPEC, policy=forbidden, source=CLASSIC)
