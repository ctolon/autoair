def test_overwrite_needs_the_setting_and_the_permission() -> None:
    generated = fingerprint.add(gen(SPEC))
    edited = existing(generated.replace("echo load", "echo LOAD"))
    importer = fake_importer({}, lambda _s: None)
    blocked = plan_source(
        SPEC, existing=edited, stored=SPEC, ctx=ctx(importer), resolution="overwrite"
    )
    assert blocked.action == "blocked"
    assert blocked.refusals[0].code == "overwrite_disabled"
    # ejected_files=overwrite alone does not open it: preserve.allow_force_overwrite is the
    # switch every overwrite needs
    switch_off = ctx(importer, ejected_files="overwrite")
    switch_off.can_overwrite = True
    assert plan_source(SPEC, existing=edited, stored=SPEC, ctx=switch_off).options == [
        "preserve",
        "raw",
    ]
    off = plan_source(SPEC, existing=edited, stored=SPEC, ctx=switch_off, resolution="overwrite")
    assert off.action == "blocked"
    assert "preserve.allow_force_overwrite" in off.message
    block = ctx(importer, allow_force_overwrite=True)
    blocked = plan_source(SPEC, existing=edited, stored=SPEC, ctx=block, resolution="overwrite")
    assert blocked.action == "blocked"
    assert "not allowed" in blocked.refusals[0].message
    allowed_cfg = ctx(importer, ejected_files="overwrite", allow_force_overwrite=True)
    offered = plan_source(SPEC, existing=edited, stored=SPEC, ctx=allowed_cfg)
    assert offered.options == ["preserve", "overwrite", "raw"]
    no_right = plan_source(
        SPEC, existing=edited, stored=SPEC, ctx=allowed_cfg, resolution="overwrite"
    )
    assert no_right.action == "blocked"
    assert "deploy:overwrite_ejected" in no_right.message
    allowed_cfg.can_overwrite = True
    done = plan_source(SPEC, existing=edited, stored=SPEC, ctx=allowed_cfg, resolution="overwrite")
    assert done.action == "generate"
    assert done.overwrite
    assert done.expected_sha == sha256_text(edited.content)


