SPEC = DagSpec.model_validate(CLASSIC_SPEC)


def gen(spec: DagSpec) -> str:
    return render(spec, airflow_version=(3, 3, 2))


def existing(
    content: str, *, recorded: str | None = None, source: str | None = None
) -> ExistingFile:
    return ExistingFile(
        name="classic.py",
        content=content,
        location="/dags/classic.py",
        recorded_sha=recorded,
        source_sha=source,
    )


# --------------------------------------------------------------------------- fingerprints


def test_fingerprint_round_trip() -> None:
    body = '"""Generated by AutoAir"""\nx = 1\n'
    stamped = fingerprint.add(body)
    assert stamped.startswith(fingerprint.FINGERPRINT_PREFIX)
    assert fingerprint.state(stamped) == "valid"
    assert fingerprint.state(stamped.replace("x = 1", "x = 2")) == "mismatch"
    assert fingerprint.state(body) == "absent"
    assert fingerprint.add(stamped) == stamped  # idempotent
    assert fingerprint.refresh(body) == body  # files without one stay without
    edited = stamped.replace("x = 1", "x = 3")
    assert fingerprint.state(fingerprint.refresh(edited)) == "valid"


def test_generated_deploy_files_carry_a_fingerprint() -> None:
    from autoair.storage.render import render_dag_files

    files = render_dag_files(SPEC)
    assert fingerprint.state(files["classic.py"]) == "valid"
    raw = DagSpec.model_validate({"dag_id": "raw", "raw_code": "x = 1\n"})
    assert fingerprint.state(render_dag_files(raw)["raw.py"]) == "absent"


# --------------------------------------------------------------------------- classification


def test_classify_target_files() -> None:
    generated = fingerprint.add(gen(SPEC))
    assert classify(None, SPEC) == "absent"
    assert classify(existing(generated), SPEC) == "clean"  # valid fingerprint, no state
    edited = generated.replace("echo load", "echo LOAD")
    assert classify(existing(edited), SPEC) == "ejected"  # fingerprint mismatch
    assert classify(existing(CLASSIC), SPEC) == "foreign"  # hand-written, never deployed
    assert classify(existing(CLASSIC, recorded=sha256_text(CLASSIC)), SPEC) == "clean"
    assert classify(existing(CLASSIC + "\n# x\n", recorded=sha256_text(CLASSIC)), SPEC) == (
        "ejected"
    )
    imported = mark_hand_written(SPEC, CLASSIC)
    # a hand-written file AutoAir never wrote stays foreign, also when the user imported it
    assert classify(existing(CLASSIC), imported) == "foreign"
    kept = existing(CLASSIC, recorded=sha256_text(CLASSIC))
    kept.hand_written = True
    assert classify(kept, SPEC) == "hand_written"  # what a preserve deploy wrote
    old_generated = '"""Generated by AutoAir from the visual DAG spec"""\nx = 1\n'
    assert classify(existing(old_generated), SPEC) == "clean"  # before fingerprints


@pytest.mark.parametrize(
    ("source", "allowed", "enabled", "strict", "expected", "problem"),
    [
        (None, None, True, False, "generate", False),
        (DagSource(origin="python"), None, True, False, "preserve", False),
        (DagSource(origin="python"), None, True, True, "strict-preserve", False),
        (DagSource(origin="python"), None, False, False, "generate", False),
        (
            DagSource(origin="python"),
            ["generate", "strict-preserve"],
            True,
            False,
            "strict-preserve",
            False,
        ),
        (DagSource(policy="preserve"), ["generate"], True, False, "preserve", True),
        (DagSource(policy="strict-preserve"), None, False, False, "generate", True),
        (DagSource(policy="generate", origin="python"), None, True, True, "generate", False),
    ],
)
def test_resolve_policy(
    source: DagSource | None,
    allowed: list[str] | None,
    enabled: bool,
    strict: bool,
    expected: str,
    problem: bool,
) -> None:
    cfg = PreserveSettings(**({"allowed_policies": allowed} if allowed else {}))
    spec = SPEC.model_copy(update={"source": source})
    policy, issue = resolve_policy(spec, cfg, preserve_enabled=enabled, force_strict=strict)
    assert policy == expected
    assert (issue is not None) == problem


# --------------------------------------------------------------------------- plans


Lookup = Callable[[str], DagSpec | None]


def fake_importer(known: dict[str, DagSpec], fallback: Lookup) -> Any:
    calls: list[int] = []

    def run(sources: Sequence[tuple[str, str]], timeout: float) -> list[PythonImportResult]:
        calls.append(len(sources))
        out = []
        for source, _name in sources:
            spec = known.get(source) or fallback(source)
            dags = [ImportedDag(dag_id="classic", spec=spec, warnings=[])] if spec else []
            out.append(PythonImportResult(dags=dags, import_errors=[] if spec else ["boom"]))
        return out

    run.calls = calls  # type: ignore[attr-defined]
    return run


def ctx(importer: Any, **cfg: Any) -> PlanContext:
    return PlanContext(
        cfg=PreserveSettings(cache_ttl=0, **cfg),
        preserve_enabled=True,
        force_strict=False,
        render=gen,
        importer=importer,
        can_overwrite=cfg.pop("can_overwrite", False) if "can_overwrite" in cfg else False,
    )


def changed_spec() -> DagSpec:
    data = copy.deepcopy(CLASSIC_SPEC)
    node(data, "load")["params"]["bash_command"] = "echo load --full"
    return mark_hand_written(DagSpec.model_validate(data), CLASSIC)


def test_preserve_plan_patches_the_hand_written_source() -> None:
    new = changed_spec()
    # the importer reads the file as the original spec, the patched file as the new one
    importer = fake_importer({CLASSIC: SPEC}, lambda src: new if "--full" in src else None)
    plan = plan_source(new, existing=None, stored=None, ctx=ctx(importer))
    assert plan.action == "preserve", plan.refusals
    assert plan.policy == "preserve"
    assert plan.base == "source"
    assert plan.uses_source_code
    assert plan.source is not None
    assert "# every day" in plan.source
    assert '+    load = BashOperator(task_id="load", bash_command="echo load --full")' in plan.diff
    assert "-    load = BashOperator" in plan.diff  # diff against the hand-written base
    assert importer.calls == [1, 1, 1]  # every file in its own subprocess


def test_round_trip_mismatch_rejects_the_patch() -> None:
    new = changed_spec()
    wrong = copy.deepcopy(CLASSIC_SPEC)
    node(wrong, "load")["params"]["bash_command"] = "echo something else"
    wrong_spec = DagSpec.model_validate(wrong)
    gen_new = gen(new.model_copy(update={"source": None}))

    def lookup(src: str) -> DagSpec | None:
        if src == gen_new:
            return new
        return wrong_spec  # the patched file imports as something else

    plan = plan_source(
        new, existing=None, stored=None, ctx=ctx(fake_importer({CLASSIC: SPEC}, lookup))
    )
    assert plan.action == "refused"
    assert plan.refusals[0].code == "roundtrip"
    assert "bash_command" in plan.refusals[0].message
    assert plan.source is None  # never regenerated as a fallback
    assert set(plan.options) == {"raw", "generate"}


