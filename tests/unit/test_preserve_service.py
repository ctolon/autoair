def test_base_selection_prefers_new_source_code() -> None:
    patched = CLASSIC.replace("echo load", "echo load2")
    # the target holds what the last preserve deploy wrote (recorded) from source CLASSIC
    target = existing(patched, recorded=sha256_text(patched), source=sha256_text(CLASSIC))
    spec = mark_hand_written(SPEC, CLASSIC)
    data = copy.deepcopy(CLASSIC_SPEC)
    node(data, "load")["params"]["bash_command"] = "echo load2"
    target_spec = DagSpec.model_validate(data)
    importer = fake_importer({patched: target_spec, CLASSIC: SPEC}, lambda _s: None)
    stale = plan_source(spec, existing=target, stored=None, ctx=ctx(importer))
    assert stale.base == "target"  # same code as deployed last: patch the target's file
    edited = CLASSIC.replace("# the start marker", "# the start marker (edited)")
    fresh = plan_source(
        mark_hand_written(SPEC, edited),
        existing=target,
        stored=None,
        ctx=ctx(fake_importer({edited: SPEC}, lambda _s: None)),
    )
    assert fresh.base == "source"  # a code-mode edit: patch that code


