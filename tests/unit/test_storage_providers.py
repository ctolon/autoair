class FakeRepo:
    """Branches -> commit sha; commit sha -> {path: content}."""

    def __init__(self) -> None:
        self._ids = itertools.count(1)
        root = self.sha()
        self.commits: dict[str, dict[str, str]] = {root: {"README.md": "hi"}}
        self.parents: dict[str, str | None] = {root: None}
        self.heads: dict[str, str] = {"main": root}
        self.prs: list[dict[str, object]] = []
        self.requests: list[httpx2.Request] = []

    def sha(self) -> str:
        return hashlib.sha1(str(next(self._ids)).encode()).hexdigest()

    def tree(self, ref: str) -> dict[str, str] | None:
        return self.commits.get(self.heads.get(ref, ref))

    def commit(self, branch: str, changes: dict[str, str | None]) -> str:
        parent = self.heads[branch]
        files = dict(self.commits[parent])
        for path, content in changes.items():
            if content is None:
                files.pop(path, None)
            else:
                files[path] = content
        new = self.sha()
        self.commits[new] = files
        self.parents[new] = parent
        self.heads[branch] = new
        return new


