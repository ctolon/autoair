def github_app(repo: FakeRepo):
    def handler(request: httpx2.Request) -> httpx2.Response:
        repo.requests.append(request)
        assert request.headers["Authorization"] == "Bearer tok"
        path = unquote(request.url.path)
        prefix = "/repos/acme/dags"
        if path == "/graphql":
            body = json.loads(request.content)
            inp = body["variables"]["input"]
            assert "createCommitOnBranch" in body["query"]
            assert inp["branch"]["repositoryNameWithOwner"] == "acme/dags"
            branch = inp["branch"]["branchName"]
            if repo.heads.get(branch) != inp["expectedHeadOid"]:
                return httpx2.Response(
                    200,
                    json={"errors": [{"message": "Expected branch to point to x but it did not"}]},
                )
            changes: dict[str, str | None] = {
                a["path"]: base64.b64decode(a["contents"]).decode()
                for a in inp["fileChanges"]["additions"]
            }
            changes.update({d["path"]: None for d in inp["fileChanges"]["deletions"]})
            oid = repo.commit(branch, changes)
            return httpx2.Response(
                200, json={"data": {"createCommitOnBranch": {"commit": {"oid": oid, "url": "u"}}}}
            )
        assert path.startswith(prefix), path
        path = path[len(prefix) :]
        params = request.url.params
        if path.startswith("/git/ref/heads/"):
            sha = repo.heads.get(path.removeprefix("/git/ref/heads/"))
            if sha is None:
                return httpx2.Response(404, json={"message": "Not Found"})
            return httpx2.Response(200, json={"object": {"sha": sha}})
        if path == "/git/refs" and request.method == "POST":
            body = json.loads(request.content)
            name = body["ref"].removeprefix("refs/heads/")
            if name in repo.heads:
                return httpx2.Response(422, json={"message": "Reference already exists"})
            repo.heads[name] = body["sha"]
            return httpx2.Response(201, json={})
        if path.startswith("/git/refs/heads/") and request.method == "PATCH":
            repo.heads[path.removeprefix("/git/refs/heads/")] = json.loads(request.content)["sha"]
            return httpx2.Response(200, json={})
        if path.startswith("/contents"):
            tree = repo.tree(params["ref"])
            target = path.removeprefix("/contents").strip("/")
            if tree is None:
                return httpx2.Response(404, json={"message": "No commit found"})
            if target in tree:
                content = tree[target]
                return httpx2.Response(
                    200,
                    json={
                        "type": "file",
                        "path": target,
                        "sha": hashlib.sha1(content.encode()).hexdigest(),
                        "encoding": "base64",
                        "content": base64.b64encode(content.encode()).decode(),
                    },
                )
            entries = [
                {"type": "file", "path": p}
                for p in tree
                if (p.rsplit("/", 1)[0] if "/" in p else "") == target
            ]
            if not entries:
                return httpx2.Response(404, json={"message": "Not Found"})
            return httpx2.Response(200, json=entries)
        if path == "/pulls" and request.method == "POST":
            body = json.loads(request.content)
            pr = {
                "html_url": f"https://github.com/acme/dags/pull/{len(repo.prs) + 1}",
                "number": len(repo.prs) + 1,
                **body,
            }
            repo.prs.append(pr)
            return httpx2.Response(201, json=pr)
        if path == "/pulls":
            owner, _, head = params["head"].partition(":")
            assert owner == "acme"
            assert params["state"] == "open"
            return httpx2.Response(200, json=[p for p in repo.prs if p["head"] == head])
        if path == "/commits":
            sha = repo.heads.get(params["sha"], params["sha"])
            out = []
            while sha is not None:
                if params["path"] in repo.commits[sha]:
                    out.append(
                        {
                            "sha": sha,
                            "commit": {
                                "message": "m",
                                "author": {
                                    "name": "Bot",
                                    "email": "b@x",
                                    "date": "2026-01-01T00:00:00Z",
                                },
                            },
                        }
                    )
                sha = repo.parents[sha]
            return httpx2.Response(200, json=out[: int(params["per_page"])])
        raise AssertionError(f"unexpected {request.method} {request.url}")

    return handler


def test_github_provider_request_shapes_and_cas():
    repo = FakeRepo()
    gh = GitHubProvider("acme/dags", "tok", transport=httpx2.MockTransport(github_app(repo)))
    head = gh.head("main")
    assert head == repo.heads["main"]
    assert gh.head("missing") is None
    assert gh.get_file("main", "README.md")[0] == "hi"
    assert gh.get_file("main", "nope.txt") == (None, None)
    sha = gh.commit_files("main", head, {"a/b.py": "x", "README.md": None}, "t\n\nbody", "J <j@x>")
    assert repo.commits[sha] == {"a/b.py": "x"}
    graphql = next(r for r in repo.requests if r.url.path == "/graphql")
    sent = json.loads(graphql.content)["variables"]["input"]
    assert sent["expectedHeadOid"] == head
    assert sent["message"] == {"headline": "t", "body": "body\n\nCo-authored-by: J <j@x>"}
    assert sent["fileChanges"]["deletions"] == [{"path": "README.md"}]
    with pytest.raises(ConflictError):
        gh.commit_files("main", head, {"c": "d"}, "stale", None)
    assert gh.list_files("main", "a") == ["a/b.py"]
    gh.create_branch("feature", sha)
    with pytest.raises(ConflictError):
        gh.create_branch("feature", sha)
    pr = gh.open_pr("feature", "main", "T", "B")
    assert pr is not None
    assert pr.number == 1
    assert gh.find_open_pr("feature") == pr
    assert gh.find_open_pr("other") is None
    [entry] = gh.log("a/b.py", "main", 10)
    assert entry.sha == sha


def test_github_pr_mode_target(simple_spec_data):
    repo = FakeRepo()
    gh = GitHubProvider("acme/dags", "tok", transport=httpx2.MockTransport(github_app(repo)))
    target = GitTarget(gh, base_branch="main", subdir="dags", mode="pr")
    spec = DagSpec.model_validate(simple_spec_data)
    first = target.save(spec, {"simple.py": SRC}, author="alice")
    assert first.branch == "autoair/simple"
    assert first.pr_url == "https://github.com/acme/dags/pull/1"
    assert repo.prs[0]["base"] == "main"
    assert repo.tree("autoair/simple")["dags/simple.py"] == SRC

    stored = target.get("simple")
    assert stored is not None
    assert stored.pending_pr_url == first.pr_url
    second = target.save(spec, {"simple.py": SRC2}, base_etag=stored.etag)
    assert second.pr_url == first.pr_url
    assert len(repo.prs) == 1  # reused

    # The PR is merged elsewhere and closed: the next save recycles the branch.
    repo.heads["main"] = repo.heads["autoair/simple"]
    repo.prs.clear()
    assert target.get("simple").pending_branch is None
    third = target.save(spec.model_copy(update={"description": "3"}), {"simple.py": SRC})
    assert third.pr_url == "https://github.com/acme/dags/pull/1"
    assert repo.parents[repo.heads["autoair/simple"]] == repo.heads["main"]
    assert [s.dag_id for s in target.list()] == ["simple"]
    assert target.history("simple")[0].author == "Bot <b@x>"


@pytest.mark.skipif(not jwt_available(), reason="pyjwt/cryptography missing")
def test_github_app_token_source():
    import jwt
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import rsa

    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    pem = key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    ).decode()
    calls: list[httpx2.Request] = []

    def handler(request: httpx2.Request) -> httpx2.Response:
        calls.append(request)
        assert request.method == "POST"
        assert request.url.path == "/app/installations/42/access_tokens"
        token = request.headers["Authorization"].removeprefix("Bearer ")
        claims = jwt.decode(token, key.public_key(), algorithms=["RS256"])
        assert claims["iss"] == "123"
        return httpx2.Response(201, json={"token": "ghs_x", "expires_at": "2999-01-01T00:00:00Z"})

    source = GitHubAppTokenSource(123, pem, 42, transport=httpx2.MockTransport(handler))
    assert source() == "ghs_x"
    assert source() == "ghs_x"
    assert len(calls) == 1


