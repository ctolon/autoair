"""Every deploy target refuses to replace or remove the hand-written DAG file AutoAir keeps
(``DagState.hand_written``) unless the write is bound to it (``expected``) or the caller
holds ``deploy:overwrite_ejected`` (``allow_hand_written``): writes that skip the source plan
(loader/YAML output modes, raw code, MCP saves, promotions) cannot bypass it."""

from __future__ import annotations

import shutil
import subprocess
import uuid
from pathlib import Path
from typing import Any

import pytest

from autoair.spec import DagSpec
from autoair.storage import StorageError
from autoair.storage.base import sha256_text
from autoair.storage.git import GitTarget, LocalGitProvider
from autoair.storage.local import LocalFolderTarget
from autoair.storage.object import ObjectStorageTarget

HAND = "# airflow dag written by hand\nprint('kept')\n"
OWNED = '"""Generated by AutoAir"""\nprint("generated")\n'


def _spec(data: dict[str, Any], **update: Any) -> DagSpec:
    return DagSpec.model_validate({**data, **update})


def _kept(target: Any, spec: DagSpec) -> None:
    """The DAG's file is a hand-written one AutoAir keeps (a preserve write)."""
    target.save(spec, {"simple.py": HAND}, hand_written=True)


def _file_targets(tmp_path: Path) -> list[Any]:
    return [
        LocalFolderTarget(tmp_path / "dags"),
        ObjectStorageTarget(f"memory://autoair-test-{uuid.uuid4().hex}/dags"),
    ]


@pytest.mark.parametrize("index", [0, 1], ids=["local", "object"])
def test_file_targets_refuse_to_replace_the_kept_file(
    tmp_path: Path, simple_spec_data: dict[str, Any], index: int
) -> None:
    target = _file_targets(tmp_path)[index]
    spec = _spec(simple_spec_data)
    _kept(target, spec)
    # a regenerated python file without the plan's binding (raw code, MCP, render branch)
    with pytest.raises(StorageError, match="deploy:overwrite_ejected"):
        target.save(spec, {"simple.py": OWNED})
    # another output mode: the kept .py would become a stale file that is removed or left
    for mode, files in (
        ("yaml", {"simple.yaml": "dag: {}\n"}),
        ("loader", {"simple.py": '"""AutoAir loader stub"""\n'}),
    ):
        with pytest.raises(StorageError, match="deploy:overwrite_ejected"):
            target.save(_spec(simple_spec_data, output_mode=mode), files)
    assert target.current_file("simple").content == HAND
    # bound to the file it replaces (a source plan): allowed while it is unchanged
    patched = HAND + "# patched\n"
    target.save(spec, {"simple.py": patched}, expected={"simple.py": sha256_text(HAND)})
    assert target.current_file("simple").content == patched
    assert target.current_file("simple").hand_written


@pytest.mark.parametrize("index", [0, 1], ids=["local", "object"])
def test_file_targets_allow_the_permission_holder(
    tmp_path: Path, simple_spec_data: dict[str, Any], index: int
) -> None:
    target = _file_targets(tmp_path)[index]
    spec = _spec(simple_spec_data)
    _kept(target, spec)
    # allowed, but the usual ownership checks still apply: no marker, never overwritten
    with pytest.raises(StorageError, match="not created by AutoAir"):
        target.save(spec, {"simple.py": OWNED}, allow_hand_written=True)
    # a kept file that carries AutoAir's marker (a raw code takeover) can be replaced
    target.save(spec, {"simple.py": OWNED}, expected={"simple.py": sha256_text(HAND)})
    target.save(spec, {"simple.py": OWNED + "# v2\n"}, allow_hand_written=True)
    assert target.current_file("simple").content == OWNED + "# v2\n"


def git(*args: str) -> str:
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout


@pytest.fixture
def provider(tmp_path: Path) -> LocalGitProvider:
    if shutil.which("git") is None:
        pytest.skip("git not installed")
    bare = tmp_path / "remote.git"
    git("init", "--bare", "-q", "-b", "main", str(bare))
    work = tmp_path / "seed"
    git("clone", "-q", str(bare), str(work))
    (work / "README.md").write_text("seed\n")
    git("-C", str(work), "add", ".")
    git("-C", str(work), "-c", "user.name=S", "-c", "user.email=s@x", "commit", "-q", "-m", "s")
    git("-C", str(work), "push", "-q", "origin", "HEAD:main")
    git("-C", str(work), "push", "-q", "origin", "HEAD:dev")
    return LocalGitProvider(str(bare), tmp_path / "cache")


def test_git_target_refuses_to_replace_the_kept_file(
    provider: LocalGitProvider, simple_spec_data: dict[str, Any]
) -> None:
    target = GitTarget(provider, base_branch="main", mode="push")
    spec = _spec(simple_spec_data)
    _kept(target, spec)
    with pytest.raises(StorageError, match="deploy:overwrite_ejected"):
        target.save(spec, {"simple.py": OWNED})
    with pytest.raises(StorageError, match="deploy:overwrite_ejected"):
        target.save(_spec(simple_spec_data, output_mode="yaml"), {"simple.yaml": "dag: {}\n"})
    assert provider.get_file("main", "simple.py")[0] == HAND
    target.save(spec, {"simple.py": HAND + "# p\n"}, expected={"simple.py": sha256_text(HAND)})
    assert provider.get_file("main", "simple.py")[0] == HAND + "# p\n"


def test_git_promotion_refuses_to_replace_the_kept_file(
    provider: LocalGitProvider, simple_spec_data: dict[str, Any]
) -> None:
    target = GitTarget(
        provider, base_branch="main", mode="push", environments={"dev": "dev", "prod": "main"}
    )
    spec = _spec(simple_spec_data)
    target.save(spec, {"simple.py": OWNED}, environment="dev")
    target.save(spec, {"simple.py": HAND}, environment="prod", hand_written=True)
    with pytest.raises(StorageError, match="deploy:overwrite_ejected"):
        target.promote("simple", "dev", "prod")
    with pytest.raises(StorageError, match="deploy:overwrite_ejected"):
        target.promote("simple", "dev", "prod", render=lambda s, env: {"simple.py": OWNED})
    assert provider.get_file("main", "simple.py")[0] == HAND
