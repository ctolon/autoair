"""Raw code DAGs: the document type, its rendering and its validation."""

from __future__ import annotations

import pytest
from pydantic import ValidationError

from autoair.codegen import RAW_HEADER, render, render_raw
from autoair.iam import model as P
from autoair.mcp.iam import RAW_CODE_FEATURES, required_features, required_permissions
from autoair.spec import DagSpec
from autoair.storage.base import canonical_json, is_owned, summary_of, utcnow
from autoair.validation import Policy, validate_spec
from autoair.validation.raw import defined_dag_ids, operator_uses

GOOD = """from datetime import datetime

from airflow.sdk import DAG, task

with DAG(dag_id="raw_one", schedule=None, start_date=datetime(2025, 1, 1), catchup=False):

    @task
    def hello() -> str:
        return "hello"

    hello()
"""


def raw(code: str = GOOD, **extra: object) -> DagSpec:
    return DagSpec.model_validate({"dag_id": "raw_one", "raw_code": code, **extra})


def codes(report_problems: list) -> list[tuple[str, str, int | None]]:  # type: ignore[type-arg]
    return [(p.severity, p.code, p.line) for p in report_problems]


# --------------------------------------------------------------------------- document


def test_raw_document_has_no_graph() -> None:
    with pytest.raises(ValidationError, match="no nodes or edges"):
        DagSpec.model_validate(
            {
                "dag_id": "x",
                "raw_code": GOOD,
                "nodes": [{"kind": "note", "id": "n", "text": "hi"}],
            }
        )
    with pytest.raises(ValidationError, match="output_mode 'python'"):
        DagSpec.model_validate({"dag_id": "x", "raw_code": GOOD, "output_mode": "yaml"})


def test_document_type_and_summary() -> None:
    assert raw().is_raw
    assert raw().document_type == "raw"
    visual = DagSpec(dag_id="v")
    assert not visual.is_raw
    assert visual.document_type == "spec"
    summary = summary_of(raw(), updated_at=utcnow(), dag_file="raw_one.py", etag=None)
    assert summary.document_type == "raw"
    assert summary.task_count == 0


def test_visual_spec_etag_unchanged_by_the_new_field() -> None:
    # Stored etags of existing DAGs must not change (raw_code is omitted when unset).
    assert "raw_code" not in canonical_json(DagSpec(dag_id="v"))


def test_environment_overlays_do_not_change_raw_code() -> None:
    spec = raw(environments={"prod": {"tags": ["prod"], "connections": {"db": "db_prod"}}})
    assert spec.with_environment("prod") is spec
    with pytest.raises(KeyError):
        spec.with_environment("nope")


# --------------------------------------------------------------------------- rendering


def test_render_prepends_the_ownership_marker_once() -> None:
    out = render(raw())
    assert out.startswith(RAW_HEADER.format(dag_id="raw_one"))
    assert out.endswith(GOOD)
    assert is_owned(out)
    marked = raw('"""Generated by AutoAir from the raw code DAG \'raw_one\'."""\n' + GOOD)
    assert render_raw(marked) == marked.raw_code


def test_render_never_reformats() -> None:
    ugly = "x  =  1\n"
    assert render(raw(ugly)).endswith(ugly)


# --------------------------------------------------------------------------- validation


def test_valid_raw_dag() -> None:
    report = validate_spec(raw())
    assert report.ok, report.problems


def test_syntax_error_is_located() -> None:
    report = validate_spec(raw("x = 1\ndef broken(:\n"))
    assert not report.ok
    (problem,) = report.problems
    assert (problem.code, problem.line, problem.field) == ("syntax", 2, "raw_code")


def test_empty_file() -> None:
    report = validate_spec(raw("   \n"))
    assert codes(report.problems) == [("error", "raw_empty", None)]


def test_lint_uses_the_editor_rules() -> None:
    report = validate_spec(raw(GOOD + "print(undefined_name)\n"))
    lint = [p for p in report.problems if p.code.startswith("lint:")]
    assert lint
    assert lint[0].code == "lint:F821"
    assert lint[0].line == GOOD.count("\n") + 1
    assert lint[0].severity == "error"
    assert lint[0].doc_url


def test_hard_coded_secret_warning_has_a_line() -> None:
    report = validate_spec(raw(GOOD + 'api_key = "abcdef123456"\n'))
    secret = [p for p in report.problems if p.code == "secret"]
    assert [(p.severity, p.line) for p in secret] == [("warning", GOOD.count("\n") + 1)]
    assert report.ok


def test_python_code_policy_applies() -> None:
    report = validate_spec(raw(), policy=Policy(allow_python_code=False))
    assert not report.ok
    assert any("allow_python_code" in p.message for p in report.problems)


BASH = """from airflow.sdk import DAG, task
from airflow.providers.standard.operators.bash import BashOperator as Shell
import airflow.operators.bash as legacy

with DAG("raw_one", schedule=None):
    Shell(task_id="a", bash_command="echo a")
    legacy.BashOperator(task_id="b", bash_command="echo b")

    @task.bash
    def c() -> str:
        return "echo c"
"""


def test_privileged_operators_are_found_through_aliases_and_decorators() -> None:
    uses = {path for path, _, _ in operator_uses(__import__("ast").parse(BASH))}
    assert "airflow.providers.standard.operators.bash.BashOperator" in uses
    assert "airflow.operators.bash.BashOperator" in uses
    report = validate_spec(raw(BASH), policy=Policy(allow_privileged_operators=False))
    lines = sorted(p.line or 0 for p in report.problems if p.code == "policy")
    assert lines == [6, 7, 9]
    assert validate_spec(raw(BASH)).ok  # allowed by default


def test_forbidden_operators() -> None:
    policy = Policy(forbidden_operators=("*.BashOperator",))
    report = validate_spec(raw(BASH), policy=policy)
    assert sum(p.code == "policy" and "forbidden" in p.message for p in report.problems) == 3


def test_dag_id_rules_and_mismatch() -> None:
    report = validate_spec(raw(), policy=Policy(dag_id_prefix="team_"))
    assert any(p.code == "policy" and "team_" in p.message for p in report.problems)
    other = validate_spec(DagSpec(dag_id="renamed", raw_code=GOOD))
    mismatch = [p for p in other.problems if p.code == "raw_dag_id"]
    assert mismatch
    assert mismatch[0].severity == "warning"
    assert "raw_one" in mismatch[0].message


def test_defined_dag_ids() -> None:
    import ast

    assert defined_dag_ids(ast.parse(GOOD)) == {"raw_one"}
    assert defined_dag_ids(ast.parse("from airflow.sdk import dag\n@dag\ndef etl(): ...\n")) == {
        "etl"
    }
    assert defined_dag_ids(ast.parse("import os\nDAG(os.environ['X'])\n")) is None


@pytest.mark.airflow
def test_import_check_runs_the_file() -> None:
    report = validate_spec(raw(), import_check=True)
    assert report.ok, report.problems
    assert report.import_check is not None
    assert "raw_one" in report.import_check.dag_ids
    broken = validate_spec(raw(GOOD + "raise RuntimeError('boom')\n"), import_check=True)
    errors = [p for p in broken.problems if p.code == "import"]
    assert errors
    assert errors[0].line == GOOD.count("\n") + 1


# --------------------------------------------------------------------------- MCP classification


def test_mcp_raw_saves_need_code_raw() -> None:
    spec = {"spec": {"dag_id": "x", "raw_code": GOOD}}
    assert P.CODE_RAW in required_permissions("save_dag_spec", spec)
    assert P.CODE_RAW not in required_permissions("save_dag_spec", {"spec": {"dag_id": "x"}})
    assert set(RAW_CODE_FEATURES) <= set(required_features("save_dag_spec", spec))
    assert P.CODE_RAW in required_permissions("save_raw_dag_code")
    assert set(RAW_CODE_FEATURES) <= set(required_features("save_raw_dag_code"))


def test_code_raw_role_grants() -> None:
    assert P.CODE_RAW in P.BUILTIN_ROLES[P.AUTHOR]
    assert P.CODE_RAW in P.BUILTIN_ROLES[P.ADMIN]
    assert P.CODE_RAW not in P.BUILTIN_ROLES[P.VIEWER]
    assert P.CODE_RAW in P.PERMISSION_INFO


def test_blocked_operators_for_test_runs() -> None:
    from autoair.validation.raw import blocked_operators

    assert blocked_operators(BASH, Policy()) == []
    assert len(blocked_operators(BASH, Policy(allow_privileged_operators=False))) == 3
    assert blocked_operators("def x(:", Policy(allow_privileged_operators=False)) == []
