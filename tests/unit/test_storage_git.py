pytestmark = pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")

SRC = '"""Generated by AutoAir"""\nprint("v1")\n'
SRC2 = '"""Generated by AutoAir"""\nprint("v2")\n'


def git(*args, cwd=None):
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True
    ).stdout.strip()


@pytest.fixture
def remote(tmp_path):
    """A bare remote with an initial commit on ``main`` (and a ``dev`` branch)."""
    bare = tmp_path / "remote.git"
    git("init", "--bare", "-q", "-b", "main", str(bare))
    work = tmp_path / "seed"
    git("clone", "-q", str(bare), str(work))
    (work / "README.md").write_text("seed\n")
    git("-C", str(work), "add", ".")
    git(
        "-C",
        str(work),
        "-c",
        "user.name=Seed",
        "-c",
        "user.email=seed@x",
        "commit",
        "-q",
        "-m",
        "seed",
    )
    git("-C", str(work), "push", "-q", "origin", "HEAD:main")
    git("-C", str(work), "push", "-q", "origin", "HEAD:dev")
    return bare


def remote_file(bare, ref, path):
    return git("--git-dir", str(bare), "show", f"{ref}:{path}")


@pytest.fixture
def provider(remote, tmp_path):
    return LocalGitProvider(str(remote), tmp_path / "cache")


def test_provider_basics(provider, remote):
    head = provider.head("main")
    assert head
    assert len(head) == 40
    assert provider.head("nope") is None
    assert provider.get_file("main", "README.md") == (
        "seed\n",
        git("--git-dir", str(remote), "rev-parse", "main:README.md"),
    )
    assert provider.get_file("main", "missing.txt") == (None, None)
    sha = provider.commit_files(
        "main", head, {"dags/a.txt": "A", "README.md": None}, "msg\n\nbody", "Jane <jane@x.io>"
    )
    assert provider.head("main") == sha
    assert provider.list_files("main", "dags") == ["dags/a.txt"]
    assert provider.get_file("main", "README.md") == (None, None)
    [entry] = provider.log("dags/a.txt", "main", 5)
    assert entry.sha == sha
    assert entry.author == "Jane <jane@x.io>"
    assert entry.message == "msg\n\nbody"
    # compare-and-swap: committing on a stale head fails
    with pytest.raises(ConflictError):
        provider.commit_files("main", head, {"x": "y"}, "stale", None)
    provider.create_branch("feature", sha)
    with pytest.raises(ConflictError):
        provider.create_branch("feature", head)  # already exists (at another commit)
    assert provider.open_pr("feature", "main", "t", "b") is None


def test_push_mode(provider, remote, simple_spec_data):
    target = GitTarget(provider, base_branch="main", subdir="dags/autoair", mode="push")
    spec = DagSpec.model_validate(simple_spec_data)
    first = target.save(spec, {"simple.py": SRC}, author="alice", message="create simple")
    assert first.branch == "main"
    assert first.pr_url is None
    assert remote_file(remote, "main", "dags/autoair/simple.py") == SRC.strip()
    assert '"dag_id": "simple"' in remote_file(remote, "main", "dags/autoair/simple.autoair.json")
    assert git("--git-dir", str(remote), "rev-parse", "main") == first.version

    stored = target.get("simple")
    assert stored is not None
    assert stored.spec == spec
    assert stored.etag == first.etag
    assert stored.version == first.version

    spec2 = spec.model_copy(update={"description": "v2"})
    second = target.save(spec2, {"simple.py": SRC2}, base_etag=first.etag, author="bob")
    with pytest.raises(ConflictError) as info:
        target.save(spec, {"simple.py": SRC}, base_etag=first.etag)
    assert info.value.current is not None
    assert info.value.current.etag == second.etag

    history = target.history("simple")
    assert [h.version for h in history] == [second.version, first.version]
    assert history[1].message == "create simple"
    assert target.get_version("simple", first.version) == spec

    [summary] = target.list()
    assert summary.dag_id == "simple"
    assert summary.dag_file.endswith("@main:dags/autoair/simple.py")

    status = target.status()
    assert status.kind == "git"
    assert status.details["head"] == second.version

    unchanged = target.save(spec2, {"simple.py": SRC2})
    assert unchanged.version == second.version

    deleted = target.delete("simple", base_etag=second.etag)
    assert deleted
    assert target.get("simple") is None
    deleted = target.delete("simple")
    assert not deleted


def test_push_mode_detects_foreign_and_ejected_files(provider, remote, simple_spec_data):
    target = GitTarget(provider, base_branch="main", mode="push")
    spec = DagSpec.model_validate(simple_spec_data)
    head = provider.head("main")
    provider.commit_files("main", head, {"simple.py": "# hand written\n"}, "manual", None)
    with pytest.raises(StorageError, match="not created by AutoAir"):
        target.save(spec, {"simple.py": SRC})
    provider.commit_files("main", provider.head("main"), {"simple.py": None}, "rm", None)
    target.save(spec, {"simple.py": SRC})
    provider.commit_files("main", provider.head("main"), {"simple.py": SRC + "# x\n"}, "e", None)
    with pytest.raises(EjectedError):
        target.save(spec, {"simple.py": SRC2})
    assert target.save(spec, {"simple.py": SRC2}, force=True).version


def test_push_mode_retries_when_branch_moves_concurrently(provider, simple_spec_data):
    target = GitTarget(provider, base_branch="main", mode="push")
    spec = DagSpec.model_validate(simple_spec_data)
    original = provider.commit_files
    calls = {"n": 0}

    def racing_commit(branch, base_sha, changes, message, author):
        calls["n"] += 1
        if calls["n"] == 1:  # someone else pushes an unrelated change first
            original(branch, base_sha, {"other.txt": "x"}, "other", None)
        return original(branch, base_sha, changes, message, author)

    provider.commit_files = racing_commit
    result = target.save(spec, {"simple.py": SRC})
    assert calls["n"] == 2
    assert result.version == provider.head("main")


def test_pr_mode_and_pending_branch(provider, remote, simple_spec_data):
    target = GitTarget(provider, base_branch="main", mode="pr")
    spec = DagSpec.model_validate(simple_spec_data)
    base_head = provider.head("main")
    first = target.save(spec, {"simple.py": SRC})
    assert first.branch == "autoair/simple"
    assert first.pr_url is None  # plain git remote: no pull requests
    assert provider.head("main") == base_head  # base untouched
    assert remote_file(remote, "autoair/simple", "simple.py") == SRC.strip()

    stored = target.get("simple")
    assert stored is not None
    assert stored.pending_branch == "autoair/simple"
    second = target.save(
        spec.model_copy(update={"description": "x"}), {"simple.py": SRC2}, base_etag=stored.etag
    )
    assert second.branch == "autoair/simple"
    assert target.list() == []  # list() reads the base branch


def test_environments_and_promotion(provider, remote, simple_spec_data):
    target = GitTarget(
        provider, base_branch="main", mode="push", environments={"dev": "dev", "prod": "main"}
    )
    spec = DagSpec.model_validate(simple_spec_data)
    saved = target.save(spec, {"simple.py": SRC}, environment="dev")
    assert saved.branch == "dev"
    assert target.get("simple", environment="dev") is not None
    assert target.get("simple") is None

    result = target.promote("simple", "dev", "prod")
    assert result.branch == "autoair/promote/dev-to-prod/simple"
    assert remote_file(remote, result.branch, "simple.py") == SRC.strip()

    rendered = target.promote(
        "simple", "dev", "prod", render=lambda s, env: {"simple.py": SRC2.replace("v2", env)}
    )
    assert "prod" in remote_file(remote, rendered.branch, "simple.py")
    with pytest.raises(StorageError):
        target.promote("simple", "dev", "staging")
    with pytest.raises(StorageError):
        target.save(spec, {"simple.py": SRC}, environment="staging")


def test_empty_remote_push_mode(tmp_path, simple_spec_data):
    bare = tmp_path / "empty.git"
    git("init", "--bare", "-q", "-b", "main", str(bare))
    target = GitTarget(LocalGitProvider(str(bare), tmp_path / "c"), mode="push")
    assert target.list() == []
    spec = DagSpec.model_validate(simple_spec_data)
    result = target.save(spec, {"simple.py": SRC})
    assert git("--git-dir", str(bare), "rev-parse", "main") == result.version


