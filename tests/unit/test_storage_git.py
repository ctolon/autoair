def test_build_hosted_targets_and_bundle_discovery(monkeypatch, tmp_path):
    from autoair.storage.git import GitHubProvider, GitLabProvider
    from autoair.storage.git import config as git_config

    gh = build_target(
        StorageSettings(
            mode="git",
            git=GitStorageSettings(
                provider="github", repo="https://github.com/acme/dags.git", token="t"
            ),
        ),
        default_local_path=tmp_path,
    )
    assert isinstance(gh.provider, GitHubProvider)
    assert gh.provider.location == "github:acme/dags"
    gl = build_target(
        StorageSettings(
            mode="git", git=GitStorageSettings(provider="gitlab", repo="grp/dags", token="t")
        ),
        default_local_path=tmp_path,
    )
    assert isinstance(gl.provider, GitLabProvider)
    with pytest.raises(StorageError):
        build_target(
            StorageSettings(mode="git", git=GitStorageSettings(provider="github", repo="a/b")),
            default_local_path=tmp_path,
        )

    bundles = [
        {"name": "local", "classpath": "airflow.dag_processing.bundles.local.LocalDagBundle"},
        {
            "name": "repo",
            "classpath": "airflow.providers.git.bundles.git.GitDagBundle",
            "kwargs": {
                "repo_url": "https://github.com/acme/dags.git",
                "tracking_ref": "prod",
                "subdir": "dags",
                "git_conn_id": "git_default",
            },
        },
    ]
    monkeypatch.setattr(git_config, "_bundle_list", lambda: bundles)
    found = git_config.bundle_git_settings()
    assert found is not None
    assert (found.repo_url, found.tracking_ref, found.subdir, found.git_conn_id) == (
        "https://github.com/acme/dags.git",
        "prod",
        "dags",
        "git_default",
    )
    assert git_config.bundle_git_settings("other") is None
    monkeypatch.setattr(
        git_config,
        "credentials_from_connection",
        lambda conn_id: git_config.GitCredentials(token="secret-token"),
    )
    monkeypatch.setattr(
        "autoair.storage.git.config.credentials_from_connection",
        lambda conn_id: git_config.GitCredentials(token="secret-token"),
    )
    target = build_target(
        StorageSettings(
            mode="git", git=GitStorageSettings(provider="github", use_airflow_bundle=True)
        ),
        default_local_path=tmp_path,
    )
    assert target.base_branch == "prod"
    assert target.subdir == "dags"
    assert "secret-token" not in repr(git_config.GitCredentials(token="secret-token"))


