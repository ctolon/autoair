def test_modes_kill_switch_and_forced_connection() -> None:
    assert GitStorageSettings().request_token == "optional"
    assert effective_mode(cfg()) == "optional"
    assert effective_mode(cfg(request_token="required")) == "required"
    assert effective_mode(cfg(request_token="off")) == "off"
    # off on the global storage turns tokens off for team targets too
    assert effective_mode(cfg(request_token="required"), cfg(request_token="off")) == "off"
    assert effective_mode(cfg(request_token="off"), cfg(request_token="required")) == "off"
    # an admin-forced connection wins unless the admin lets tokens override it
    assert effective_mode(cfg(forced_conn_id="svc")) == "off"
    assert effective_mode(cfg(forced_conn_id="svc", request_token="required")) == "off"
    forced = cfg(forced_conn_id="svc", request_token_overrides_forced=True)
    assert effective_mode(forced) == "optional"


def test_accept_rejects_without_echoing_the_token() -> None:
    assert take(None, cfg()) is None
    token = take(f"  {TOKEN} ", cfg())
    assert isinstance(token, RequestToken)
    assert token.reveal() == TOKEN
    assert TOKEN not in repr(token)
    assert TOKEN not in str(token)
    assert TOKEN not in f"{token}"
    with pytest.raises(TypeError):
        pickle.dumps(token)
    cases: list[tuple[dict[str, Any], int, str]] = [
        ({"kind": "local"}, 400, "git_token_not_git"),
        ({"cfg": cfg(request_token="off")}, 400, "git_token_off"),
        ({"root": cfg(request_token="off")}, 400, "git_token_off"),
        ({"cfg": cfg(forced_conn_id="svc")}, 400, "git_token_off"),
        ({"scheme": "http"}, 403, "git_token_insecure"),
    ]
    for over, status, code in cases:
        with pytest.raises(RequestTokenError) as err:
            take(TOKEN, **{"c": over.pop("cfg", cfg()), **over})
        assert (err.value.status, err.value.code) == (status, code)
        assert TOKEN not in str(err.value.detail())
    for bad in ("", "   ", "short", "has space inside-1234", "x" * 5000, "tab\tinside-12345"):
        with pytest.raises(RequestTokenError) as err:
            take(bad, cfg())
        assert err.value.status == 400
    # forced connection + override: accepted
    assert take(TOKEN, cfg(forced_conn_id="svc", request_token_overrides_forced=True))


def test_transport_rules() -> None:
    assert secure_transport("https", "203.0.113.9")
    assert secure_transport("http", "127.0.0.1")
    assert secure_transport("http", "::1")
    assert secure_transport("http", "localhost")
    assert not secure_transport("http", "203.0.113.9")
    assert not secure_transport("http", None)
    assert not secure_transport("http", "testclient")
    insecure_ok = cfg(request_token_allow_insecure=True)
    assert take(TOKEN, insecure_ok, scheme="http")
    assert take(TOKEN, cfg(), scheme="http", client_host="127.0.0.1")


def test_required_mode() -> None:
    check_required(None, kind="git", cfg=cfg(), root=None)
    check_required(None, kind="local", cfg=cfg(request_token="required"), root=None)
    check_required(RequestToken(TOKEN), kind="git", cfg=cfg(request_token="required"), root=None)
    with pytest.raises(RequestTokenError) as err:
        check_required(None, kind="git", cfg=cfg(request_token="required"), root=None)
    assert err.value.code == "git_token_required"
    # forced connection (no override): the connection is used, no token needed
    check_required(
        None, kind="git", cfg=cfg(request_token="required", forced_conn_id="svc"), root=None
    )


def test_info_and_provider_hints() -> None:
    assert info(cfg(), None, "local") is None
    off = info(cfg(forced_conn_id="svc"), None, "git")
    assert off is not None
    assert off.mode == "off"
    assert off.hint is None
    assert off.reason
    assert "svc" in off.reason
