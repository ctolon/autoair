    assert HINTS["gitlab"].scopes == ["api"]
    assert HINTS["gitea"].scopes == ["write:repository"]
    assert HINTS["local"].scopes == []
    assert set(HINTS) == {"github", "gitlab", "bitbucket", "azure", "gitea", "local"}


