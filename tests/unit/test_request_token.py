@needs_git
def test_local_push_over_https_auth_header_never_in_config(tmp_path: Path) -> None:
    """A real push over git's smart HTTP: the token travels as the Basic header of
    http.extraHeader (environment), never in argv, the remote URL or .git/config."""
    root = tmp_path / "srv"
    bare_repo(root, "dags.git")
    with GitHttpServer(root, TOKEN) as server:
        url = server.url("dags.git")
        c = cfg(
            provider="local",
            repo=url,
            mode="push",
            cache_dir=tmp_path / "cache",
            request_token_allow_insecure=True,  # the fake host speaks plain HTTP
        )
        target = build_request_target(c, RequestToken(TOKEN))
        assert isinstance(target, GitTarget)
        provider = target.provider
        assert isinstance(provider, LocalGitProvider)
        env = provider._env()
        values = [env[k] for k in env if k.startswith("GIT_CONFIG_VALUE_")]
        basic = base64.b64encode(f"x-access-token:{TOKEN}".encode()).decode()
        assert f"Authorization: Basic {basic}" in values
        assert "" in values  # credential.helper reset: no helper stores anything
        result = target.save(spec(), {"demo.py": SRC})
        assert result.branch == "main"
        assert server.seen
        assert all(a == f"Basic {basic}" for a in server.seen)
        shown = subprocess.run(
            ["git", "--git-dir", str(root / "dags.git"), "show", "main:demo.py"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        assert shown == SRC
        for path in (tmp_path / "cache").rglob("*"):
            if path.is_file() and path.name in ("config", "FETCH_HEAD", "packed-refs"):
                text = path.read_text(errors="replace")
                assert TOKEN not in text
                assert basic not in text
        # a wrong token: the host's refusal is an AuthError carrying no secret
        wrong = build_request_target(c, RequestToken("wrong-token-123456"))
        with pytest.raises(AuthError) as err:
            wrong.save(spec("other"), {"other.py": SRC})
        assert "wrong-token-123456" not in str(err.value)


def test_ssh_and_plain_http_hosts_are_refused(tmp_path: Path) -> None:
    for repo in ("git@github.com:acme/dags.git", "ssh://git@host/acme/dags.git"):
        with pytest.raises(RequestTokenError) as err:
            build_request_target(
                cfg(provider="local", repo=repo, cache_dir=tmp_path), RequestToken(TOKEN)
            )
        assert err.value.code == "git_token_ssh_remote"
    with pytest.raises(RequestTokenError) as err:
        build_request_target(
            cfg(provider="local", repo="http://git.example.com/a/b.git", cache_dir=tmp_path),
            RequestToken(TOKEN),
        )
    assert err.value.code == "git_token_insecure_host"
    with pytest.raises(RequestTokenError):
        build_request_target(
            cfg(provider="github", repo="acme/dags", api_url="http://ghe.example.com/api/v3"),
            RequestToken(TOKEN),
        )
    # file:// remotes have no network transport: allowed
    assert build_request_target(
        cfg(provider="local", repo=f"file://{tmp_path}/x.git", cache_dir=tmp_path),
        RequestToken(TOKEN),
    )


def test_token_user_lookups() -> None:
    def gh(request: httpx2.Request) -> httpx2.Response:
        assert request.url.path == "/user"
        return httpx2.Response(200, json={"login": "octocat"})

    target = build_request_target(
        cfg(provider="github", repo="acme/dags"),
        RequestToken(TOKEN),
        transport=httpx2.MockTransport(gh),
    )
    assert token_user(target) == "octocat"

    def gl(request: httpx2.Request) -> httpx2.Response:
        return httpx2.Response(200, json={"username": "gitlab-jane"})

    target = build_request_target(
        cfg(provider="gitlab", repo="grp/dags"),
        RequestToken(TOKEN),
        transport=httpx2.MockTransport(gl),
    )
    assert token_user(target) == "gitlab-jane"

    def denied(request: httpx2.Request) -> httpx2.Response:
        return httpx2.Response(403, json={"message": "missing read:user"})

    target = build_request_target(
        cfg(provider="gitea", repo="https://gitea.test/acme/dags.git"),
        RequestToken(TOKEN),
        transport=httpx2.MockTransport(denied),
    )
    assert token_user(target) is None  # best effort: never fails the write


