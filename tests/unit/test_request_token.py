@pytest.mark.parametrize("kind", ["bitbucket", "azure"])
def test_bitbucket_and_azure_use_the_request_token(kind: str) -> None:
    repo = bb_az.FakeRepo()
    seen: list[httpx2.Headers] = []
    handler = bb_az.bitbucket_handler(repo) if kind == "bitbucket" else bb_az.azure_handler(repo)
    c = cfg(
        provider=kind,
        repo="ws/dags" if kind == "bitbucket" else "org/proj/dags",
        api_url=None if kind == "bitbucket" else "https://azure.test",
        token="configured",
        username="service-user",  # the service's app-password user is not paired with it
        azure_bearer=True,  # a typed token is a PAT (Basic), not an Entra bearer token
        mode="pr",
        subdir="dags",
    )
    target = build_request_target(c, RequestToken(TOKEN), transport=_recording(handler, seen))
    assert target.save(spec(), {"demo.py": SRC}).pr_url
    expected = (
        f"Bearer {TOKEN}"
        if kind == "bitbucket"
        else "Basic " + base64.b64encode(f":{TOKEN}".encode()).decode()
    )
    assert seen
    assert all(h["Authorization"] == expected for h in seen)


