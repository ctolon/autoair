def test_masking_covers_logs_tracebacks_and_data(caplog: pytest.LogCaptureFixture) -> None:
    install_log_masking()
    log = logging.getLogger("autoair.test.mask")
    basic = base64.b64encode(f"x-access-token:{TOKEN}".encode()).decode()
    caplog.set_level(logging.DEBUG)
    with masking(TOKEN):
        assert mask(f"url https://{TOKEN}@host and {basic}") == "url https://***@host and ***"
        assert mask_data({"a": [TOKEN, {"b": f"x{TOKEN}y"}], TOKEN: 1}) == {
            "a": ["***", {"b": "x***y"}],
            "***": 1,
        }
        log.warning("push to https://u:%s@host failed", TOKEN)
        try:
            raise RuntimeError(f"boom {TOKEN}")
        except RuntimeError:
            log.exception("failed")
    log.warning("after %s", TOKEN)  # outside the request: nothing is registered
    text = caplog.text
    assert "push to https://u:***@host failed" in text
    assert "boom ***" in text
    assert text.count(TOKEN) == 1
    assert "after" in text
    assert mask(TOKEN) == TOKEN  # nothing registered any more
