def cfg(**kw: Any) -> GitStorageSettings:
    return GitStorageSettings(**kw)


def take(raw: str | None, c: GitStorageSettings, root: GitStorageSettings | None = None, **kw):
    args = {"kind": "git", "cfg": c, "root": root, "scheme": "https", "client_host": "10.0.0.5"}
    return accept(raw, **{**args, **kw})


