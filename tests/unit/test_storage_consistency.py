"""File-like deploy targets: unreadable state fails closed, a failed write advances
nothing, and object-storage writers on several replicas cannot both win."""

from __future__ import annotations

import inspect
import threading
import uuid
from collections.abc import Iterator
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest

from autoair.persistence import DatabaseSettings, FileDocumentStore
from autoair.spec import DagSpec
from autoair.storage import ConflictError, EjectedError, StorageError
from autoair.storage.config import StorageSettings, object_locks
from autoair.storage.local import LocalFolderTarget
from autoair.storage.object import ObjectStorageTarget
from tests.db_backends import BACKENDS, database_settings, drop_tables

SRC = '"""Generated by AutoAir"""\nprint("v1")\n'
SRC2 = '"""Generated by AutoAir"""\nprint("v2")\n'
EDITED = '"""Generated by AutoAir"""\nprint("edited by hand")\n'


@pytest.fixture
def spec(simple_spec_data: dict[str, Any]) -> DagSpec:
    return DagSpec.model_validate(simple_spec_data)


def _ejected(tmp_path: Path, spec: DagSpec) -> LocalFolderTarget:
    target = LocalFolderTarget(tmp_path)
    target.save(spec, {"simple.py": SRC})
    (tmp_path / "simple.py").write_text(EDITED)  # hand edit after the deploy
    return target


# --------------------------------------------------------------------------- state record


def test_corrupt_state_refuses_to_overwrite(tmp_path: Path, spec: DagSpec) -> None:
    target = _ejected(tmp_path, spec)
    state = tmp_path / ".autoair/state/simple.json"
    state.write_text("{not json")
    with pytest.raises(StorageError, match=r"state.*simple\.json") as info:
        target.save(spec.model_copy(update={"description": "v2"}), {"simple.py": SRC2})
    assert not isinstance(info.value, ConflictError)
    assert (tmp_path / "simple.py").read_text() == EDITED
    with pytest.raises(StorageError, match=r"state.*simple\.json"):
        target.delete("simple")
    assert (tmp_path / "simple.py").read_text() == EDITED
    with pytest.raises(StorageError, match=r"state.*simple\.json"):
        target.save(spec, {"simple.py": SRC2}, force=True)  # force does not guess either
    # Reads keep working while the record is broken.
    stored = target.get("simple")
    assert stored is not None
    assert stored.version is None


def test_missing_state_treats_files_as_unknown(tmp_path: Path, spec: DagSpec) -> None:
    target = _ejected(tmp_path, spec)
    (tmp_path / ".autoair/state/simple.json").unlink()
    with pytest.raises(EjectedError):
        target.save(spec.model_copy(update={"description": "v2"}), {"simple.py": SRC2})
    assert (tmp_path / "simple.py").read_text() == EDITED
    with pytest.raises(EjectedError):
        target.delete("simple")
    assert (tmp_path / "simple.py").read_text() == EDITED
    # The user decides: force overwrites the file whose history AutoAir lost.
    target.save(spec, {"simple.py": SRC2}, force=True)
    assert (tmp_path / "simple.py").read_text() == SRC2


def test_missing_state_still_rewrites_identical_content(tmp_path: Path, spec: DagSpec) -> None:
    target = LocalFolderTarget(tmp_path)
    target.save(spec, {"simple.py": SRC})
    (tmp_path / ".autoair/state/simple.json").unlink()
    result = target.save(spec, {"simple.py": SRC})  # nothing to lose: the same file
    assert result.version
    assert (tmp_path / ".autoair/state/simple.json").exists()


# --------------------------------------------------------------------------- write order


def test_failed_dag_file_write_advances_nothing(
    tmp_path: Path, spec: DagSpec, monkeypatch: pytest.MonkeyPatch
) -> None:
    target = LocalFolderTarget(tmp_path)
    first = target.save(spec, {"simple.py": SRC})
    spec_before = (tmp_path / "simple.autoair.json").read_text()
    state_before = (tmp_path / ".autoair/state/simple.json").read_text()
    history_before = target.history("simple")
    original = target.local.write

    def failing_write(rel: str, content: str) -> None:
        if rel == "simple.py":
            raise OSError(28, "No space left on device")
        original(rel, content)

    monkeypatch.setattr(target.local, "write", failing_write)
    with pytest.raises(OSError, match="No space left"):
        target.save(
            spec.model_copy(update={"description": "v2"}),
            {"simple.py": SRC2},
            base_etag=first.etag,
        )
    assert (tmp_path / "simple.py").read_text() == SRC
    assert (tmp_path / "simple.autoair.json").read_text() == spec_before
    assert (tmp_path / ".autoair/state/simple.json").read_text() == state_before
    assert target.history("simple") == history_before
    stored = target.get("simple")
    assert stored is not None
    assert stored.etag == first.etag
    monkeypatch.setattr(target.local, "write", original)
    # The same edit goes through once the disk is fixed (the etag did not advance).
    assert target.save(
        spec.model_copy(update={"description": "v2"}), {"simple.py": SRC2}, base_etag=first.etag
    ).version


def test_failed_first_write_leaves_no_spec(
    tmp_path: Path, spec: DagSpec, monkeypatch: pytest.MonkeyPatch
) -> None:
    target = LocalFolderTarget(tmp_path)
    original = target.local.write

    def failing_write(rel: str, content: str) -> None:
        if rel == "simple.py":
            raise PermissionError(13, "Permission denied")
        original(rel, content)

    monkeypatch.setattr(target.local, "write", failing_write)
    with pytest.raises(PermissionError):
        target.save(spec, {"simple.py": SRC})
    assert target.get("simple") is None
    assert target.history("simple") == []
    assert not (tmp_path / ".autoair/state/simple.json").exists()


# --------------------------------------------------------------------------- object storage


def _object_target(url: str, locks: Any) -> ObjectStorageTarget:
    if "locks" in inspect.signature(ObjectStorageTarget).parameters:
        return ObjectStorageTarget(url, locks=locks)
    return ObjectStorageTarget(url)  # pragma: no cover - versions without replica locks


@pytest.fixture(params=BACKENDS)
def shared_locks(request: pytest.FixtureRequest, tmp_path: Path) -> Iterator[Any]:
    """The lease store every replica shares (file, SQLite, PostgreSQL state backends)."""
    settings = SimpleNamespace(
        database=DatabaseSettings(**database_settings(request.param, tmp_path)),
        state_dir=tmp_path / "state",
    )
    storage = StorageSettings(mode="object", object_url="memory://x/dags")
    yield object_locks(settings, storage)
    drop_tables(settings)


def test_two_replicas_with_the_same_base_etag_cannot_both_win(
    shared_locks: Any, spec: DagSpec
) -> None:
    url = f"memory://autoair-{uuid.uuid4().hex}/dags"
    locks = shared_locks
    replica_a = _object_target(url, locks)
    replica_b = _object_target(url, locks)
    base = replica_a.save(spec, {"simple.py": SRC}).etag

    a_writing = threading.Event()
    release_a = threading.Event()
    original = replica_a.object_store.write

    def slow_write(rel: str, content: str) -> None:
        if rel == "simple.autoair.json":
            a_writing.set()
            release_a.wait(10)
        original(rel, content)

    replica_a.object_store.write = slow_write  # type: ignore[method-assign]
    outcomes: dict[str, Any] = {}

    def run(name: str, target: ObjectStorageTarget, description: str) -> None:
        try:
            outcomes[name] = target.save(
                spec.model_copy(update={"description": description}),
                {"simple.py": SRC2 if name == "a" else SRC2 + "# b\n"},
                base_etag=base,
            )
        except Exception as exc:
            outcomes[name] = exc

    thread_a = threading.Thread(target=run, args=("a", replica_a, "from a"))
    thread_a.start()
    assert a_writing.wait(10)
    thread_b = threading.Thread(target=run, args=("b", replica_b, "from b"))
    thread_b.start()
    thread_b.join(0.5)  # B either finished (no shared lock) or waits for A's lease
    release_a.set()
    thread_a.join(10)
    thread_b.join(10)
    assert not isinstance(outcomes["a"], Exception), outcomes["a"]
    assert isinstance(outcomes["b"], ConflictError), outcomes["b"]
    stored = replica_b.get("simple")
    assert stored is not None
    assert stored.spec.description == "from a"


def test_object_lock_lease_expires(tmp_path: Path, spec: DagSpec) -> None:
    """A replica that died while holding the lease does not block the DAG forever."""
    url = f"memory://autoair-{uuid.uuid4().hex}/dags"
    locks = FileDocumentStore(str(tmp_path / "locks"))
    target = ObjectStorageTarget(url, locks=locks, lock_seconds=0.2, lock_wait_seconds=5)
    lease = target._lease("simple")
    lease.__enter__()  # never released: the replica crashed
    assert target.save(spec, {"simple.py": SRC}).version


def test_object_lock_wait_gives_up_with_a_conflict(tmp_path: Path, spec: DagSpec) -> None:
    url = f"memory://autoair-{uuid.uuid4().hex}/dags"
    locks = FileDocumentStore(str(tmp_path / "locks"))
    target = ObjectStorageTarget(url, locks=locks, lock_seconds=60, lock_wait_seconds=0.3)
    with target._lease("simple"), pytest.raises(ConflictError, match="another"):
        target.save(spec, {"simple.py": SRC})


def test_object_store_on_a_local_file_system_renames_into_place(
    tmp_path: Path, spec: DagSpec
) -> None:
    target = ObjectStorageTarget(f"file://{tmp_path}/dags")
    target.save(spec, {"simple.py": SRC})
    target.save(spec.model_copy(update={"description": "v2"}), {"simple.py": SRC2})
    assert (tmp_path / "dags/simple.py").read_text() == SRC2
    assert not list((tmp_path / "dags").glob(".*.tmp"))


def test_a_writer_that_lost_its_lease_stops_and_rolls_back(tmp_path: Path, spec: DagSpec) -> None:
    url = f"memory://autoair-{uuid.uuid4().hex}/dags"
    locks = FileDocumentStore(str(tmp_path / "locks"))
    slow = ObjectStorageTarget(url, locks=locks, lock_seconds=0.2, lock_wait_seconds=5)
    other = ObjectStorageTarget(url, locks=locks, lock_seconds=60, lock_wait_seconds=5)
    original = slow.object_store.write

    def stalled_write(rel: str, content: str) -> None:
        original(rel, content)
        if rel == "simple.autoair.json":  # stalls past its lease; another replica takes over
            other._lease("simple").__enter__()

    slow.object_store.write = stalled_write  # type: ignore[method-assign]
    slow.lock_seconds = 0.0  # its lease is expired by the time the spec is written
    with pytest.raises(ConflictError, match="took it over"):
        slow.save(spec, {"simple.py": SRC})
    assert slow.get("simple") is None  # the spec written before was rolled back
