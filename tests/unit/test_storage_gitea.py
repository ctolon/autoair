def test_unbuildable_target_starts_degraded(tmp_path: Path) -> None:
    settings = StorageSettings(mode="git", git=GitStorageSettings(conn_id="missing_conn"))
    target = build_target_or_unavailable(settings, default_local_path=tmp_path)
    assert isinstance(target, UnavailableTarget)
    assert "git storage needs a repository" in target.error
    status = target.status()
    assert (status.kind, status.writable, status.details["unavailable"]) == ("git", False, True)
    assert target.list() == []
    assert target.get("x") is None
    with pytest.raises(StorageError, match="unavailable"):
        target.delete("x")
