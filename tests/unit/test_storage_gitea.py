def _github_host(valid: set[str]) -> httpx2.MockTransport:
    def handler(request: httpx2.Request) -> httpx2.Response:
        token = request.headers.get("Authorization", "").removeprefix("Bearer ")
        if token not in valid:
            return httpx2.Response(401, json={"message": "Bad credentials"})
        if request.url.path.endswith("/git/ref/heads/main"):
            return httpx2.Response(200, json={"object": {"sha": "a" * 40}})
        return httpx2.Response(200, json=[])

    return httpx2.MockTransport(handler)


def test_shared_connection_credentials_are_re_read(monkeypatch: pytest.MonkeyPatch) -> None:
    from autoair.storage.git import config as git_config

    current = {"token": "old"}
    reads: list[str] = []

    def connection(conn_id: str) -> GitCredentials:
        reads.append(conn_id)
        return GitCredentials(repo_url="https://github.com/acme/dags.git", **current)

    monkeypatch.setattr(git_config, "credentials_from_connection", connection)
    cfg = GitStorageSettings(provider="github", conn_id="git_svc", credentials_ttl=3600)
    target = build_target(StorageSettings(mode="git", git=cfg), default_local_path=Path("/x"))
    assert isinstance(target, GitTarget)
    assert isinstance(target.provider, GitHubProvider)
    assert target.provider._token == "old"
    current["token"] = "new"
    assert target.refresh_credentials() is False  # cached (TTL)
    assert target.provider._token == "old"
    assert target.refresh_credentials(force=True) is True  # e.g. after a 401
    assert target.provider._token == "new"
    assert target.refresh_credentials(force=True) is False  # unchanged: no new provider
    assert reads == ["git_svc"] * 3

    # A token from the settings does not come from the connection: nothing to re-read.
    pinned = cfg.model_copy(update={"token": SecretStr("pinned")})
    fixed = build_target(StorageSettings(mode="git", git=pinned), default_local_path=Path("/x"))
    assert isinstance(fixed, GitTarget)
    assert fixed.refresh_credentials(force=True) is False


def test_auth_failure_re_reads_the_connection_and_retries_once() -> None:
    valid = {"new"}
    token = {"value": "old"}
    loads: list[int] = []

    def load() -> GitCredentials:
        loads.append(1)
        return GitCredentials(token=token["value"])

    def make(creds: GitCredentials | None) -> GitHubProvider:
        return GitHubProvider(
            "acme/dags", creds.token if creds else "", transport=_github_host(valid)
        )

    first = GitCredentials(token="old")
    refresh = ConnectionCredentials(load, make, first, ttl=3600)
    target = GitTarget(make(first), provider_refresh=refresh)
    # The token was rotated in Airflow: the 401 makes the target re-read it and retry.
    token["value"] = "new"
    assert target.list() == []
    assert loads == [1]
    # Rotated again but the connection still holds a refused token: the error surfaces
    # after a single re-read (no retry loop).
    valid.clear()
    with pytest.raises(AuthError):
        target.list()
    assert loads == [1, 1]


def test_ttl_zero_reads_the_connection_every_operation() -> None:
    clock = iter(range(100))
    loads: list[int] = []

    def load() -> GitCredentials:
        loads.append(1)
        return GitCredentials(token=f"t{len(loads)}")

    refresh = ConnectionCredentials(
        load, lambda c: c, GitCredentials(token="t0"), ttl=0, clock=lambda: float(next(clock))
    )
    assert refresh() == GitCredentials(token="t1")
    assert refresh() == GitCredentials(token="t2")
    assert len(loads) == 2


def test_per_user_credentials_are_read_per_deploy_and_on_auth_failure(tmp_path: Path) -> None:
    class Shared:
        kind = "git"

    secrets = {"git_alice": GitCredentials(token="one")}
    loads: list[str] = []

    def load_secret(conn_id: str) -> GitCredentials:
        loads.append(conn_id)
        return secrets[conn_id]

    async def check(_conn_id: str) -> dict[str, str]:
        return {"connection_id": "git_alice"}

    cfg = GitStorageSettings(
        provider="github",
        repo="acme/dags",
        credentials_mode="per_user",
        credentials_ttl=3600,
    )

    def resolve() -> Any:
        return asyncio.run(
            resolve_user_target(
                Shared(),  # type: ignore[arg-type]
                cfg,
                username="alice",
                requested_conn_id=None,
                check_access=check,
                load_secret=load_secret,
            )
        )

    first = resolve().target
    assert first.provider._token == "one"
    secrets["git_alice"] = GitCredentials(token="two")
    second = resolve().target  # every deploy reads the user's connection again
    assert second.provider._token == "two"
    # A target still in use re-reads it when the host refuses the old token.
    assert first.refresh_credentials(force=True) is True
    assert first.provider._token == "two"
    assert loads == ["git_alice"] * 3


