def test_save_get_etag_and_history(tmp_path, simple_spec_data):
    target = LocalFolderTarget(tmp_path)
    spec = DagSpec.model_validate(simple_spec_data)
    first = target.save(spec, {"simple.py": SRC}, author="alice", message="first")
    assert first.etag == spec_etag(spec)
    assert first.path == str(tmp_path / "simple.py")
    stored = target.get("simple")
    assert stored is not None
    assert stored.etag == first.etag
    assert stored.version == first.version

    spec2 = spec.model_copy(update={"description": "second"})
    second = target.save(spec2, {"simple.py": SRC2}, base_etag=first.etag, author="bob")
    assert second.version != first.version

    history = target.history("simple")
    assert [v.version for v in history] == [second.version, first.version]
    assert history[1].author == "alice"
    assert history[1].message == "first"
    assert target.get_version("simple", first.version) == spec
    assert target.get_version("simple", second.version).description == "second"
    with pytest.raises(NotFoundError):
        target.get_version("simple", "20200101T000000000000Z-deadbeef")
    with pytest.raises(StorageError):
        target.get_version("simple", "../../etc/passwd")

    status = target.status()
    assert status.kind == "local"
    assert status.writable
    summaries = target.list()
    assert [s.etag for s in summaries] == [second.etag]


def test_unchanged_save_creates_no_history(tmp_path, simple_spec_data):
    target = LocalFolderTarget(tmp_path)
    spec = DagSpec.model_validate(simple_spec_data)
    target.save(spec, {"simple.py": SRC})
    result = target.save(spec, {"simple.py": SRC})
    assert result.message.startswith("unchanged")
    assert len(target.history("simple")) == 1


def test_stale_etag_conflicts(tmp_path, simple_spec_data):
    target = LocalFolderTarget(tmp_path)
    spec = DagSpec.model_validate(simple_spec_data)
    first = target.save(spec, {"simple.py": SRC})
    target.save(spec.model_copy(update={"description": "other"}), {"simple.py": SRC2})
    with pytest.raises(ConflictError) as info:
        target.save(spec, {"simple.py": SRC}, base_etag=first.etag)
    assert info.value.current is not None
    assert info.value.current.spec.description == "other"
    with pytest.raises(ConflictError):
        target.delete("simple", base_etag=first.etag)
    # creating with a base etag of something that does not exist conflicts too
    other = spec.model_copy(update={"dag_id": "other"})
    with pytest.raises(ConflictError):
        target.save(other, {"other.py": SRC}, base_etag="x")


def test_ejected_file_detection(tmp_path, simple_spec_data):
    target = LocalFolderTarget(tmp_path)
    spec = DagSpec.model_validate(simple_spec_data)
    target.save(spec, {"simple.py": SRC})
    (tmp_path / "simple.py").write_text(SRC + "# tweaked by hand\n")
    with pytest.raises(EjectedError):
        target.save(spec, {"simple.py": SRC2})
    with pytest.raises(EjectedError):
        target.delete("simple")
    target.save(spec, {"simple.py": SRC2}, force=True)
    assert (tmp_path / "simple.py").read_text() == SRC2


def test_switching_file_set_removes_stale_generated_files(tmp_path, simple_spec_data):
    target = LocalFolderTarget(tmp_path)
    spec = DagSpec.model_validate(simple_spec_data)
    target.save(spec, {"simple.py": SRC})
    yaml_spec = spec.model_copy(update={"output_mode": "yaml"})
    target.save(yaml_spec, {"simple.yaml": "# Generated by AutoAir\nsimple: {}\n"})
    assert _visible(tmp_path) == ["simple.autoair.json", "simple.yaml"]
    assert target.list()[0].dag_file.endswith("simple.yaml")


def test_rejects_bad_file_names(tmp_path, simple_spec_data):
    target = LocalFolderTarget(tmp_path)
    spec = DagSpec.model_validate(simple_spec_data)
    for files in ({}, {"other.py": SRC}, {"../simple.py": SRC}, {"simple.autoair.json": "{}"}):
        with pytest.raises(StorageError):
            target.save(spec, files)


def test_history_is_pruned(tmp_path, simple_spec_data):
    target = LocalFolderTarget(tmp_path, history_limit=3)
    spec = DagSpec.model_validate(simple_spec_data)
    for i in range(5):
        target.save(spec.model_copy(update={"description": str(i)}), {"simple.py": SRC})
    history = target.history("simple")
    assert len(history) == 3
    assert target.get_version("simple", history[0].version).description == "4"
    snapshot = json.loads(
        (tmp_path / ".autoair" / "history" / "simple" / f"{history[0].version}.json").read_text()
    )
    assert snapshot["spec"]["dag_id"] == "simple"


def test_target_repository_adapter_and_renderer(tmp_path, simple_spec_data):
    spec = DagSpec.model_validate(simple_spec_data).model_copy(update={"output_mode": "loader"})
    assert render_dag_files(spec) == {"simple.py": render_stub("simple")}
    with pytest.raises(StorageError):
        render_dag_files(spec, environment="nope", strict=True)
    assert render_dag_files(spec, environment="nope") == {"simple.py": render_stub("simple")}
    repo = TargetRepository(LocalFolderTarget(tmp_path))
    repo.save(spec, None)
    assert repo.get("simple") == spec
    assert repo.delete("simple")


def test_build_local_target(tmp_path):
    target = build_target(StorageSettings(), default_local_path=tmp_path)
    assert isinstance(target, LocalFolderTarget)
    assert target.root == tmp_path.resolve()
    with pytest.raises(StorageError):
        build_target(StorageSettings(mode="object"), default_local_path=tmp_path)
