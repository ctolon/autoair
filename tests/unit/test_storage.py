from __future__ import annotations

import json

import pytest

from autoair.loader import render_stub
from autoair.spec import DagSpec
from autoair.storage import (
    ConflictError,
    EjectedError,
    FileSystemRepository,
    LocalFolderTarget,
    NotFoundError,
    StorageError,
    StorageSettings,
    TargetRepository,
    build_target,
    render_dag_files,
    spec_etag,
)

SRC = '"""Generated by AutoAir"""\nprint("v1")\n'
SRC2 = '"""Generated by AutoAir"""\nprint("v2")\n'


def _visible(path):
    return sorted(p.name for p in path.iterdir() if p.name != ".autoair")


# ------------------------------------------------------------------- FileSystemRepository


def test_save_python_and_switch_to_loader(tmp_path, simple_spec_data):
    repo = FileSystemRepository(tmp_path)
    spec = DagSpec.model_validate(simple_spec_data)
    repo.save(spec, '"""Generated by AutoAir"""\n')
    assert (tmp_path / "simple.py").read_text().startswith('"""Generated by AutoAir')
    assert repo.get("simple") == spec

    loader_spec = spec.model_copy(update={"output_mode": "loader"})
    repo.save(loader_spec, None)
    assert "load_dag(__file__)" in (tmp_path / "simple.py").read_text()
    assert [s.dag_id for s in repo.list()] == ["simple"]
    assert repo.delete("simple")
    assert _visible(tmp_path) == []
    assert not repo.delete("simple")


def test_refuses_to_overwrite_foreign_files(tmp_path, simple_spec_data):
    (tmp_path / "simple.py").write_text("# hand written dag\n")
    with pytest.raises(StorageError, match="not created by AutoAir"):
        FileSystemRepository(tmp_path).save(DagSpec.model_validate(simple_spec_data), "x")


@pytest.mark.parametrize("dag_id", ["../evil", "a/b", ".hidden"])
def test_path_traversal_blocked(tmp_path, dag_id):
    with pytest.raises(StorageError):
        FileSystemRepository(tmp_path).spec_path(dag_id)
    with pytest.raises(StorageError):
        LocalFolderTarget(tmp_path).get(dag_id)


def test_files_without_state_are_managed(tmp_path, simple_spec_data):
    spec = DagSpec.model_validate(simple_spec_data)
    (tmp_path / "simple.autoair.json").write_text(spec.model_dump_json())
    (tmp_path / "simple.py").write_text(render_stub("simple"))
    target = LocalFolderTarget(tmp_path)
    assert target.get("simple").spec == spec
    target.save(spec, {"simple.py": SRC})
    assert (tmp_path / "simple.py").read_text() == SRC


