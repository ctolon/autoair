def test_git_process_env_has_no_server_secrets(
    remote: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """What a git process really receives (a credential helper / hook would see it)."""
    monkeypatch.setenv("AUTOAIR_STORAGE__GIT__TOKEN", "server-token")
    monkeypatch.setenv("AIRFLOW__DATABASE__SQL_ALCHEMY_CONN", "postgresql://u:pw@db/a")
    monkeypatch.setenv("AWS_SECRET_ACCESS_KEY", "aws")
    provider = LocalGitProvider(str(remote), tmp_path / "cache", token="request-token")
    env = provider._env()
    assert "AUTOAIR_STORAGE__GIT__TOKEN" not in env
    assert "AIRFLOW__DATABASE__SQL_ALCHEMY_CONN" not in env
    assert "AWS_SECRET_ACCESS_KEY" not in env
    assert env["PATH"] == os.environ["PATH"]
    assert env["GIT_TERMINAL_PROMPT"] == "0"
    # The per-request token still authenticates the push (GIT_CONFIG_*, never argv).
    assert any(v.startswith("Authorization: Basic ") for k, v in env.items() if "VALUE" in k)
    assert provider.head("main")  # git itself still works with the scoped environment


