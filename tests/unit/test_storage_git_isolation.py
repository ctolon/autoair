def test_ssh_key_files_are_per_key(tmp_path: Path) -> None:
    """Providers of two users sharing one clone cache (gitea, a forced connection) must
    each use their own key; a rotated key replaces the old one at once."""
    cache = tmp_path / "cache"
    alice = LocalGitProvider("ssh://git@host/r.git", cache, private_key="ALICE KEY")
    bob = LocalGitProvider("ssh://git@host/r.git", cache, private_key="BOB KEY")
    alice_file = alice._key_file()
    bob_file = bob._key_file()
    assert alice_file is not None
    assert bob_file is not None
    assert alice_file != bob_file
    assert alice_file.read_text() == "ALICE KEY\n"
    assert bob_file.read_text() == "BOB KEY\n"
    assert alice_file.stat().st_mode & 0o077 == 0
    assert str(bob_file) in bob._env()["GIT_SSH_COMMAND"]
    rotated = LocalGitProvider("ssh://git@host/r.git", cache, private_key="ALICE NEW")
    rotated_file = rotated._key_file()
    assert rotated_file is not None
    assert rotated_file.read_text() == "ALICE NEW\n"


def _age(path: Path, days: float) -> None:
    then = time.time() - days * 86400
    os.utime(path, (then, then))


def test_old_ssh_key_files_are_pruned_when_a_key_is_written(tmp_path: Path) -> None:
    cache = tmp_path / "cache"
    old = LocalGitProvider("ssh://git@host/r.git", cache, private_key="OLD KEY")
    recent = LocalGitProvider("ssh://git@host/r.git", cache, private_key="RECENT KEY")
    old_file, recent_file = old._key_file(), recent._key_file()
    assert old_file is not None
    assert recent_file is not None
    keys = old_file.parent
    _age(old_file, 31)
    _age(recent_file, 29)
    leftover = keys / ".key-abc123"  # an interrupted write
    leftover.write_text("partial")
    _age(leftover, 40)
    foreign = keys / "id_rsa"  # not AutoAir's: never touched, however old
    foreign.write_text("someone else's key")
    _age(foreign, 400)
    linked = keys / f"id_autoair-{'0' * 32}"  # AutoAir's name, but a symlink
    linked.symlink_to(foreign)
    os.utime(linked, (0, 0), follow_symlinks=False)

    new = LocalGitProvider("ssh://git@host/r.git", cache, private_key="NEW KEY")
    new_file = new._key_file()
    assert new_file is not None
    assert new_file.exists()
    assert not old_file.exists()
    assert not leftover.exists()
    assert recent_file.exists()
    assert foreign.read_text() == "someone else's key"
    assert linked.is_symlink()
    # a pruned key that is used again is simply written again
    again = old._key_file()
    assert again == old_file
    assert again.read_text() == "OLD KEY\n"


def test_using_a_key_keeps_it_and_the_key_in_use_is_never_pruned(tmp_path: Path) -> None:
    from autoair.storage.git.local_git import prune_key_cache

    cache = tmp_path / "cache"
    used = LocalGitProvider("ssh://git@host/r.git", cache, private_key="USED KEY")
    used_file = used._key_file()
    assert used_file is not None
    _age(used_file, 90)
    assert used._key_file() == used_file  # the use refreshes its age
    assert used_file.stat().st_mtime > time.time() - 60
    _age(used_file, 90)
    assert prune_key_cache(used_file.parent, 30, keep=used_file) == []
    assert used_file.exists()


def test_ssh_key_cache_days_zero_keeps_every_key(tmp_path: Path) -> None:
    cache = tmp_path / "cache"
    kw: dict[str, Any] = {"ssh_key_cache_days": 0}
    old = LocalGitProvider("ssh://git@host/r.git", cache, private_key="OLD KEY", **kw)
    old_file = old._key_file()
    assert old_file is not None
    _age(old_file, 3650)
    LocalGitProvider("ssh://git@host/r.git", cache, private_key="NEW KEY", **kw)._key_file()
    assert old_file.exists()


def test_ssh_key_cache_days_reaches_the_provider(tmp_path: Path) -> None:
    from autoair.storage.config import GitStorageSettings, _git_provider

    assert GitStorageSettings().ssh_key_cache_days == 30
    with pytest.raises(ValueError, match="greater than or equal to 0"):
        GitStorageSettings(ssh_key_cache_days=-1)
    cfg = GitStorageSettings(provider="local", ssh_key_cache_days=7, cache_dir=tmp_path)
    provider = _git_provider(cfg, "ssh://git@host/r.git", None, per_user=False)
    assert isinstance(provider, LocalGitProvider)
    assert provider.ssh_key_cache_days == 7


# --------------------------------------------------------------------------- reset_branch


def test_reset_branch_refuses_to_overwrite_a_concurrent_commit(
    remote: Path, tmp_path: Path
) -> None:
    provider = LocalGitProvider(str(remote), tmp_path / "cache")
    base = provider.head("main")
    assert base
    provider.create_branch("autoair/simple", base)
    seen = provider.commit_files("autoair/simple", base, {"a.txt": "a"}, "a", None)
    theirs = _push_from_elsewhere(remote, tmp_path, "autoair/simple", "b.txt")
    with pytest.raises(ConflictError):
        provider.reset_branch("autoair/simple", base, expect=seen)
    assert git("--git-dir", str(remote), "rev-parse", "autoair/simple") == theirs
    provider.reset_branch("autoair/simple", base, expect=theirs)
    assert git("--git-dir", str(remote), "rev-parse", "autoair/simple") == base


class _PrProvider(LocalGitProvider):
    """A git CLI provider with pull requests (like Gitea); a concurrent writer pushes to
    the pending branch and opens its pull request right after AutoAir checked for one."""

    supports_pull_requests = True

    def __init__(self, *args: Any, race: Any = None, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self.race = race
        self.pr: PullRequest | None = None

    def find_open_pr(self, head: str) -> PullRequest | None:
        pr = self.pr
        if self.race is not None:
            race, self.race = self.race, None
            race()
            self.pr = PullRequest(url="https://host/pr/1", number=1)
        return pr

    def open_pr(self, *args: Any, **kwargs: Any) -> PullRequest | None:
        self.pr = PullRequest(url="https://host/pr/1", number=1)
        return self.pr


def test_recycling_a_branch_keeps_a_commit_pushed_meanwhile(
    remote: Path, tmp_path: Path, simple_spec_data: dict[str, Any]
) -> None:
    spec = DagSpec.model_validate(simple_spec_data)
    provider = _PrProvider(str(remote), tmp_path / "cache")
    target = GitTarget(provider, base_branch="main", mode="pr")
    target.save(spec, {"simple.py": SRC})
    provider.pr = None  # the first pull request was merged: the branch is stale
    theirs: dict[str, str] = {}
    provider.race = lambda: theirs.setdefault(
        "sha", _push_from_elsewhere(remote, tmp_path, "autoair/simple", "theirs.txt")
    )
    result = target.save(spec.model_copy(update={"description": "v2"}), {"simple.py": SRC2})
    log = git("--git-dir", str(remote), "rev-list", "autoair/simple")
    assert theirs["sha"] in log.split()  # not force-pushed away
    assert result.version == git("--git-dir", str(remote), "rev-parse", "autoair/simple")


