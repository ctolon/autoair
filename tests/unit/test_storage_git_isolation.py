def test_git_target_fails_closed_on_an_unreadable_state_record(
    remote: Path, tmp_path: Path, simple_spec_data: dict[str, Any]
) -> None:
    from autoair.storage import EjectedError, StorageError

    spec = DagSpec.model_validate(simple_spec_data)
    provider = LocalGitProvider(str(remote), tmp_path / "cache")
    target = GitTarget(provider, base_branch="main", mode="push")
    target.save(spec, {"simple.py": SRC})
    edited = SRC + "# edited by hand\n"
    head = provider.head("main")
    provider.commit_files(
        "main", head, {"simple.py": edited, ".autoair/state/simple.json": "{broken"}, "x", None
    )
    with pytest.raises(StorageError, match=r"state record .*simple\.json"):
        target.save(spec, {"simple.py": SRC2}, force=True)
    with pytest.raises(StorageError, match=r"state record .*simple\.json"):
        target.delete("simple")
    provider.commit_files(
        "main", provider.head("main"), {".autoair/state/simple.json": None}, "rm", None
    )
    with pytest.raises(EjectedError):
        target.save(spec, {"simple.py": SRC2})
    assert target.save(spec, {"simple.py": SRC2}, force=True).version
