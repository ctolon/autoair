SRC = '"""Generated by AutoAir"""\nprint("v1")\n'
SRC2 = '"""Generated by AutoAir"""\nprint("v2")\n'


def git(*args: str) -> str:
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout.strip()


@pytest.fixture
def remote(tmp_path: Path) -> Path:
    bare = tmp_path / "remote.git"
    git("init", "--bare", "-q", "-b", "main", str(bare))
    work = tmp_path / "seed"
    git("clone", "-q", str(bare), str(work))
    (work / "README.md").write_text("seed\n")
    git("-C", str(work), "add", ".")
    git("-C", str(work), "-c", "user.name=S", "-c", "user.email=s@x", "commit", "-q", "-m", "s")
    git("-C", str(work), "push", "-q", "origin", "HEAD:main")
    return bare


def _push_from_elsewhere(bare: Path, tmp: Path, branch: str, name: str) -> str:
    """Another writer (a second replica, a person) commits on ``branch``."""
    work = tmp / f"other-{name}"
    git("clone", "-q", "-b", branch, str(bare), str(work))
    (work / name).write_text("theirs\n")
    git("-C", str(work), "add", ".")
    git("-C", str(work), "-c", "user.name=O", "-c", "user.email=o@x", "commit", "-q", "-m", name)
    git("-C", str(work), "push", "-q", "origin", f"HEAD:{branch}")
    return git("--git-dir", str(bare), "rev-parse", branch)


