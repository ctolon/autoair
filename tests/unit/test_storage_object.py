from __future__ import annotations

import uuid

import fsspec
import pytest

from autoair.spec import DagSpec
from autoair.storage import (
    ConflictError,
    EjectedError,
    ObjectStorageTarget,
    StorageError,
    StorageSettings,
    build_target,
)

SRC = '"""Generated by AutoAir"""\nprint("v1")\n'
SRC2 = '"""Generated by AutoAir"""\nprint("v2")\n'


@pytest.fixture
def url():
    return f"memory://autoair-{uuid.uuid4().hex}/dags"


def test_roundtrip_on_memory_fs(url, simple_spec_data, tmp_path):
    target = build_target(
        StorageSettings(mode="object", object_url=url), default_local_path=tmp_path
    )
    assert isinstance(target, ObjectStorageTarget)
    spec = DagSpec.model_validate(simple_spec_data)
    first = target.save(spec, {"simple.py": SRC}, author="alice")
    assert first.path.startswith("memory://")
    assert first.path.endswith("/dags/simple.py")

    fs = fsspec.filesystem("memory")
    base = url.removeprefix("memory://")
    assert fs.cat_file(f"{base}/simple.py").decode() == SRC
    assert "simple.autoair.json" in [p.rsplit("/", 1)[-1] for p in fs.ls(base, detail=False)]

    stored = target.get("simple")
    assert stored is not None
    assert stored.spec == spec
    assert stored.etag == first.etag

    spec2 = spec.model_copy(update={"description": "two"})
    second = target.save(spec2, {"simple.py": SRC2}, base_etag=first.etag)
    with pytest.raises(ConflictError):
        target.save(spec, {"simple.py": SRC}, base_etag=first.etag)

    history = target.history("simple")
    assert [h.version for h in history] == [second.version, first.version]
    assert target.get_version("simple", first.version) == spec

    [summary] = target.list()
    assert summary.dag_id == "simple"
    assert summary.updated_at is not None
    assert target.status().details["protocol"] == "memory"

    assert target.delete("simple", base_etag=second.etag)
    assert target.get("simple") is None
    assert target.list() == []


def test_object_ownership_and_ejection(url, simple_spec_data):
    target = ObjectStorageTarget(url)
    spec = DagSpec.model_validate(simple_spec_data)
    fs = fsspec.filesystem("memory")
    base = url.removeprefix("memory://")
    fs.pipe_file(f"{base}/simple.py", b"# foreign\n")
    with pytest.raises(StorageError, match="not created by AutoAir"):
        target.save(spec, {"simple.py": SRC})
    fs.rm_file(f"{base}/simple.py")
    target.save(spec, {"simple.py": SRC})
    fs.pipe_file(f"{base}/simple.py", (SRC + "# edited\n").encode())
    with pytest.raises(EjectedError):
        target.save(spec, {"simple.py": SRC2})


def test_object_paths_cannot_escape(url):
    target = ObjectStorageTarget(url)
    with pytest.raises(StorageError):
        target.object_store.full("../x")
