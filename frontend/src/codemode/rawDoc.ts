import type { DagSpec } from "../api/gen/types.gen";

/** A minimal, valid Airflow 3 DAG file for a new raw code DAG. */
export function rawTemplate(dagId: string): string {
  return `"""${dagId}: a raw code DAG, deployed as written."""

from datetime import datetime

from airflow.sdk import DAG, task

with DAG(
    dag_id="${dagId}",
    schedule=None,
    start_date=datetime(2025, 1, 1),
    catchup=False,
):

    @task
    def hello() -> str:
        return "hello"

    hello()
`;
}

const GENERATED_HEADER =
  /^"""Generated by AutoAir from the visual DAG spec '([^'\n]*)'\.\n\nDo not edit by hand: changes are overwritten on the next deploy\.\nEdit the DAG in the AutoAir builder \(spec: [^\n]*\) instead\."""/;

/**
 * The generated file of a visual DAG as the start of a raw code DAG: the "do not edit"
 * docstring becomes a raw-code one (the rest of the code is kept as it is).
 */
export function ejectSource(code: string): string {
  return code.replace(
    GENERATED_HEADER,
    (_m, dagId: string) =>
      `"""Generated by AutoAir from the raw code DAG '${dagId}'.\n\nThis file is edited as code in AutoAir and deployed as written."""`,
  );
}

/**
 * A visual DAG turned into a raw code DAG: the metadata AutoAir lists and deploys with
 * (id, names, tags, team, environments) is kept; nodes, edges and the generated-code
 * settings are dropped (the code now carries them).
 */
export function ejectedSpec(spec: DagSpec, code: string): DagSpec {
  return {
    dag_id: spec.dag_id,
    ...(spec.display_name ? { display_name: spec.display_name } : {}),
    ...(spec.description ? { description: spec.description } : {}),
    ...(spec.tags?.length ? { tags: spec.tags } : {}),
    ...(spec.team ? { team: spec.team } : {}),
    ...(spec.environments && Object.keys(spec.environments).length ? { environments: spec.environments } : {}),
    output_mode: "python",
    nodes: [],
    edges: [],
    raw_code: ejectSource(code),
  };
}

const DAG_ID_PATTERNS = [/\bdag_id\s*=\s*["']([A-Za-z0-9_.-]{1,250})["']/, /\bDAG\(\s*["']([A-Za-z0-9_.-]{1,250})["']/];

/** The dag_id a DAG file declares literally, else one derived from `fallback` (a file name). */
export function guessDagId(source: string, fallback: string): string {
  for (const re of DAG_ID_PATTERNS) {
    const m = re.exec(source);
    if (m?.[1]) return m[1];
  }
  const stem = fallback
    .replace(/\.py$/, "")
    .replace(/[^A-Za-z0-9_.-]+/g, "_")
    .replace(/^[._-]+/, "");
  return stem || "raw_dag";
}
