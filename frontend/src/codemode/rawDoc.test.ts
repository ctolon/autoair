import { describe, expect, it } from "vitest";

import type { DagSpec } from "../api/gen/types.gen";
import { ejectSource, ejectedSpec, guessDagId, rawTemplate } from "./rawDoc";

const GENERATED = `"""Generated by AutoAir from the visual DAG spec 'etl'.

Do not edit by hand: changes are overwritten on the next deploy.
Edit the DAG in the AutoAir builder (spec: etl.autoair.json) instead."""

from airflow.sdk import DAG
`;

describe("raw code documents", () => {
  it("replaces the generated docstring when ejecting", () => {
    const out = ejectSource(GENERATED);
    expect(out).toContain("Generated by AutoAir from the raw code DAG 'etl'.");
    expect(out).not.toContain("Do not edit by hand");
    expect(out.endsWith("from airflow.sdk import DAG\n")).toBe(true);
    expect(ejectSource("x = 1\n")).toBe("x = 1\n");
  });

  it("keeps the metadata and drops the graph", () => {
    const spec = {
      dag_id: "etl",
      display_name: "ETL",
      tags: ["a"],
      team: "data",
      environments: { prod: {} },
      schedule: { type: "cron", expression: "0 * * * *" },
      nodes: [{ kind: "note", id: "n", text: "x" }],
      edges: [],
    } as unknown as DagSpec;
    const raw = ejectedSpec(spec, GENERATED);
    expect(raw).toMatchObject({ dag_id: "etl", display_name: "ETL", tags: ["a"], team: "data", nodes: [], edges: [] });
    expect(raw.environments).toEqual({ prod: {} });
    expect("schedule" in raw).toBe(false);
    expect(raw.raw_code).toContain("raw code DAG 'etl'");
  });

  it("guesses the dag_id of a file", () => {
    expect(guessDagId('with DAG(dag_id="sales", schedule=None):', "x.py")).toBe("sales");
    expect(guessDagId("DAG('orders')", "x.py")).toBe("orders");
    expect(guessDagId("print(1)", "my dag.py")).toBe("my_dag");
    expect(guessDagId("", ".py")).toBe("raw_dag");
  });

  it("starts new raw DAGs from a file defining their dag_id", () => {
    expect(rawTemplate("d1")).toContain('dag_id="d1"');
  });
});
