/** Two users co-edit the showcase DAG: Alice's window shows Bob's avatar, cursor and selection. */
async function collab({ page, context, browser, token, mode, shot }) {
  const { newPage } = await import("./lib.mjs");
  const join = async (p) => {
    await openApp(p, { dag: SHOWCASE });
    await hidePalette(p);
    await fitView(p);
    await p.getByRole("button", { name: "Collaborate" }).click();
    await p.getByRole("dialog").getByRole("button", { name: "Collaborate" }).click();
    await expect(p.getByTestId("collab-status")).toHaveAttribute("data-status", "connected", { timeout: 20_000 });
    await p.keyboard.press("Escape");
  };
  await context.addInitScript(() => localStorage.setItem("autoair.collab.name", "Alice Doe"));
  const bob = await newPage(browser, { mode, token, name: "Bob Roe" });
  try {
    await join(page);
    await join(bob.page);
    await expect(page.getByTestId("collab-peer")).toHaveText("BR", { timeout: 15_000 });
    await node(bob.page, "build_daily_sales").click();
    const box = await node(bob.page, "load_warehouse").boundingBox();
    await bob.page.mouse.move(box.x + box.width * 0.6, box.y + box.height + 40, { steps: 6 });
    await bob.page.mouse.move(box.x + box.width * 0.55, box.y + box.height + 22, { steps: 4 });
    await expect(page.getByTestId("collab-cursor")).toBeVisible({ timeout: 10_000 });
    await expect(page.getByTestId("collab-remote-selection")).toHaveCount(1, { timeout: 10_000 });
    await selectNode(page, "notify_team");
    await page.waitForTimeout(800);
    await shot("collab-presence");
  } finally {
    await bob.context.close();
  }
}

