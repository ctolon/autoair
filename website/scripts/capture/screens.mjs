/** Palette hidden: the canvas gets the room (Ctrl/⌘+B toggles it). */
async function hidePalette(page) {
  if (await page.getByPlaceholder(/Search operators/).isVisible()) {
    await page.getByRole("button", { name: /^Hide palette/ }).click();
    await page.waitForTimeout(300);
  }
}

async function bottomTab(page, name) {
  await page.getByRole("tab", { name: new RegExp(`^${name}`) }).first().click();
  await page.waitForTimeout(300);
}

async function selectNode(page, text) {
  await node(page, text).click();
  await page.waitForTimeout(400);
}

/** Scrolls the visible read-only code view so that the line containing `text` is on top. */
async function scrollCodeTo(page, text) {
  const view = page.locator(".cm-editor").filter({ hasText: "Generated by AutoAir" }).last();
  await view.waitFor({ timeout: 20_000 });
  await page.waitForTimeout(800);
  await view.evaluate((el, needle) => {
    const scroller = el.querySelector(".cm-scroller");
    const line = [...el.querySelectorAll(".cm-line")].find((l) => l.textContent?.includes(needle));
    if (scroller && line) scroller.scrollTop += line.getBoundingClientRect().top - scroller.getBoundingClientRect().top - 8;
  }, text);
  await page.waitForTimeout(300);
}

async function commandPalette(page, command) {
  await clickPane(page);
  await page.keyboard.press("ControlOrMeta+k");
  await page.keyboard.type(command);
  await page.waitForTimeout(300);
  await page.keyboard.press("Enter");
}

