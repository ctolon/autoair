/** Scrolls the inspector so that `locator` sits `offset` px below the inspector's top. */
async function inspectorScrollTo(page, locator, offset = 60) {
  await locator.first().evaluate((el, off) => {
    let p = el.parentElement;
    while (p && !(p.scrollHeight > p.clientHeight + 4 && getComputedStyle(p).overflowY !== "visible")) p = p.parentElement;
    if (p) p.scrollTop += el.getBoundingClientRect().top - p.getBoundingClientRect().top - off;
  }, offset);
  await page.waitForTimeout(300);
}

